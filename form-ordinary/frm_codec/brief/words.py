"""Слова досье формы для человека и модели: склонение, короткие имена элементов, замена внутренних терминов движка.

В досье не попадают ни номера позиций записи, ни имена операций и команд навыка, ни внутренние ключи, ни формулы правил привязок:
этот модуль переводит тексты линтера, диагностики привязок и пределов раскладки в слова о том, что видит пользователь и что при этом
происходит с формой. Исходные тексты остаются в числах фактов (`numbers`) — для машины.

* `plural(n, one, few, many)` — «1 знак», «2 знака», «5 знаков»;
* `Shortener(names)` — полное имя элемента (`Панель/Вложенная/Поле`) заменяется коротким, если короткое в форме одно;
* `plain_limit(text)` — предел раскладки без хвоста о том, как раскладка считается;
* `plain_design(text)`, `plain_lint(remark, ...)` — замечания линтера о смеси оформления;
* `JARGON` — образцы внутренних терминов; сторож по ним проверяет готовое досье.
"""
import re

# Образцы того, чего в досье быть не должно: тесты ищут их в тексте готового `brief.md`.
JARGON = (r"позици[июя] \d+", r"set_view", r"frm_json", r"normalize_guides", r"dependents_\w+", r"раскол ", r"встречн\w+ запис",
          r"правило на саму себя", r"правило на себя", r"\b[FS]\.[tblr][+-]\d+", r"#\d+\.[tblr][+-]\d+", r"элемент \d+ \(в форме",
          r"u\d+/", r"`[a-z_]+`", r"условие не выяснено", r"расчёт держит")

LIMIT_TAIL = re.compile(r"; граница идёт долей \(([\d.]+) роста окна\):.*$", re.S)


def plural(n, one, few, many):
    """Слово после числа `n`: «1 знак», «2 знака», «5 знаков», «11 знаков», «21 знак»."""
    n = abs(int(n))
    if n % 100 in (11, 12, 13, 14):
        return many
    return {1: one, 2: few, 3: few, 4: few}.get(n % 10, many)


def counted(n, one, few, many):
    return f"{n} {plural(n, one, few, many)}"


class Shortener:
    """Короткие имена элементов формы.

    `names` — `brief.facts._Names`. Элемент называется последним сегментом имени, если такое имя в форме одно (обращение модуля
    `ЭлементыФормы.<Имя>` тоже не знает панелей); у тёзок остаётся полное имя (у безымянных тёзок — с индексом)."""

    def __init__(self, names):
        self.names = names
        counts = {}
        for item in names.item_of.values():
            counts[item.label()] = counts.get(item.label(), 0) + 1
        self.counts = counts
        self.short_of = {}
        for full, item in names.item_of.items():
            self.short_of[full] = item.label() if counts[item.label()] == 1 else full
        long = sorted((n for n in self.short_of if "/" in n), key=len, reverse=True)
        self.pattern = re.compile(r"(?<![\w/#])(" + "|".join(re.escape(n) for n in long) + r")(?![\w/#])") if long else None

    def name(self, full):
        """Короткое имя элемента по полному (имя, которого в форме нет, остаётся как есть)."""
        return self.short_of.get(full, full)

    def text(self, text):
        """Текст, в котором полные имена элементов заменены короткими."""
        if not text or self.pattern is None:
            return text
        return self.pattern.sub(lambda m: self.short_of.get(m.group(1), m.group(1)), text)


def plain_limit(text):
    """Строка предела раскладки без объяснения того, как раскладка считает долю (она называет только, что предел приблизительный)."""
    found = LIMIT_TAIL.search(text)
    if found is None:
        return text
    return (text[:found.start()] + f"; граница идёт долей роста окна ({found.group(1)}): в предприятии раскладка у такого предела "
            "может остановиться раньше или идти дальше, поэтому предел приблизителен")


DESIGN_WORDS = {
    "смесь": "часть элементов формы оформлена в другом поколении платформы, чем остальные (8.2 и 8.3 вперемешку): такие элементы "
             "выглядят иначе соседей",
    "смесь у вложенных": "поля ввода в колонках таблиц оформлены в другом поколении платформы, чем сама форма: они выглядят иначе соседей",
    "раскол вида": "у полей ввода два вида оформления в одной форме (классический 8.2 и 8.3): меньшинство выглядит иначе соседей",
    "раскол позиции 16": "у полей ввода два вида оформления в одной форме (классический 8.2 и 8.3): меньшинство выглядит иначе соседей",
}


def plain_design(text):
    """Замечание линтера о смеси оформления словами; `None` — текст не из этого рода замечаний."""
    head = text.split(":", 1)[0].strip()
    for key, words in DESIGN_WORDS.items():
        if head == key or head.startswith(key + " ") or head.startswith(key + ":"):
            return words
    return None


def plain_guides(numbers):
    """Предупреждение о дальней направляющей края словами: где она и чем это грозит."""
    far = numbers.get("far") or []
    parts = []
    for row in far:
        edge = {3: "правая", 4: "нижняя"}.get(row.get("edge"), str(row.get("edge")))
        where = f"страница {row['page']}, " if row.get("page") else ""
        parts.append(f"{where}{edge} направляющая в {row['coord']} px (отступ от края формы {row['margin']} px)")
    return ("направляющие формы стоят не у края: " + "; ".join(parts) + ". В предприятии такая раскладка может «залипать» после "
            "растяжения окна: появляется полоса прокрутки, и при возврате размера форма не сжимается обратно") if parts else None


def plain_wide_page(row):
    """Страница панели шире видимой части панели — словами о том, что видит пользователь."""
    axes = " и ".join(f"{('по ширине', 'по высоте')[o['axis']]} на {o['px']} px" for o in row["over"])
    return (f"страница {row['page']} панели «{row['panel']}» шире видимой части панели {axes}: в предприятии вложенные элементы встают по правилам "
            f"от видимой области, а не от края страницы, как записано в файле, поэтому поля, привязанные вправо или вниз, при том же размере окна "
            f"уже или короче, чем нарисованы в файле ({row['by_guide']} из {row['total']} элементов страницы)")


def plain_narrow_page(row):
    """Страница панели уже (ниже) видимой части панели — словами о том, что видит пользователь."""
    axes = " и ".join(f"{('по ширине', 'по высоте')[o['axis']]} на {o['px']} px" for o in row["under"])
    return (f"страница {row['page']} панели «{row['panel']}» уже (ниже) видимой части панели {axes}: предприятие ставит элементы страницы "
            f"по правилам от видимой области, и поля, привязанные вправо или вниз, шире (длиннее), чем в файле "
            f"({row['by_guide']} из {row['total']} элементов записаны по правилам от края страницы)")


def plain_area_off(row):
    """Вложенные элементы панели, записанные не по своим правилам, — словами."""
    names = ", ".join(f"«{n}»" for n in row["items"]) + (f" и ещё {row['count'] - len(row['items'])}" if row["count"] > len(row["items"]) else "")
    return (f"у панели «{row['panel']}» {counted(row['count'], 'элемент записан', 'элемента записаны', 'элементов записаны')} не по своим правилам "
            f"({names}): по модели предприятие поставит их по правилам от видимой области, то есть иначе, чем в файле")


def plain_scroll_panel(row):
    """Панель, которая при сужении окна перестаёт сжимать страницу и прокручивается, — словами."""
    when = f"при ширине окна меньше {row['window']}" if row["axis"] == 0 and row["window"] is not None else (
        f"при высоте окна меньше {row['window']}" if row["window"] is not None else "уже в проектном размере")
    return (f"панель «{row['panel']}» {when} получает полосу прокрутки: поле «{row['item']}» дошло бы до минимума ({row['min']} px), "
            "и страница перестаёт сжиматься")


