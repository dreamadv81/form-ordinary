def _images_section(result):
    if result is None:
        return {"error": "картинки не построены"}
    section = {"format": result["format"], "scale": round(result["scale"], 2), "behavior_scale": round(result["behavior_scale"], 2),
               "note": result["note"], "not_drawn": result["not_drawn"], "code_notes": result.get("code_notes", []),
               "hidden_mode": result.get("hidden_mode", "hide"), "conditional_mode": result.get("conditional_mode", "plain"), "requested": result.get("requested", []),
               "behavior_frames": result.get("behavior_frames", []), "behavior_legend": result.get("behavior_legend", []), "behavior_why": result.get("behavior_why"),
               "conditional_same": result.get("conditional_same"), "code_pages": result.get("code_pages", [])}
    for key in ("clean", "marked", "behavior"):
        section[key] = pathlib.Path(result[key]).name
    return section


