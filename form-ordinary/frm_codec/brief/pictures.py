def _md_images(images):
    lines = ["## 8. Картинки", ""]
    if "error" in images:
        return lines + [images["error"], ""]
    lines.append(f"Формат: {images['format']}; масштаб форм {images['scale']} (clean, marked), полосы {images['behavior_scale']}; "
                 "длинная сторона не больше 1600 px.")
    if images["note"]:
        lines.append(images["note"])
    for key in ("clean", "marked", "behavior"):
        lines.append(f"- `{images[key]}` — {IMAGE_WORDS[key]}.")
    for note in images.get("code_notes") or []:
        lines.append(f"- {note[0].upper() + note[1:]}.")
    for row in images.get("code_pages") or []:
        if row.get("file"):
            lines.append(f"- `{row['file']}` — страница «{row['caption']}» панели «{row['panel'].split('/')[-1]}», которую меняет код ({row['why']}).")
    if images.get("behavior_why"):
        lines.append(f"- Кадры `{images['behavior']}`: {images['behavior_why']}.")
    elif images.get("behavior_frames"):
        lines.append("- На кадрах `" + images["behavior"] + "` подписан только размер окна. Кадры слева направо: " + "; ".join(images["behavior_frames"]) + ".")
        lines.append("- Значки на кадре «как в файле» (без значка: элемент остаётся на месте): " + "; ".join(images["behavior_legend"]) + ".")
    lines += ["", "Условности картинок (рисунок — каркас формы, а не снимок предприятия; их отличия от экрана не дефекты формы) — в `docs/brief.md`, «Условности картинок»."]
    return lines + [""]
