"""Виды полей карты формата. Они объявлены только здесь, а карта импортирует их отсюда и повторно экспортирует."""

INT, DEC, STR, GUID, B64 = "int", "dec", "str", "guid", "base64"
BOOL, ENUM, TYPE, NODE = "bool", "enum", "type", "node"
# Битовое слово: в файле это одно целое число, а в JSON — объект с именованными флагами и остатком.
BITS = "bits"
# Целое число, которое платформа записывает двумя способами: без хвостовых нулей — обычным целым (`28`), с хвостовыми нулями —
# экспонентой (`2e1`, `1.2e2`). Дробное число (`93.75`) этим видом не называется (`schema.fits_scalar`).
INT_EXP = "int-exp"
# Число, которое платформа записывает двумя способами: единицу (масштаб 100 %) — целым `1`, любое другое — десятичной дробью
# одинарной точности (`3.730000019073486` для 373 %). Так записан масштаб поля картинки.
INT_DEC = "int-dec"
