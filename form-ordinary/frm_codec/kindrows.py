def _custom_colors(kind, body):
    """Число цветов произвольной палитры в теле, если тело именно такой длины (платформа вставляет цвета сразу за позицией числа); иначе 0."""
    try:
        if kind == PIVOT:
            count, base = body[303], PIVOT_LENGTH
        else:
            events, pair = chartrows.shape(body)
            count, base = body[163 + events + pair], chartrows.BASE_LENGTH + events + pair
    except (IndexError, TypeError, ValueError, KeyError):
        return 0
    if isinstance(count, int) and not isinstance(count, bool) and count > 0 and len(body) == base + count:
        return count
    return 0


def refusal(kind, node):
    """Слова отказа, если запись вне области определения; `None` — читается и пишется."""
    body = diagrams.body(node)
    if body is None:
        return "тело диаграммы не разобрано"
    if body[0] != VERSION:
        return (f"тело записано версией {body[0]}, а строки палитры названы по записи версии {VERSION} (платформа 8.3.27); "
                "в записях старых версий (64, 65) позиции другие")
    custom = _custom_colors(kind, body)
    if custom:
        return (f"в теле произвольная палитра цветов из {custom}: за позицией её числа (163 у диаграммы Ганта и дендрограммы, 303 у сводной) стоят сами цвета, тело длиннее на их число, "
                "и позиции строк за ней сдвинуты; такую запись редактор по строкам палитры не правит")
    if kind == PIVOT:
        if len(body) != PIVOT_LENGTH or body[:5] != PIVOT_HEAD:
            return (f"тело сводной диаграммы — {len(body)} позиций с заголовком {body[:5]}, а адреса названы для тела шаблона: {PIVOT_LENGTH} позиций, "
                    f"четыре серии и четыре точки ({PIVOT_HEAD}); при другом числе серий и точек платформа добавляет блоки по 11 позиций и позиции строк сдвигаются")
        return None
    return chartrows.refusal(body)


def _require(kind, node):
    why = refusal(kind, node)
    if why is not None:
        raise EditError(why)


def _holder(node, row):
    """`(контейнер, ключ)` значения строки в узле; отказ словами, если блока содержимого такой формы нет."""
    try:
        if row.where == "content":
            holder, key = node["content"], row.at[0]
            steps = row.at[1:]
        else:
            body = diagrams.body(node)
            at = row.at[1]
            if node.get("type") == PIVOT:
                holder, key = body, at
            else:
                holder, key = body, chartrows._actual(body, at)
            steps = row.at[2:]
        for step in steps:
            holder, key = holder[key], step
        holder[key]
        return holder, key
    except (KeyError, IndexError, TypeError):
        raise EditError(f"в записи нет места строки {row.label!r} ({_address(row)}): блок содержимого другой формы, чем у платформы 8.3.27") from None


