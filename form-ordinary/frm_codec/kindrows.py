@dataclasses.dataclass(frozen=True)
class KRow(chartrows.Row):
    where: str = "body"       # body — тело записи, content — блок содержимого узла
    mirror: str = ""          # слова о втором месте значения, которое ведёт операция


def _shared(name, at, seen=None, note=None, codes=None, default=None, proof="pair", mirror=""):
    """Строка тела записи, общая с диаграммой `Chart`: значение и вид — те же, адрес — свой."""
    base = chartrows.BASE_BY_NAME[name]       # первая таблица диаграммы: значения перебора диаграммы `Chart` на другие виды не переносятся
    return KRow(name=name, group=base.group, label=base.label, kind=base.kind, at=at, proof=proof,
                codes=base.codes if codes is None else codes, seen=base.seen if seen is None else tuple(seen),
                default=base.default if default is None else default, note=base.note if note is None else note, mirror=mirror)


def _content(name, group, label, kind, at, codes=None, seen=(), default=None, note="", refuse="", proof="pair"):
    return KRow(name=name, group=group, label=label, kind=kind, at=tuple(at), proof=proof, codes=codes, seen=tuple(seen), default=default, note=note,
                refuse=refuse, where="content")


def _flag(name, group, label, at, note="", proof="pair"):
    return _content(name, group, label, "flag", at, note=note, proof=proof)


def _enum(name, group, label, at, codes, note="", seen=None):
    return _content(name, group, label, "enum", at, codes=codes, seen=tuple(codes) if seen is None else seen, note=note)


def _body(name, group, label, kind, at, codes=None, seen=(), default=None, note="", refuse="", proof="pair"):
    return KRow(name=name, group=group, label=label, kind=kind, at=tuple(at), proof=proof, codes=codes, seen=tuple(seen), default=default, note=note, refuse=refuse)


