_HOTKEY = re.compile(r"\s*\([^()]*\)\s*$")


def key_of(name):
    """Ключ таблицы по названию действия или подсказке: без горячей клавиши в скобках («Добавить (Ins)» → «добавить») и без многоточия."""
    text = _HOTKEY.sub("", " ".join((name or "").split())).rstrip("…").strip().lower().replace("ё", "е")
    return text


_KEYS = {key_of(name): picture for name, picture in ACTION_PICTURES.items()}


def known(name):
    """Для названия действия есть значок."""
    return key_of(name) in _KEYS


def picture_of(name):
    """Имя картинки библиотеки для названия действия либо `None`."""
    return _KEYS.get(key_of(name))


def draw(x, y, name):
    """Значок действия `name` с левым верхним углом (x, y): `<image class='icon action-icon'>` 16×16 с подсказкой; `None` — таблица названия не знает."""
    picture = picture_of(name)
    bitmap = platform_pictures.bitmap(picture) if picture else None
    if bitmap is None:
        return None
    return picture_bitmap.image_tag(x, y, bitmap, 16, " ".join((name or "").split()), "icon action-icon")
