def _border_raw(row, value, unverified, current=None):
    if isinstance(value, dict):
        if set(value) - {"border_type", "explicit"} or "border_type" not in value:
            raise EditError(f"{row.name} ({row.label}): рамка — слово палитры либо объект с border_type и explicit, а пришло {value!r}")
        label, explicit = value["border_type"], value.get("explicit")
    else:
        label, explicit = value, None
    label = BORDER_ENGLISH.get(label, label)
    if label not in BORDER_CODES:
        raise EditError(f"{row.name} ({row.label}): рамка — {', '.join(BORDER_CODES)}, а пришло {value!r}")
    if label not in row.seen and not unverified:
        raise EditError(_unseen(row, f"«{label}»", BORDER_CODES[label]))
    # Признак «задана явно»: у записанных платформой значений — как у неё; у прочих выбор рамки в диалоге ставит 1.
    if label == "Нет рамки" and row.after_edit:
        # «Нет рамки» поверх «Нет рамки» блок не меняет; поверх другой рамки платформа пишет (0, 1).
        pair = (current[3], current[4]) if current[3] == 0 else (0, 1)
    else:
        pair = (1, 1) if label == "Одинарная" else (0, 1) if (row.name == "labels_border" and label == "Нет рамки") else \
            (0, 0) if (row.name == "border" and label == "Нет рамки") else (BORDER_CODES[label], 1)
    raw = copy.deepcopy(row.default)
    raw[3], raw[4] = pair
    if explicit is not None:
        if explicit != bool(pair[1]) and not unverified:
            raise EditError(f"{row.name} ({row.label}): у «{label}» платформа пишет признак explicit = {bool(pair[1])}, а пришло {explicit!r}; под unverified — как задано")
        raw[4] = int(explicit)
    return raw


