def refusal(body):
    """Слова отказа, если тело вне области определения; `None` — тело читается и пишется."""
    if not isinstance(body, list) or not body:
        return "тело диаграммы не разобрано"
    if body[0] != VERSION:
        return (f"тело диаграммы записано версией {body[0]}, а строки палитры названы по записи версии {VERSION} (платформа 8.3.27); "
                "в записи версии 64, которую несут формы старых конфигураций, позиции другие")
    if len(body) < 18:
        return "тело диаграммы короче базовой формы"
    if body[3] != 1:
        return ("«Настройка серий» выключена: тело без блока серии «Сводная» и без записи серии короче на 12 позиций, и позиции строк другие; "
                "такую диаграмму редактор по строкам палитры не правит")
    if body[2] != 0 or body[4] != 0:
        return (f"в диаграмме серий {body[4]} и точек {body[2]}: блоки серий и точек стоят в теле по 11 позиций, а за ними сдвигаются все позиции; "
                f"длина такого тела {expected_length(body[4], body[2])} (214 + 13·серий + 12·точек + 4·серий·точек), позиции строк для него не названы")
    if body[EVENTS_FLAG] not in (0, 1):
        return f"позиция {EVENTS_FLAG} («есть обработчики») — {body[EVENTS_FLAG]!r}, а платформа пишет 0 или 1"
    events = body[EVENTS_FLAG]
    flag = body[SERIES_FLAG + events] if len(body) > SERIES_FLAG + events else None
    if flag not in (0, 1):
        return f"позиция {SERIES_FLAG} («у серии есть настройки показа») — {flag!r}, а платформа пишет 0 или 1"
    if len(body) != BASE_LENGTH + events + flag:
        return (f"длина тела {len(body)}, а у базовой формы с флагами строения {events} и {flag} она равна {BASE_LENGTH + events + flag}: "
                "в теле есть вставка, которой карта не знает")
    return None


def expected_length(series, points):
    """Длина тела с `series` сериями и `points` точками при выключенных флагах строения («есть обработчики», «настройки показа серии»)."""
    return BASE_LENGTH + 13 * series + 12 * points + 4 * series * points


def shape(body):
    """`(есть обработчики, есть пара показа)` — флаги строения базовой формы."""
    events = body[EVENTS_FLAG]
    return events, body[SERIES_FLAG + events]


def _actual(body, at):
    """Живой индекс позиции базовой формы."""
    events, pair = shape(body)
    return at + (events if at >= EVENTS_LIST_AT else 0) + (pair if at >= SERIES_PAIR_AT else 0)


def _holder(body, row):
    """`(контейнер, ключ)` значения строки в живом теле; `None`, если значения нет (пары показа ещё нет)."""
    if row.at[0] == PAIR:
        events, flag = shape(body)
        return (body[SERIES_PAIR_AT + events], row.at[1]) if flag else None
    holder, key = body, _actual(body, row.at[0])
    for step in row.at[1:]:
        holder, key = holder[key], step
    return holder, key


def _require(body):
    why = refusal(body)
    if why is not None:
        raise EditError(why)


def _row(name):
    row = BY_NAME.get(name)
    if row is None:
        raise EditError(f"у диаграммы такой строки палитры нет: {name!r}; есть {', '.join(NAMES)}")
    return row


# ── Значения ──────────────────────────────────────────────────────────────────────────────────────

def rgb_code(rgb):
    """Код цвета: красный — младший байт."""
    return rgb[0] + 256 * rgb[1] + 65536 * rgb[2]


def _color_value(raw):
    if isinstance(raw, list) and len(raw) == 3 and raw[0] == 3 and isinstance(raw[2], list) and raw[2]:
        kind, code = raw[1], raw[2][0]
        if kind == 0 and isinstance(code, int):
            return "#%02X%02X%02X" % (code & 255, (code >> 8) & 255, (code >> 16) & 255)
        if kind == 4:
            return "Авто"
        return {"color_kind": kind, "code": code}
    return raw


def _parse_color(value, row):
    """Блок цвета по значению: `#RRGGBB`, `[r, g, b]`, `{"rgb": [r, g, b]}`, `Авто` или `по умолчанию`."""
    if isinstance(value, dict) and set(value) == {"rgb"}:
        value = value["rgb"]
    if isinstance(value, str):
        text = value.strip()
        if text.lower() in ("по умолчанию", "default"):
            return copy.deepcopy(row.default)
        if text == "Авто":
            return [3, 4, [0]]
        found = re.fullmatch(r"#?([0-9A-Fa-f]{6})", text)
        if found:
            number = int(found.group(1), 16)
            return [3, 0, [rgb_code((number >> 16 & 255, number >> 8 & 255, number & 255))]]
    if isinstance(value, (list, tuple)) and len(value) == 3 and all(isinstance(n, int) and not isinstance(n, bool) and 0 <= n <= 255 for n in value):
        return [3, 0, [rgb_code(value)]]
    raise EditError(f"{row.name}: цвет — `#RRGGBB`, список [r, g, b], `Авто` или `по умолчанию`, а пришло {value!r}")


def _font_value(raw):
    if isinstance(raw, list) and raw == [7, 3, 0, 1, 100]:
        return "Авто"
    if isinstance(raw, list) and len(raw) >= 17 and raw[0] == 7 and raw[1] == 0:
        size = raw[3] / 10
        shown = {"name": raw[16], "size": int(size) if size == int(size) else size}
        if raw[7] == 700:
            shown["bold"] = True
        return shown
    return raw


def _font_raw(value, row):
    """Запись шрифта и признак «такой писала платформа»: `Авто` либо абсолютный шрифт `{"name": …, "size": …}`."""
    if value == "Авто":
        return copy.deepcopy(row.default), True
    if row.faces:
        return _face_raw(value, row), True
    if not isinstance(value, dict) or set(value) != {"name", "size"}:
        raise EditError(f"{row.name}: шрифт — `Авто` или объект {{\"name\": имя, \"size\": пункты}} (другие свойства шрифта у диаграммы не пишутся), а пришло {value!r}")
    name, size = value["name"], value["size"]
    if not isinstance(name, str) or not name or isinstance(size, bool) or not isinstance(size, (int, float)) or size <= 0:
        raise EditError(f"{row.name}: имя шрифта — строка, размер — положительное число, а пришло {value!r}")
    if size * 10 != int(size * 10):
        raise EditError(f"{row.name}: размер шрифта задаётся с точностью до десятой доли пункта, а пришло {size}")
    return [7, 0, 0, int(size * 10), 0, 0, 0, 400, 0, 0, 0, 1, 3, 2, 1, 34, name, 1, 100], (name, int(size * 10)) == ("Arial", 170)


FACES_WRITTEN = ("Arial", "Tahoma")      # гарнитуры, которые платформа записывала у диаграммы; запись остальных гарнитур таблицы — как у шрифтов других элементов


def _face_raw(value, row):
    """Абсолютный шрифт по гарнитуре из таблицы гарнитур диалога «Выбор шрифта»: `{"name": …, "size": …[, "bold": true]}`."""
    if not isinstance(value, dict) or not {"name", "size"} <= set(value) or set(value) - {"name", "size", "bold"}:
        raise EditError(f"{row.name}: шрифт — `Авто` или объект {{\"name\": имя, \"size\": пункты[, \"bold\": true]}} (наклон, подчёркивание и зачёркивание у диаграммы "
                        f"не пишутся), а пришло {value!r}")
    name, size, bold = value["name"], value["size"], value.get("bold", False)
    if not isinstance(name, str) or not name or isinstance(size, bool) or not isinstance(size, (int, float)) or size <= 0:
        raise EditError(f"{row.name}: имя шрифта — строка, размер — положительное число, а пришло {value!r}")
    if not isinstance(bold, bool):
        raise EditError(f"{row.name}: `bold` — true или false, а пришло {bold!r}")
    if abs(size * 10 - round(size * 10)) > 1e-9:
        raise EditError(f"{row.name}: размер шрифта задаётся с точностью до десятой доли пункта, а пришло {size}")
    if name not in FACES:
        raise EditError(f"{row.name}: шаг и семейство гарнитуры {name!r} не известны, платформа писала их для {', '.join(FACES)}. Другую гарнитуру задайте правкой JSON по адресу шрифта")
    return [7, 0, 0, round(size * 10), 0, 0, 0, 700 if bold else 400, 0, 0, 0, 1, FACE_PRECISION.get(name, 3), 2, 1, FACES[name], name, 1, 100]


def _ls_value(raw):
    if isinstance(raw, list) and raw[:2] == [1, 0]:
        return ""
    if isinstance(raw, list) and len(raw) == 3 and raw[:2] == [1, 1] and isinstance(raw[2], list) and len(raw[2]) == 2:
        return raw[2][1]
    return raw


def _ls_raw(text):
    return [1, 0] if text == "" else [1, 1, [LANG, text]]


NUMBER_DIGITS = 15       # значащих цифр: дальше запись числа платформой не проверялась


def _number_value(raw):
    """Число из записи: целое — как есть, строка с точкой — дробным числом."""
    if isinstance(raw, str) and re.fullmatch(r"-?[0-9]+\.[0-9]+", raw):
        return float(raw)
    return raw


def _number_raw(value, row):
    """Запись числа: целое пишется целым, дробное — строкой с точкой без хвостовых нулей (`1.5`), как платформа пишет значение, введённое с запятой."""
    if isinstance(value, bool) or not isinstance(value, (int, float, str)):
        raise EditError(f"{row.name} ({row.label}): число — целое, дробное (1.5) или строка вида `1,5`, а пришло {value!r}")
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")) or "e" in repr(value):
            raise EditError(f"{row.name} ({row.label}): запись очень большого или очень малого числа {value!r} платформой не проверялась")
        text = repr(value)
    elif isinstance(value, str):
        text = value.strip().replace(",", ".")
        if not re.fullmatch(r"-?[0-9]+(\.[0-9]+)?", text):
            raise EditError(f"{row.name} ({row.label}): число — цифры с необязательной дробной частью через запятую или точку (без порядка и пробелов), а пришло {value!r}")
    else:
        text = str(value)
    digits = len(text.lstrip("-").replace(".", "").lstrip("0")) or 1
    if digits > NUMBER_DIGITS:
        raise EditError(f"{row.name} ({row.label}): {value!r} длиннее {NUMBER_DIGITS} значащих цифр, такую запись платформа не проверялась")
    number = Decimal(text)
    if number == number.to_integral_value():
        return int(number)
    shown = format(number.normalize(), "f")
    return shown


def _label(row, code):
    for label, known in (row.codes or {}).items():
        if known == code:
            return label
    return code


def _border_value(raw, row):
    if isinstance(raw, list) and len(raw) == 7 and raw[0] == 3:
        return {"border_type": _label(row, raw[3]), "explicit": bool(raw[4])}
    return raw


def _pretty(raw, row):
    """Значение строки в читаемом виде по сырой записи."""
    kind = row.kind
    if kind == "flag":
        return bool(raw) if raw in (0, 1) else raw
    if kind in ("enum", "palette", "pair"):
        return _label(row, raw)
    if kind == "ls":
        return _ls_value(raw)
    if kind == "number":
        return _number_value(raw)
    if kind == "color":
        return _color_value(raw)
    if kind == "font":
        return _font_value(raw)
    if kind == "border":
        return _border_value(raw, row)
    if kind == "line":
        return _label(row, raw[3]) if isinstance(raw, list) and len(raw) > 3 else raw
    return raw


def read(body, name):
    """Значение строки в читаемом виде; вне области определения — отказ словами."""
    row = _row(name)
    _require(body)
    found = _holder(body, row)
    if found is None:
        return "Авто" if row.kind == "pair" else None
    holder, key = found
    return _pretty(holder[key], row)


def _shown(value):
    if isinstance(value, bool):
        return "☑" if value else "☐"
    return value if isinstance(value, str) else repr(value)


# ── Запись ────────────────────────────────────────────────────────────────────────────────────────

def _unseen(row, shown, code):
    return (f"{row.name} ({row.label}) = {shown}: код {code} известен по списку или по другому виду, а эту строку платформа с таким значением не записывает; "
            "позвать всё же можно — unverified=True, — и тогда результат проверяете вы")


def _code_of(row, value, unverified):
    """Код списка по слову палитры; число — только под `unverified`; слово с известным, но не записанным платформой кодом — тоже."""
    codes = row.codes or {}
    if isinstance(value, str) and value in codes:
        if value not in row.seen and not unverified:
            raise EditError(_unseen(row, f"«{value}»", codes[value]))
        return codes[value]
    known = ", ".join(f"«{label}» ({code})" for label, code in codes.items())
    if isinstance(value, bool) or not isinstance(value, int):
        raise EditError(f"{row.name} ({row.label}): значение — слово палитры ({known}) или число кода под `unverified`, а пришло {value!r}. "
                        "Коды остальных слов списка неизвестны")
    if not unverified:
        raise EditError(f"{row.name} ({row.label}): число кода записывается только под `unverified`; слово палитры называют из {', '.join(codes)}")
    return value


def write(doc, element, name, value, unverified=False):
    """Строка палитры диаграммы по имени (`set_property`); `None`, если элемент не диаграмма вида `Chart` или имя не из строк."""
    if name not in BY_NAME:
        return None
    place = find_element(doc, element)
    if place.element.get("type") != "Chart":
        return None
    row = BY_NAME[name]
    body = diagrams.body(place.element)
    where = f"{name} у {element!r} (Chart): {row.label}"
    if row.refuse:
        raise EditError(f"{where} — {row.refuse} Адрес: `{_address(row)}`.")
    if row.kind == "address":
        raise EditError(f"{where} — запись лежит списком, строение которого собирают диалоги палитры; редактор её не строит. Адрес: `{_address(row)}`. {row.note}")
    _require(body)
    if row.kind == "pair":
        return _put_pair(body, row, value, unverified, element)
    holder, key = _holder(body, row)
    before = _pretty(copy.deepcopy(holder[key]), row)
    words = _put(body, row, holder, key, value, unverified)
    after = read(body, name)
    said = f"диаграмма {element!r}: {row.label} ({row.group}) {_shown(before)} → {_shown(after)}; позиция {_address(row)}"
    return said + (f"; {words}" if words else "")


def _put_pair(body, row, value, unverified, element):
    code = _code_of(row, value, unverified)
    events, flag = shape(body)
    words = ""
    if not flag:
        body[SERIES_FLAG + events] = 1
        body[SERIES_FLAG + 1 + events] = [0, 1, 0]
        body.insert(SERIES_PAIR_AT + events, [0, 0])
        words = (f"заведена пара показа: позиция {SERIES_FLAG} → 1, список позиции {SERIES_FLAG + 1} — `[0, 1, 0]`, пара `[0, 0]` перед позицией {SERIES_PAIR_AT}, "
                 "как её заводит платформа")
    pair = body[SERIES_PAIR_AT + events]
    before, pair[row.at[1]] = pair[row.at[1]], code
    return (f"диаграмма {element!r}: {row.label} ({row.group}) {_label(row, before)} → {_label(row, code)}; позиция {_address(row)}"
            + (f"; {words}" if words else ""))


def _put(body, row, holder, key, value, unverified):
    kind = row.kind
    if kind == "flag":
        if isinstance(value, bool):
            new = int(value)
        elif isinstance(value, int) and value in (0, 1) and unverified:
            new = value
        else:
            raise EditError(f"{row.name} ({row.label}): флажок — true или false, а пришло {value!r}")
        holder[key] = new
        return _cowrite_flag(body, row, new)
    if kind == "enum":
        holder[key] = _code_of(row, value, unverified)
        return _cowrite_type(body, holder[key]) if row.name == "chart_type" else ""
    if kind == "int":
        if isinstance(value, bool) or not isinstance(value, int):
            raise EditError(f"{row.name} ({row.label}): платформа записывает число целым, а пришло {value!r}")
        if row.limits and not row.limits[0] <= value <= row.limits[1]:
            raise EditError(f"{row.name} ({row.label}): платформа записывала целое 45; пределы поля палитры не сняты, редактор принимает целые от {row.limits[0]} до "
                            f"{row.limits[1]} (процент), а пришло {value}")
        holder[key] = value
        if row.name == "max_series_percent" and body[_actual(body, 63)] != MAX_SERIES_PERCENT_MODE:
            return ("палитра покажет строку только при «МаксимумСерий» = «Процент»; хранит ли платформа значение при другом способе, не проверялось")
        return ""
    if kind == "number":
        raw = _number_raw(value, row)
        holder[key] = raw
        if row.name == "axis_base":
            at = _actual(body, 67)
            before, body[at] = body[at], raw
            return f"то же в позиции 67 ({before} → {raw}): базовое значение оси значений лежит дважды, как его и записывает платформа"
        return ""
    if kind == "text":
        if not isinstance(value, str):
            raise EditError(f"{row.name} ({row.label}): текст — строка, а пришло {value!r}")
        holder[key] = value
        return ""
    if kind == "ls":
        if not isinstance(value, str):
            raise EditError(f"{row.name} ({row.label}): текст — строка (формат вида «ЧДЦ=1» платформа принимает текстом), а пришло {value!r}")
        holder[key] = _ls_raw(value)
        if row.name == "series_text":
            at = _actual(body, 9)
            before, body[at] = body[at], 1
            return f"позиция 9 {before} → 1: так платформа отмечает текст серии, введённый вручную" if before != 1 else ""
        return ""
    if kind == "color":
        holder[key] = _parse_color(value, row)
        return _cowrite_color(body, row, holder[key])
    if kind == "border":
        holder[key] = _border_raw(row, value, unverified, holder[key])
        return ""
    if kind == "palette":
        holder[key] = _code_of(row, value, unverified)
        if row.name == "color_palette":
            second = body[_actual(body, 196)]
            before, second[1] = second[1], holder[key]
            return f"то же в записи позиции 196 ({before} → {holder[key]})"
        return ""
    if kind == "font":
        raw, written = _font_raw(value, row)
        if not written and not unverified:
            raise EditError(f"{row.name} ({row.label}): платформа записывала шрифт Arial 17, кроме него и `Авто` — только под unverified: у других шрифтов "
                            "набор символов и семейство в записи другие")
        holder[key] = raw
        if row.faces and raw != row.default and raw[16] not in FACES_WRITTEN:
            return (f"гарнитура {raw[16]!r}: у диаграммы платформа писала {' и '.join(FACES_WRITTEN)}, запись этой гарнитуры взята из таблицы гарнитур шрифтов других элементов "
                    f"(шаг и семейство {raw[15]})")
        return ""
    if kind == "line":
        code = _code_of(row, value, unverified)
        holder[key][3] = code
        holder[key][4] = 1 if code == 0 else 2
        return f"толщина линии {holder[key][4]} (у «Нет линии» платформа пишет 1, у остальных стилей 2)"
    raise EditError(f"{row.name}: вид {kind} не пишется")


def _cowrite_flag(body, row, new):
    if row.name == "points_settings":
        at = _actual(body, 7)
        before, body[at] = body[at], new
        return f"позиция 7 {before} → {new}: так платформа ведёт эту запись вместе с «Настройкой точек»" if before != new else ""
    return ""


def _cowrite_type(body, code):
    """Расчётный цвет серии «Сводная» (позиция 5) при смене типа: 8874375 у линейных типов, 11837108 у остальных. Серия должна быть в базовом состоянии: цвет — расчётный
    (не заданный рукой), «Индикатор» выключен, тип графического представления «Авто»; при другом состоянии платформа цвет считает иначе (при включённом «Индикаторе» у «Гистограммы» он 8874375) — тогда не трогаем."""
    at = _actual(body, 5)
    color = body[at]
    computed = tuple(SERIES_COMPUTED_COLORS.values())
    if not (isinstance(color, list) and len(color) == 3 and color[1] == 0 and isinstance(color[2], list) and color[2] and color[2][0] in computed):
        return "цвет серии «Сводная» (позиция 5) задан не расчётным значением и не переписан"
    if body[_actual(body, 11)] != 0 or body[_actual(body, 164)][3] != 0:
        return "цвет серии «Сводная» (позиция 5) не переписан: у серии включён «Индикатор» или задан тип графического представления, платформа считает цвет иначе"
