def humanize(name):
    """Описание обработчика, как его пишет платформа: подчёркивание — пробел (`Обр_1` → `Обр 1`), слова по заглавным буквам."""
    words = re.sub(r"(?<=[а-яa-z0-9])(?=[А-ЯA-Z])", " ", name.replace("_", " ")).split(" ")
    return " ".join([words[0]] + [w[:1].lower() + w[1:] for w in words[1:]])


def _handler(code, procedure, text):
    shown = text if text is not None else humanize(procedure)
    description = [1, 1, [LANG, shown]]
    return [code, {"guid": EVENT_MARK},
            [3, procedure, [1, procedure, description, copy.deepcopy(description), copy.deepcopy(description), [4, 0, [0], "", -1, -1, 1, 0, ""], [0, 0, 0]]]]


def _params(event):
    return f"; параметры процедуры в модуле (так создаёт её платформа): {', '.join(EVENT_PARAMS[event])}"


def set_event(doc, element, event, procedure, text=None):
    """Обработчик события диаграммы: запись в списке обработчиков тела на место по коду. `None`, если элемент не диаграмма вида `Chart`."""
    place = find_element(doc, element)
    if place.element.get("type") != "Chart":
        return None
    code = EVENT_CODES.get(event)
    if code is None:
        raise EditError(f"у диаграммы {element!r} события {event!r} нет: четыре события палитры — {', '.join(EVENT_CODES)} (имя русское, как в палитре)")
    if not isinstance(procedure, str) or not procedure:
        raise EditError(f"set_event у {element!r}: имя процедуры — непустая строка, а пришло {procedure!r}")
    body = diagrams.body(place.element)
    _require(body)
    return put_handler(body, "диаграмма", element, event, code, procedure, text, _params(event))


def put_handler(body, what, element, event, code, procedure, text, params):
    """Запись обработчика в список тела (позиции 112 и 113) на место по коду; общая у диаграммы, диаграммы Ганта и дендрограммы. Возвращает слова отчёта."""
    record = _handler(code, procedure, text)
    if body[EVENTS_FLAG] == 0:
        body[EVENTS_FLAG] = 1
        body.insert(EVENTS_LIST_AT, [1, record])
        return (f"{what} {element!r}: событие {event} (код {code}) → процедура {procedure!r}; список обработчиков заведён "
                f"(позиция {EVENTS_FLAG} → 1, список на позиции {EVENTS_LIST_AT}){params}")
    block = body[EVENTS_LIST_AT]
    items = block[1:]
    if not isinstance(block, list) or len(items) != block[0]:
        raise EditError(f"список обработчиков {what} {element!r} не сходится со своим счётчиком — он не разобран")
    for at, item in enumerate(items):
        if item[0] == code:
            was = item[2][1]
            block[1 + at] = record
            return f"{what} {element!r}: событие {event} (код {code}) → процедура {procedure!r} (замена, была {was!r}){params}"
    block.insert(1 + next((at for at, item in enumerate(items) if item[0] > code), len(items)), record)
    block[0] += 1
    return f"{what} {element!r}: событие {event} (код {code}) → процедура {procedure!r}; запись встала по коду, обработчиков {block[0]}{params}"


