"""Правила сетки рядов, общие для `describe` (форма → блоки описания) и `structure` (форма → дерево структуры).

Два правила, взятые из `describe`: куски (`joined`) и блоки (`runs`). Своего второго экземпляра они не имеют: `structure`
вызывает эти функции, а не повторяет их, иначе обратный ход «описание → форма → структура» разошёлся бы с прямым.

* **Кусок.** Таблица, рамка, панель или панель команд, лежащая между двумя рядами, рвёт сетку: блок через неё не идёт.
  `joined(верх_предыдущего, верх_ряда, верхи_разделителей)` — ряд продолжает кусок предыдущего ряда, если верх ни одного
  разделителя не лежит строго ниже верха предыдущего ряда и не ниже верха этого.
* **Блок.** Подряд идущие ряды с одним числом пар — один блок. Одиночный ряд после рядов из нескольких пар — свой блок на одну
  колонку.
"""


def joined(prev_top, top, separators):
    """Ряд с верхом `top` продолжает кусок, в котором предыдущий ряд имел верх `prev_top`; `separators` — верхи разделителей."""
    return not any(prev_top < sep <= top for sep in separators)


def runs(rows):
    """Ряды одного куска → блоки `[{"n": число пар в ряду, "rows": [ряды]}]`; ряд — перечень пар (ячеек)."""
    out = []
    for row in rows:
        if out and out[-1]["n"] == len(row):
            out[-1]["rows"].append(row)
        else:
            out.append({"n": len(row), "rows": [row]})
    return out
