def append_procedure(text, name, params=(), body=(), unverified=False):
    """Дописывает процедуру в конец `form.bsl`. Принимает и возвращает байты.

    Работа идёт с байтами, а не со строкой, чтобы сохранить BOM и перевод строк файла (CRLF, если он есть в
    файле, иначе LF): платформа читает модуль как есть. Процедура добавляется через пустую строку, а переводы
    строк в конце исходного файла нормализуются.

    Имя проверяется до изменения модуля (`procedure_name_refusal`). Оно подставляется в `Процедура Имя(` как
    есть, и модуль с неправильным именем или с зарезервированным словом не скомпилируется, а сообщит об этом
    платформа только человеку в конфигураторе. Вот что считается отказом:
    * литерал (`Истина`, `Ложь`, `Неопределено`, `NULL`) и слово объявления (`Экспорт`, `Знач`): «не
      скомпилируется: Ожидается имя процедуры» (`KEYWORD_NAMES`);
    * имя метода глобального контекста: «не скомпилируется: … уже определена» (`GLOBAL_METHODS`);
    * имя свойства глобального контекста (`GLOBAL_PROPERTIES`) — по-разному. `Метаданные` / `Metadata`: «уже
      определена». `Константы`, `ПараметрыСеанса`, `Справочники`, `Документы`, `Перечисления`, `РегистрыСведений`,
      `ПользователиИнформационнойБазы`, `ХранилищаНастроек` и английские написания этих пар годятся (модуль
      компилируется). Остальные 91 имя не проверялись и дают отказ «не проверялось».
    Английские `False`, `Undefined`, `Export`, `Val` дают «Ожидается имя процедуры». `Асинх` и `Async` — обычные
    имена. Первые два вида отказа `unverified` не снимает; отказ «не проверялось» снимает только
    `unverified=True`.

    Проверки выполняются в таком порядке (`procedure_name_refusal`, затем проверка повтора): вид имени,
    зарезервированное слово (по таблице справочника), литерал или слово объявления, метод глобального контекста,
    свойство глобального контекста, повтор внутри модуля. Совпадение с методом глобального контекста проверяется
    до повтора: платформа отказывает на нём, даже если в модуле это имя не объявлено, и причина другая — имя
    занято платформой. Имена общих модулей конфигурации редактор не знает (они являются свойствами глобального
    контекста), их должен проверить человек.

    Повтор имени — отказ, потому что две процедуры с одним именем платформа не скомпилирует. Повтором считается
    объявленное имя процедуры или функции (`module_names`) без учёта регистра. Объявление ищется в любом месте
    кода вне комментариев и строк, а не только в начале строки. Слово в комментарии, в строке или внутри другого
    имени повтором не считается.

    Переменная модуля с тем же именем (`Перем` вне процедур) и имя, которое модуль вызывает, не объявляя (метод
    глобального контекста или общего модуля), отказа не дают, но отчёт перечисляет их (`module_words`):
    платформа компилирует оба случая, но человеку нужно видеть, как изменится смысл обращений.
    """
    if not isinstance(text, (bytes, bytearray)):
        raise EditError("модуль формы правится БАЙТАМИ: у файла есть BOM и свой перевод строк, "
                        "и через строку они теряются молча")
    refused = procedure_name_refusal(name, unverified)
    if refused:
        raise EditError(refused)
    raw = bytes(text)
    methods, _variables, _calls = module_names(raw)
    wanted = name.casefold()
    if wanted in methods:
        line, kind, spelled = methods[wanted]
        raise EditError(f"в модуле уже объявлена {kind} {spelled!r} (строка {line}) — имена во "
                        "встроенном языке регистронезависимы, и двух процедур и функций с одним "
                        f"именем платформа не скомпилирует ({name!r}), а сказать об этом она "
                        "может только человеку в конфигураторе")
    newline = b"\r\n" if b"\r\n" in raw else b"\n"
    head = f"Процедура {name}({', '.join(params)})".encode("utf-8")
    lines = [b""] + [head] + [("\t" + line).encode("utf-8") for line in body] \
        + ["КонецПроцедуры".encode("utf-8"), b""]
    return raw.rstrip(b"\r\n") + newline + newline.join(lines)


# Зарезервированные слова встроенного языка взяты из таблицы справочника (`1c8-doc`, «Формат исходных текстов
# программных модулей» → «Зарезервированные слова»). Они «не могут использоваться в качестве создаваемых имен
# переменных, реквизитов объектов конфигурации и объявляемых процедур и функций», и у каждого есть русское и
# английское написание. `Выполнить` (`Execute`) тоже есть в этой таблице. Литералы `Истина`, `Ложь`,
# `Неопределено`, `NULL` и слова `Экспорт`, `Знач`, `Асинх` в таблицу не входят и отказывают по другой причине —
# см. `UNMEASURED_NAMES` ниже.
RESERVED_WORDS = (
    ("Если", "If"), ("Тогда", "Then"), ("ИначеЕсли", "ElsIf"), ("Иначе", "Else"),
    ("КонецЕсли", "EndIf"), ("Для", "For"), ("Каждого", "Each"), ("Из", "In"), ("По", "To"),
    ("Пока", "While"), ("Цикл", "Do"), ("КонецЦикла", "EndDo"), ("Ждать", "Await"),
    ("Процедура", "Procedure"), ("Функция", "Function"), ("КонецПроцедуры", "EndProcedure"),
    ("КонецФункции", "EndFunction"), ("Перем", "Var"), ("Перейти", "Goto"),
    ("Возврат", "Return"), ("Продолжить", "Continue"), ("Прервать", "Break"), ("И", "And"),
    ("Или", "Or"), ("Не", "Not"), ("Попытка", "Try"), ("Исключение", "Except"),
    ("ВызватьИсключение", "Raise"), ("КонецПопытки", "EndTry"), ("Новый", "New"),
    ("Выполнить", "Execute"))
_RESERVED = {word.casefold(): pair for pair in RESERVED_WORDS for word in pair}
# Слова, которые язык занимает, хотя таблица «Зарезервированные слова» их не называет: литералы и слова
# объявления. `Истина`, `Ложь`, `Неопределено`, `NULL`, `True`, `Экспорт`, `Знач` платформа отвергает
# («Ожидается имя процедуры», имя подсвечивается красным, как ключевое слово), поэтому отказ жёсткий («не
# скомпилируется») и `unverified` его не снимает. Третий элемент — английские написания `False`, `Undefined`,
# `Export`, `Val`: платформа отвергает их так же. `Асинх` и `Async` платформа принимает («Синтаксических ошибок
# не обнаружено!»), поэтому в списке их нет.
KEYWORD_NAMES = (
    ("литерал", ("Истина", "True"), ("Истина", "True")),
    ("литерал", ("Ложь", "False"), ("Ложь", "False")),
    ("литерал", ("Неопределено", "Undefined"), ("Неопределено", "Undefined")),
    ("литерал", ("NULL",), ("NULL",)),
    ("слово объявления", ("Экспорт", "Export"), ("Экспорт", "Export")),
    ("слово объявления", ("Знач", "Val"), ("Знач", "Val")))
_KEYWORDS = {word.casefold(): (kind, pair, word in measured)
             for kind, pair, measured in KEYWORD_NAMES for word in pair}
# Имена глобального контекста (`edit.globals`, справочник `1c8-doc/global/`). Процедура `Сообщить(Текст)` в
# модуле обычной формы даёт ошибку «Процедура или функция с указанным именем уже определена (Сообщить)»; ошибка
# компиляции появляется уже при `ПолучитьФорму`. То же происходит с `Message` (английское имя этого метода) и со
# вторым методом `СтрНайти`, поэтому правило «имя метода глобального контекста» подтверждено на втором методе и
# на английском написании. Остальные методы отказывают по тому же правилу: имя занято платформой.
#
# Свойства глобального контекста проверялись на девяти парах имён, и результатов было два, поэтому
# распространять их на все имена нельзя. `Метаданные` / `Metadata` — «уже определена». `Константы` /
# `Constants`, `ПараметрыСеанса` / `SessionParameters`, `Справочники`, `Документы`, `Перечисления`,
# `РегистрыСведений`, `ПользователиИнформационнойБазы`, `ХранилищаНастроек` — «Синтаксических ошибок не
# обнаружено!». Русское и английское написания одной пары вели себя одинаково, поэтому проверка одного написания
# считается проверкой обоих. Остальные 91 пара не проверялись и отказывают с сообщением «не проверялось»; отказ
# снимает `unverified`. Общих модулей в проверочной базе не было, поэтому для них граница описана только
# словами.
MEASURED_GLOBAL_METHOD = "Сообщить"
MEASURED_GLOBAL_METHODS = ("Сообщить", "Message", "СтрНайти")
# Проверялись парами: здесь русское имя пары, а в наборах ниже — оба написания.
MEASURED_PROPERTY_REFUSED = ("Метаданные",)
MEASURED_PROPERTY_ALLOWED = ("Константы", "ПараметрыСеанса", "Справочники", "Документы",
                             "Перечисления", "РегистрыСведений",
                             "ПользователиИнформационнойБазы", "ХранилищаНастроек")
_MEASURED_METHODS = {name.casefold() for name in MEASURED_GLOBAL_METHODS}
_GLOBAL_METHODS = {word.casefold(): pair for pair in GLOBAL_METHODS for word in pair}
_GLOBAL_PROPERTIES = {word.casefold(): pair for pair in GLOBAL_PROPERTIES for word in pair}


def _both_writings(russian_names):
    """Оба написания каждой пары (по русскому имени): проверка одного написания закрывает пару целиком."""
    return {word.casefold() for name in russian_names for word in _GLOBAL_PROPERTIES[name.casefold()]}


_PROPERTY_REFUSED = _both_writings(MEASURED_PROPERTY_REFUSED)
_PROPERTY_ALLOWED = _both_writings(MEASURED_PROPERTY_ALLOWED)
# Написания, проверенные напрямую: русские имена всех девяти пар и английские `Metadata`, `Constants`,
# `SessionParameters`. Английские написания остальных шести пар считаются допустимыми по паре, и отчёт об этом
# говорит.
_PROPERTY_SET_BY_ROUND = ({name.casefold() for name in MEASURED_PROPERTY_REFUSED + MEASURED_PROPERTY_ALLOWED}
                          | {"metadata", "constants", "sessionparameters"})
_PROPERTY_CLOSED_BY_PAIR = _PROPERTY_ALLOWED - _PROPERTY_SET_BY_ROUND
CORPUS_GLOBAL_NAMES = {"модулей форм": 1840, "объявлений": 20554, "совпадений": 0}
_DIGITS = frozenset("0123456789")
_CHAR_WORDS = {" ": "пробел", "\t": "табуляция", "\u00a0": "неразрывный пробел",
               "\r": "перевод строки", "\n": "перевод строки"}


def procedure_name_refusal(name, unverified=False):
    """Возвращает отказ со словами, если `name` не годится как имя объявляемой процедуры; `None` — имя годится.

    Справочник встроенного языка требует двух вещей. Имя — «любая последовательность букв, цифр и знаков
    подчеркивания, начинающаяся с буквы или знака подчеркивания» (раздел «Имена переменных, процедур и
    функций»). Имя не должно совпадать с зарезервированным словом (`RESERVED_WORDS`) ни в каком регистре. Цифры
    допускаются только 0–9: цифры других алфавитов справочник не называет, и отказ для них безопаснее догадки.

    Дальше действуют результаты проверки платформой. Литерал, слово объявления (`KEYWORD_NAMES`) и метод
    глобального контекста (`GLOBAL_METHODS`) дают отказ «не скомпилируется», который `unverified` не снимает.
    Для свойств глобального контекста (`GLOBAL_PROPERTIES`) `Метаданные` / `Metadata` дают тот же отказ, ещё
    восемь пар (`MEASURED_PROPERTY_ALLOWED`) допустимы, а остальные 91 дают отказ «не проверялось», который
    снимает `unverified=True`. Порядок проверок описан в докстринге `append_procedure`."""
    if not isinstance(name, str):
        return (f"имя процедуры — строка, а не {type(name).__name__} ({name!r}): оно встаёт в "
                "`Процедура Имя(` как есть")
    where = ("имя — буквы, цифры и «_», и начинается оно с буквы или «_» (справочник встроенного "
             "языка, «Имена переменных, процедур и функций»)")
    tail = (f" Такое имя встало бы в `Процедура {name}(` как есть, и модуль не скомпилировался бы "
            "— а сказать об этом платформа может только человеку в конфигураторе")
    if not name:
        return f"имя процедуры пустое: {where}.{tail}"
    if not (name[0].isalpha() or name[0] == "_"):
        first = "цифра" if name[0] in _DIGITS else _CHAR_WORDS.get(name[0], f"«{name[0]}»")
        return f"имя процедуры {name!r} начинается не с буквы и не с «_» (первый знак — {first}): " \
               f"{where}.{tail}"
    bad = []
    for char in name:
        if not (char.isalpha() or char in _DIGITS or char == "_"):
            word = _CHAR_WORDS.get(char, f"«{char}»")
            if word not in bad:
                bad.append(word)
    if bad:
        return (f"в имени процедуры {name!r} есть знаки, которых в имени не бывает "
                f"({', '.join(bad)}): {where}.{tail}")
    pair = _RESERVED.get(name.casefold())
    if pair:
        return (f"имя {name!r} — зарезервированное слово встроенного языка ({pair[0]} / "
                f"{pair[1]}): зарезервированные слова «не могут использоваться в качестве … "
                "объявляемых процедур и функций» (справочник встроенного языка, «Зарезервированные "
                f"слова»), и в любом регистре.{tail}")
    keyword = _KEYWORDS.get(name.casefold())
    if keyword:
        kind, pair, measured = keyword
        return (f"имя {name!r} — {kind} встроенного языка ({' / '.join(pair)}): не скомпилируется: "
                "Ожидается имя процедуры (проверка Ctrl+F7 модуля формы: имя красное, как ключевое "
                "слово). "
                + ("" if measured else
                   f"Написание {name!r} не проверялось — отказано по тому же классу. ")
                + (f"Английское написание {name!r} проверено: тот же ответ. "
                   if measured and name.casefold() == pair[-1].casefold() and len(pair) > 1
                   and name.casefold() != "true" else "")
                + "unverified этот отказ не снимает: платформа его уже сказала")
    method = _GLOBAL_METHODS.get(name.casefold())
    if method:
        return (f"имя {name!r} — метод глобального контекста ({method[0]} / {method[1]}): не "
                "скомпилируется: Процедура или функция с указанным именем уже определена "
                f"(`{MEASURED_GLOBAL_METHOD}(Текст)` в модуле формы — ошибка при Ctrl+F7; в "
                "предприятии ошибка компиляции поднимается уже при ПОЛУЧЕНИИ формы "
                "(`ПолучитьФорму` — окно «Обнаружены ошибки»), а не только при открытии; то же "
                "для английского имени `Message` и второго метода `СтрНайти`). "
                + ("" if name.casefold() in _MEASURED_METHODS else
                   "Проверялись три имени (`Сообщить`, `Message`, `СтрНайти`); остальные методы "
                   "глобального контекста отказаны по тому же классу. ")
                + "unverified этот отказ не снимает. Назовите процедуру иначе")
    if name.casefold() in _PROPERTY_REFUSED:
        pair = _GLOBAL_PROPERTIES[name.casefold()]
        return (f"имя {name!r} — свойство глобального контекста ({pair[0]} / {pair[1]}): не "
                "скомпилируется: Процедура или функция с указанным именем уже определена "
                "(`Метаданные`, `Metadata` — Ctrl+F7 модуля обычной формы). Свойства глобального "
                "контекста проверялись девятью парами с одним отказом (`Метаданные` / `Metadata`), и на остальные 91 это "
                "не обобщается. unverified этот отказ не снимает. Назовите процедуру иначе")
    prop = _GLOBAL_PROPERTIES.get(name.casefold())
    if prop and name.casefold() in _PROPERTY_ALLOWED:
        return None
    if prop and not unverified:
        return (f"{property_words(name)}. Неизвестное — отказ, а не догадка: такое имя встало бы "
                f"в `Процедура {name}(` как есть, и не скомпилируйся модуль, сказать об этом "
                "платформа смогла бы только человеку в конфигураторе. Позвать всё же можно — "
                "unverified=True, — и тогда результат проверяете вы")
    return None


def property_words(name):
    """Пояснение «не проверялось» для имени свойства глобального контекста; один и тот же текст используется в
    отказе и в отчёте."""
    pair = _GLOBAL_PROPERTIES[name.casefold()]
    return (f"имя {name!r} — свойство глобального контекста ({pair[0]} / {pair[1]}): метод с "
            "таким именем платформа отвергает («уже определена»); свойства проверялись девятью "
            "парами из ста, и исхода было два (`Метаданные` / `Metadata` — «уже определена»; "
            "`Константы`, `ПараметрыСеанса`, `Справочники`, `Документы`, `Перечисления`, "
            "`РегистрыСведений`, `ПользователиИнформационнойБазы`, `ХранилищаНастроек` и "
            "английские `Constants`, `SessionParameters` компилируются), поэтому о прочих 91 "
            "сказать нечего: процедуру с таким именем никто не объявлял, "
            "и компилируется ли модуль с ней, не проверялось; имена общих модулей конфигурации "
            "редактор не знает вовсе")


# Объявление процедуры или функции: ключевое слово и имя могут стоять в любом месте кода — после `КонецФункции`
# на той же строке, после `;`, после аннотации с параметрами (`&Перед("Имя") Процедура О()`), а не только в
# начале строки. Вне строк и комментариев (`_code_lines`) слово «Процедура» с именем после него всегда является
# объявлением. Перед словом не должно стоять ни буквы, ни точки: поэтому `КонецПроцедуры`, `EndProcedure` и
# `Объект.Процедура` не совпадают. Скобку правило не требует: лишний отказ возможен, пропущенное объявление —
# нет. В корпусе есть модуль обычной формы с объявлением не в начале строки (обфусцированный: `…;конецфункции
# функция __a(a)перем a_;…`).
_METHOD_RE = _re.compile(
    r"(?<![\w.])(процедура|функция|procedure|function)\s+([^\W\d]\w*)", _re.IGNORECASE)
_METHOD_END_RE = _re.compile(r"(?<![\w.])(?:конецпроцедуры|конецфункции|endprocedure|endfunction)"
                             r"(?!\w)", _re.IGNORECASE)
_VARIABLE_RE = _re.compile(r"(?<![\w.])(?:перем|var)(?!\w)", _re.IGNORECASE)
# Имена в операторе `Перем`: первое слово каждого пункта списка (`Перем А Экспорт, Б;`).
_VARIABLE_ITEM_RE = _re.compile(r"(?:^|,)\s*([^\W\d]\w*)")
# Вызов без объявления: имя и `(`, не после точки (`Объект.Имя(` — метод объекта, а не модуля), не после `&`
# (`&Перед("Имя")` — это аннотация, а не вызов) и не после `Новый` (`Новый Имя(` — конструктор типа; между ними
# может быть любое число пробелов).
_CALL_RE = _re.compile(r"(?<![\w.&])(?:(новый|new)\s+)?([^\W\d]\w*)\s*\(", _re.IGNORECASE)
_METHOD_KINDS = {"процедура": "процедура", "procedure": "процедура", "функция": "функция",
                 "function": "функция"}


def _code_lines(text):
    """`[(номер строки, код, начата ли строка вне строкового литерала)]` — текст модуля без комментариев `//` и без
    строковых литералов (на их месте пусто, кавычки остаются).

    Литерал встроенного языка записывается в двойных кавычках, кавычка внутри удваивается (`""`), а
    многострочный литерал продолжается на следующих строках, которые начинаются с `|`. Состояние «внутри
    литерала» сохраняется между строками: у строки, начатой внутри литерала, код начинается с закрывающей
    кавычки, а содержимое литерала отбрасывается. Между строками многострочного литерала может быть комментарий
    — строка, начинающаяся с `//` (так закомментирована строка запроса: `//|      Поле / 100 > 75";`); кавычка в
    нём литерал не закрывает. Комментарий `//` вне литерала отсекается до конца строки, и кавычка в нём литерал
    не открывает (`Процедура А() // «кавычка" без пары`)."""
    out, inside = [], False
    for number, line in enumerate(text.splitlines(), 1):
        started_outside = not inside
        if inside and line.lstrip().startswith("//"):
            out.append((number, "", False))
            continue
        code, i = [], 0
        while i < len(line):
            char = line[i]
            if inside:
                if char == '"':
                    if line[i + 1:i + 2] == '"':
                        i += 2
                        continue
                    inside = False
                    code.append('"')
                i += 1
                continue
            if char == "/" and line[i + 1:i + 2] == "/":
                break
            if char == '"':
                inside = True
            code.append(char)
            i += 1
        out.append((number, "".join(code), started_outside))
    return out


def module_names(raw):
    """Имена модуля: `(методы, переменные, вызовы)`; ключ — имя без учёта регистра.

    `методы` — объявленные процедуры и функции: `{имя: (строка, «процедура»|«функция», как написано)}`.
    `переменные` — переменные модуля (`Перем` вне процедур): `{имя: (строка, как написано)}`. `вызовы` — имена,
    которые код (вне комментариев и строк) вызывает как процедуру или функцию (`Имя(`, не после точки и не после
    `Новый`, не само объявление и не зарезервированное слово): `{имя: [строки]}`. Модуль читается как UTF-8 (BOM
    снимается), байты не UTF-8 заменяются; на поиск объявлений это не влияет.

    Код модуля без комментариев и строк (`_code_lines`) склеивается в один текст, и объявления, концы методов и
    операторы `Перем` ищутся в нём по порядку вхождений, а не построчно: объявление может стоять не в начале
    строки, `Перем` — после `;` вторым на строке, а список его имён — на строке продолжения. Лежит ли `Перем`
    внутри метода, определяется по тому же порядку: `Перем` между объявлением метода и его концом — локальная
    переменная."""
    text = bytes(raw).decode("utf-8", errors="replace").lstrip("\ufeff")
    starts, parts, at = [], [], 0
    for _number, code, _outside in _code_lines(text):
        starts.append(at)
        parts.append(code)
        at += len(code) + 1
    code = "\n".join(parts)

    def line_of(position):
        return _bisect.bisect_right(starts, position)

    events = sorted([(m.start(), 0, m) for m in _METHOD_RE.finditer(code)]
                    + [(m.start(), 1, m) for m in _METHOD_END_RE.finditer(code)]
                    + [(m.start(), 2, m) for m in _VARIABLE_RE.finditer(code)],
                    key=lambda event: event[:2])
    methods, variables, calls, heads = {}, {}, {}, set()
    in_method = False
    for _position, kind, match in events:
        if kind == 0:
            methods.setdefault(match.group(2).casefold(),
                               (line_of(match.start(2)), _METHOD_KINDS[match.group(1).casefold()],
                                match.group(2)))
            heads.add(match.start(2))
            in_method = True
        elif kind == 1:
            in_method = False
        elif not in_method:
            end = code.find(";", match.end())
            statement = code[match.end():end if end >= 0 else len(code)]
            for item in _VARIABLE_ITEM_RE.finditer(statement):
                word = item.group(1)
                if word.casefold() not in ("экспорт", "export"):
                    variables.setdefault(word.casefold(),
                                         (line_of(match.end() + item.start(1)), word))
    for call in _CALL_RE.finditer(code):
        name = call.group(2)
        if call.group(1) or call.start(2) in heads or name.casefold() in _RESERVED:
            continue
        calls.setdefault(name.casefold(), []).append(line_of(call.start(2)))
    return methods, variables, calls


# Три имени проверены вызовом и обработчиком: процедура вызвана, событие «Нажатие» названо этим именем, модуль
# после пересохранения не изменился ни в одном байте. Остальные 97 свойств глобального контекста не проверялись.
# Подсветка: редактор платформы красит `Асинх` как ключевое слово, а `Константы` и `ПараметрыСеанса` — как
# обычное имя; при этом процедура компилируется и вызывается.
ROUND19_MODULE_NAMES = {"константы": "Константы", "параметрысеанса": "ПараметрыСеанса", "асинх": "Асинх"}
ROUND19_MODULE_WORDS = ("проверено вызовом и обработчиком: процедура вызвана, событие «Нажатие» названо этим именем, "
                        "модуль после пересохранения байт в байт")
ROUND19_ASYNC_WORDS = ("оговорка о подсветке: редактор платформы красит `Асинх` как ключевое слово (красным), хотя "
                       "процедура компилируется и вызывается — имя допустимо")


def module_words(before, kwargs):
    """Слова отчёта о дописанной процедуре: имя переменной модуля и имя, которое модуль вызывает, не объявляя.

    Ни тот ни другой случай отказа не даёт. Вызов метода глобального контекста или общего модуля — допустимый
    код, и процедура с тем же именем в модуле формы компилируется; но эти вызовы начнут обращаться к новой
    процедуре, и отчёт называет их строки. Переменная модуля с тем же именем тоже допустима: платформа
    компилирует модуль, где переменная и метод называются одинаково (`MODULE_VARIABLE_TWINS`).

    Для имени свойства глобального контекста, пропущенного через `unverified`, отчёт ставит пометку «не
    проверялось» с тем же пояснением, что было бы в отказе."""
    name = kwargs.get("name")
    if not isinstance(before, (bytes, bytearray)) or not isinstance(name, str):
        return ""
    _methods, variables, calls = module_names(before)
    said = ""
    if name.casefold() in ROUND19_MODULE_NAMES:
        said += f"; имя {name!r}: {ROUND19_MODULE_WORDS}"
        if name.casefold() == "асинх":
            said += f"; {ROUND19_ASYNC_WORDS}"
    if name.casefold() in _PROPERTY_CLOSED_BY_PAIR:
        pair = _GLOBAL_PROPERTIES[name.casefold()]
        said += (f"; имя {name!r} — английское написание пары ({pair[0]} / {pair[1]}), которое не "
                 "проверялось: годным оно признано по паре (пары вели себя одинаково в обоих "
                 "написаниях), само написание не проверялось")
    if name.casefold() in _GLOBAL_PROPERTIES and name.casefold() not in _PROPERTY_ALLOWED:
        said += (f"; не проверялось: {property_words(name)} — вызов под unverified, и "
                 "результат (компилируется ли модуль) проверяете вы")
    variable = variables.get(name.casefold())
    if variable:
        line, spelled = variable
        said += (f"; имя {name!r} совпадает с переменной модуля {spelled!r} (строка {line}, "
                 f"Перем) — платформа это допускает: {MODULE_VARIABLE_TWINS}; обращение без "
                 "скобок — к переменной, со скобками — к процедуре")
    lines = calls.get(name.casefold())
    if lines:
        shown = ", ".join(str(line) for line in lines[:10]) + (" …" if len(lines) > 10 else "")
        said += (f"; имя {name!r} модуль уже ЗОВЁТ как процедуру или функцию, не объявив, — "
                 f"{_times(len(lines))} (строки {shown}): это вызов метода глобального контекста "
                 "или общего модуля, и дописанная процедура примет такие вызовы на себя — "
                 "проверьте, что так и задумано")
    return said


# Переменная модуля и метод с одним именем встречаются в модулях 8.x из корпусов, и платформа такие модули
# компилирует. Например, типовая БСП держит `Перем ЭтоГлобальнаяОбработка;` и `Функция ЭтоГлобальнаяОбработка()`
# в одной ветке `#Если`, а функция читает и пишет одноимённую переменную. В модуле обычной формы есть `Перем
# Флаг Экспорт;` и `Процедура Флаг()`, которую форма ставит обработчиком ожидания.
