"""Редактор формы: операции над документом уровня 1 поверх кодека.

Кодек читает `form.frm` в JSON и собирает его обратно. Редактор берёт на себя то, что иначе пришлось бы вести вручную, чтобы
платформа приняла форму: сквозной номер кнопки и счётчик в голове блока действий, счётчик списка элементов, сквозной индекс
элемента и счётчик его выдачи, самоссылки привязок, страницу и порядок обхода в хвосте блока координат, строки в списках
родителя, имя и данные колонки (это два разных свойства; см. `add_column`) и процедуру в `form.bsl`. Забытые мелочи
приводят к разным последствиям. Неверный счётчик списка элементов обнаруживает `validate`. Неверный счётчик пятого списка
блока координат платформа отвергает целиком. Отставший `last_index` не обнаруживает никто, и следующий элемент, созданный в
конфигураторе, получит уже занятый индекс.

После операции документ проходит `validate` без отказов и без предупреждений, которых операция могла не создавать.

Правило состава. Операцией становится приём, который принят платформой, или приём, у которого результат подтверждается
образцами форм. Это разные утверждения: «платформа сама пишет такие формы» и «платформа приняла форму, собранную нами».
Платформой проверены реквизит одного типа (строка без квалификаторов), привязка у одного типа элемента (поле ввода), одно
событие (`OnChange` у того же поля) и удаление кнопки с одним видом действия (стандартным). Вызов шире этого операция
выполняет, если образцы форм подтверждают результат, но сообщает об этом в отчёте: перечень вариантов называется
`ON_CORPUS`, а пометку ставит одно место (`_on_corpus`). Если образцы результат не подтверждают, операция отказывает, а не
ставит пометку.

Приём без подтверждения операцией не становится. Он остаётся черновиком и по умолчанию отказывает, называя, что платформа не
проверяла (ключ `unverified=True` снимает отказ). Черновики: `remove_page` и операции над страницами самой формы
(`add_form_page`, `remove_form_page`), правило которых получено по образцам форм.

«GUID» в карте не означает «уникальный». У набора кнопок меню GUID постоянный (`schema.MENU_BUTTON_SET`): со случайным GUID
меню в 1С:Предприятии не раскрывается. Новый GUID операция выдаёт только там, где его заново выдаёт платформа (голова блока,
кнопка). Владелец кнопки (`BTN_OWNER`) — это голова её блока, и ставит его операция, а не шаблон.

Шрифт. Платформа приняла все проверенные записи и при пересохранении вернула их без изменений. У `set_font` два
проверенных способа записи, и по умолчанию выбран тот, который меньше вмешивается в запись (`TYPEFACE_WAYS`).

Имена полей берутся из карты, а адреса определяются по строению. Имя запрашивается у `schema.MAP` по позиции (`_at`), как в
`validate._reference_names`. Если у позиции нет имени в карте (имя страницы панели, имя и номер колонки, член списка
родителя), используется запасной ключ. Узлы ищутся по строению, а не по адресу: блок действий — по паре ключей, как в
`meaning._bars`, держатель страниц — по имени из карты (`validate._pages_of`), держатель колонок — по ключу `columns`.

Общие с проверкой части вызываются, а не копируются: `validate.PLACEMENT_NAMES`, `COMMANDBAR_NAMES`, `NUMBERING_NAMES`,
`REFERENCE_NAMES`, `NO_REFERENCE` и `_pages_of`.
"""
