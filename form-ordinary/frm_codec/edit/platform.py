# значения вне класса пометка не ставится: отчёт называет, что проверено, а границу берёт у корпуса. Пометка
# также ставится только тогда, когда граница корпуса сама пропускает значение; значение, которого в корпусе нет
# и которое пропущено через `unverified`, получает слова «корпус такого не видел ни разу».
#
# Кроме класса значений учитывается строение. Ширина «любое целое» подтверждена только для колонки с вложенным
