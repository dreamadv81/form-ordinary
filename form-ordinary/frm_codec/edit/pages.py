def _after_back_words(doc, guide):
    """Слова про повторное «Сверху» — только в состоянии после обратного пути (отступ 19, край H)."""
    height = (doc.get("form") or {}).get("height")
    if guide.get(GUIDE_OFFSET) == BACK_SHIFT and _is_int(guide.get(GUIDE_COORD)) \
            and guide[GUIDE_COORD] + guide[GUIDE_OFFSET] == height:
        return (": такое состояние остаётся после обратного пути «Не отображать» (нижняя 401/19). Повторное "
                "«Сверху» платформа пишет итогом 382/19 с правой 700/0, а предприятие кладёт такую форму "
                "иначе, чем предсказывает модель (`BACK_ONE_FORM`); редактор этого не повторяет")
    return ""


def _page0_guide_ok(doc):
    """Нижняя направляющая страницы 0 в проверенном виде: одна, с целыми координатой и отступом и краем по
    высоте формы. Только при таком виде страницу 0 пересчитывают (под `unverified` тоже: иначе
    повторное «Не отображать» → «Сверху» сдвинуло бы страницу второй раз, 368 → 349).
    """
    guide = _form_bottom_guide(_form_pages_block(doc))
    height = (doc.get("form") or {}).get("height")
    return (guide is not None and _is_int(guide.get(GUIDE_COORD)) and _is_int(guide.get(GUIDE_OFFSET))
            and guide[GUIDE_COORD] + guide[GUIDE_OFFSET] == height)


def _bottom_guide_bounds(doc):
    """Слова для случая, когда нижняя направляющая страницы 0 не соответствует проверенному виду: одна, с
    краем по высоте формы.
    """
    out = []
    guide = _form_bottom_guide(_form_pages_block(doc))
    height = (doc.get("form") or {}).get("height")
    if guide is None:
        out.append("у страницы 0 нет одной нижней направляющей: править нечего, а как платформа "
                   "ведёт такую форму, не проверялось")
    elif guide.get(GUIDE_COORD) is None or guide.get(GUIDE_OFFSET) is None \
            or guide[GUIDE_COORD] + guide[GUIDE_OFFSET] != height:
        out.append(f"край нижней направляющей страницы 0 ({guide.get(GUIDE_COORD)} + "
                   f"{guide.get(GUIDE_OFFSET)}) не равен высоте формы ({height}): проверялась "
                   "форма, у которой они совпадают")
    return out


def _edge_rules(coords, sides):
    """Правила элемента к сторонам формы `sides` (объект 0): `[(правило, сторона)]`; если смещение не
    целое, то `None`.
    """
    out = []
    for key in ANCHORS:
        for rname in RULES:
            rule = (coords.get(key) or {}).get(rname)
            if isinstance(rule, dict) and rule.get(RULE_OBJECT) == 0 and rule.get(RULE_SIDE) in sides:
                if not _is_int(rule.get(RULE_OFFSET)):
                    return None
                out.append((rule, rule[RULE_SIDE]))
    return out


def _later_guides_of(block):
    """Правые и нижние направляющие страниц формы после первой: `{страница: [узлы]}`."""
    pages = (block.get(PAGES) or {}).get(PAGE_ITEMS) if isinstance(block.get(PAGES), dict) else None
    count = len(pages) if isinstance(pages, list) else None
    by_page = {}
    for g in block.get(GUIDES) or ():
        if isinstance(g, dict) and _is_int(g.get(GUIDE_PAGE)) and g[GUIDE_PAGE] >= 1 \
                and (count is None or g[GUIDE_PAGE] < count) and g.get(GUIDE_ORDER) in (3, 4):
            by_page.setdefault(g[GUIDE_PAGE], []).append(g)
    return by_page


def _later_pages(doc, strict):
    """Страницы формы после первой при включении «Сверху»: что платформа с ними делает и что не
    проверялось. Возвращает `(направляющие, правила, слова, страницы)`; направляющие — `[(узел, поле, на
    сколько)]`, правила — `[(узел, на сколько)]`, страницы — те, у которых направляющие были по «Не
    отображать» (их номера создания пересортировываются).

    * Страница с направляющими по «Не отображать» (край `(W, H)`): правая направляющая уменьшается на 2,
      нижняя на 20 (отступ 8 тот же), у её элементов ненулевые правила к правому краю формы растут на 2,
      а к нижнему на 20, box прежний.
    * Страница, у которой направляющие уже по «Сверху» (`(W−2, H−20)`, так их кладёт `add_form_page`),
      не трогается; её элементы с правилами к краям операция называет в словах, потому что поведение
      платформы для них не проверялось.
    * Правило со смещением 0 у элемента такой страницы (элемент прижат к краю), направляющие иного края
      и иные неразобранные случаи операция называет в словах.

    Параметр `strict`: если смещение испорчено, то при `strict` операция отказывает словами до записи,
    иначе называет это в словах.
    """
    form = doc.get("form") or {}
    width, height = form.get("width"), form.get("height")
    block = _form_pages_block(doc)
    guides, rules, words = [], [], []
    state = {}
    bottoms, rights = {}, {}  # нижняя и правая направляющие страницы «по Не отображать»: узлы
    guide_at = {}  # правая направляющая страницы: координата до правки
    for page, nodes in sorted(_later_guides_of(block).items()):
        right = [g for g in nodes if g[GUIDE_ORDER] == 3]
        bottom = [g for g in nodes if g[GUIDE_ORDER] == 4]
        if len(right) != 1 or len(bottom) != 1 or not all(
                _is_int(g.get(GUIDE_COORD)) and _is_int(g.get(GUIDE_OFFSET)) for g in right + bottom):
            state[page] = "odd"
            words.append(f"у страницы формы {page} не одна правая и одна нижняя направляющая с целыми "
                         "координатой и отступом: как перепишет конфигуратор, не проверялось")
            continue
        edge = (right[0][GUIDE_COORD] + right[0][GUIDE_OFFSET],
                bottom[0][GUIDE_COORD] + bottom[0][GUIDE_OFFSET])
        guide_at[page] = right[0][GUIDE_COORD]
        if edge == (width, height):
            state[page] = "plain"
            guides += [(right[0], GUIDE_COORD, -LATER_RIGHT_SHIFT), (bottom[0], GUIDE_COORD, -LATER_BOTTOM_SHIFT)]
            bottoms[page], rights[page] = bottom[0], right[0]
        elif edge == (width - 2, height - 20):
            state[page] = "top"
        else:
            state[page] = "odd"
            words.append(f"у страницы формы {page} направляющие с краем {edge}, а проверены (W, H) → (W−2, H−20) "
                         f"({width}, {height}): как перепишет конфигуратор, не проверялось")
    holder = container(doc)
    named = set()
    bound_right = set()  # страницы с элементом, привязанным вправо
    for element in (holder.get(ELEMENTS) or {}).get(ITEMS) or []:
        coords = element.get(COORDS) if isinstance(element, dict) else None
        page = coords.get(PAGE) if isinstance(coords, dict) else None
        if _is_int(page) and page >= 1 and isinstance(coords, dict) and _edge_rules(coords, (3,)) \
                and coords.get(WIDTH) == guide_at.get(page):
            bound_right.add(page)
    # Страница после первой с элементами, прижатыми к низу формы (правило 0, низ H): прижатые не
    # трогаются (ни box, ни правила), нижняя направляющая встаёт на их низ (412/8 меняется на 420/0, а не
    # на 392/8). Правая направляющая страницы без элемента, привязанного вправо на направляющей, меняется
    # на −18 (692/8 на 674/8; причина неизвестна), а с таким элементом не меняется (692/8).
    pinned_pages = {}
    for element in (holder.get(ELEMENTS) or {}).get(ITEMS) or []:
        coords = element.get(COORDS) if isinstance(element, dict) else None
        page = coords.get(PAGE) if isinstance(coords, dict) else None
        if _is_int(page) and page >= 1 and state.get(page) == "plain" and _is_flush(coords) and coords.get(HEIGHT) == height:
            pinned_pages[page] = coords[HEIGHT]
    for page, low in sorted(pinned_pages.items()):
        node = bottoms[page]
        guides[:] = [g for g in guides if not (g[0] is node and g[1] == GUIDE_COORD)]
        guides += [(node, GUIDE_COORD, low - node[GUIDE_COORD]), (node, GUIDE_OFFSET, -node[GUIDE_OFFSET])]
        guides[:] = [g for g in guides if g[0] is not rights[page]]  # `−2` правой направляющей здесь не пишется
        if page not in bound_right:
            guides.append((rights[page], GUIDE_COORD, -PINNED_PAGE_RIGHT_CUT))
        words.append(f"страница формы {page}: прижатые к низу формы ({low}) не меняются, нижняя направляющая "
                     f"ложится на их низ ({low}/0), так записывает платформа (проверено на одной форме); "
                     "правая направляющая страницы "
                     + ("не меняется: на ней лежит элемент с правилом вправо" if page in bound_right else
                        "уменьшается на 18 (692/8 → 674/8): причина не объяснена, форма одна")
                     + "; случай «справа чисто, снизу выступает» и иные нижние края не проверялись")
    for page in sorted(bound_right - set(pinned_pages)):
        # Если на странице правый край элемента с правилом к правому краю формы лежит НА правой направляющей,
        # платформа пишет её смещением отступа (692/6), а не координатой (690/8). Если элемент на направляющую
        # не опирается, платформа пишет 690/8.
        guides[:] = [(n, GUIDE_OFFSET, d) if (n.get(GUIDE_PAGE) == page and n.get(GUIDE_ORDER) == 3) else (n, f, d)
                     for n, f, d in guides]
    for element in (holder.get(ELEMENTS) or {}).get(ITEMS) or []:
        coords = element.get(COORDS) if isinstance(element, dict) else None
        page = coords.get(PAGE) if isinstance(coords, dict) else None
        if not _is_int(page) or page < 1:
            continue
        name = (element.get(NAME_BLOCK) or {}).get(NAME)
        found = _edge_rules(coords, (1, 3))
        if found is None:
            if strict:
                raise EditError(f"у правила к краю формы элемента {name!r} страницы {page} смещение не "
                                "целое — страницы после первой пересчитать нечем")
            words.append(f"у элемента {name} страницы {page} смещение правила к краю формы не целое")
            continue
        if not found:
            continue
        if page in pinned_pages and _is_flush(coords):
            continue  # прижатый на странице после первой: ни box, ни правила не меняются
        if page not in state:
            words.append(f"у страницы формы {page} с элементом {name} нет правой и нижней направляющих: как "
                         "перепишет конфигуратор, не проверялось")
        elif state[page] != "plain":
            if page not in named:
                named.add(page)
                words.append(f"на странице формы {page} лежат элементы с правилами к краям формы, а её "
                             "направляющие уже не по «Не отображать» (край (W, H)): как перепишет "
                             "конфигуратор, не проверялось")
        else:
            for rule, side in found:
                if rule[RULE_OFFSET] == 0:
                    words.append(f"элемент {name} страницы {page} прижат к краю формы (смещение 0): на "
                                 "страницах после первой прижатых элементов не проверялось, правило не меняется")
                else:
                    rules.append((rule, LATER_RIGHT_SHIFT if side == 3 else LATER_BOTTOM_SHIFT))
    return guides, rules, words, sorted(p for p, st in state.items() if st == "plain")


def page0_content_bounds(doc):
    """Чем содержимое формы шире проверенного: слова; пустой результат означает «ничем». Здесь нет ни
    «нижней панели с верхом от низа формы» (платформа поднимает её целиком), ни «прижатого не-панельного
    элемента» (поднимается как панель). Остаются случаи, которые не проверялись: страницы после первой
    (`_later_pages`) и **правила к центру формы**: под `unverified` операция их пишет, но у формы вида
    `bar33` область под закладками ниже на 19, и куда платформа денет центр, не проверялось.
    """
    return _later_pages(doc, strict=False)[2] + _centre_words(doc) + _pinned_bar33_words(doc) + _pinned_types_words(doc)


# Типы прижатых к низу формы элементов, у которых подъём на 19 при «Сверху» у `bar33` проверен: поле
# ввода, кнопка, надпись, поле ввода с кнопкой, командная панель. Иной тип (флажок и прочие)
# обрабатывается по аналогии, и без ключа операция отказывает.
PINNED_TYPES_MEASURED = ("Button", "Label", "TextBox", "CommandBar")


def _pinned_types_words(doc):
    """Слова о прижатых к низу формы (правило со смещением 0) элементах типа, который не проверялся, у вида
    `bar33`: без ключа операция отказывает, под `unverified` записывает как было — элемент поднимается на
    19, как панель, по аналогии. Результат пуст, если вид не `bar33` либо все прижатые элементы входят в
    `PINNED_TYPES_MEASURED`.
    """
    if page0_edge_kind(doc) != BAR33:
        return []
    found = [(str((e.get(NAME_BLOCK) or {}).get(NAME)), e.get("type")) for e, c in _page0_top_level(container(doc))
             if _is_flush(c) and e.get("type") not in PINNED_TYPES_MEASURED]
    if not found:
        return []
    return [f"у `bar33` к низу формы прижаты элементы типа, который не проверялся ({', '.join(f'{n}: {t}' for n, t in found)}): проверены {', '.join(PINNED_TYPES_MEASURED)}. "
            "Платформа поднимает прижатый элемент на 19 вместе с панелью; для иного типа операция делает "
            "то же по аналогии (не проверялось) и правила не меняет"]


def _pinned_bar33_words(doc):
    """Слова о привязанном к низу формы элементе ниже направляющей у вида `bar33`. У `nobar33` платформа
    поднимает такой элемент как прижатый (387/33 меняется на 368/33, кнопка поднимается на 19 с
    прежними правилами). У `bar33` платформой это не проверялось. Операция раньше сдвигала его правило
    на +19 и не поднимала, и элемент выходил за край. Теперь без ключа операция отказывает словами; под
    ключом элемент поднимается на 19 вместе с панелью, его правила не меняются, по аналогии с `nobar33`.
    """
    if page0_edge_kind(doc) != BAR33:
        return []
    names = _pinned_below(doc)
    if not names:
        return []
    return [f"у `bar33` привязанный к низу формы элемент лежит НИЖЕ нижней направляющей ({', '.join(names)}). У `nobar33` платформа поднимает такой "
            "элемент как прижатый (направляющая 387/33 → 368/33, кнопка 390 → 371 с прежними правилами); у `bar33` это не проверялось. "
            "Операция поднимает элемент на 19 вместе с панелью и не меняет его правила, по аналогии с `nobar33` "
            "(почти все такие элементы лежат на самой нижней панели). Прежняя запись — правило +19 при неизменном box — выталкивала их за край области"]


def _centre_words(doc):
    """Слова о правилах к центру формы (сторона 4, объект 0) у элементов страницы 0."""
    names = []
    for element, coords in _page0_top_level(container(doc)):
        if _edge_rules(coords, (4,)):
            names.append(str((element.get(NAME_BLOCK) or {}).get(NAME)))
    return [f"правила к центру формы ({', '.join(names)}): поведение платформы при включении «Сверху» "
            "не проверялось, как и то, куда она сместит центр области, ставшей на 19 ниже"] if names else []


def tabs_top_bounds(doc):
    """Чем форма шире проверенного при включении закладок «Сверху»: слова; пустой результат означает
    «ничем». Названы DPI не 96, Рамка, нижняя направляющая страницы 0 не по высоте формы и содержимое
    (`page0_content_bounds`).
    """
    out = []
    block = doc.get(FORM_BLOCK) if isinstance(doc, dict) else None
    dpi = block.get(DPI) if isinstance(block, dict) else None
    if dpi is not None and dpi != 96:
        out.append(f"DPI формы {dpi}, а проверялось при 96: полоса закладок в единицах формы не проверялась")
    border = _form_border_type(doc)
    if border not in (None, FORM_NO_BORDER):
        out.append(f"у формы Рамка ({border}): включение закладок проверялось у формы без Рамки")
    return out + _bottom_guide_bounds(doc) + page0_content_bounds(doc)


def _later_nobar_words(doc, offset):
    """Слова про страницы после первой у формы без нижней панели (вид `nobar8`, при Рамке отступ 6)."""
    later = sorted(_later_guides_of(_form_pages_block(doc)))
    return [f"у формы без нижней панели (отступ {offset}) есть страницы после первой ({', '.join(map(str, later))}): "
            "при включении «Сверху» платформа переписывает страницы после первой у вида `bar33`, а у формы "
            "без панели это не проверялось, поэтому страницы не меняются"] if later else []


def _unverified_edge_words(doc, key):
    """Слова отчёта, когда отказ вида записан под `unverified`: что пишется и чем не подтверждено."""
    if key == NOBAR33_PINNED:
        names = ", ".join(_pinned_below(doc))
        return [f"вид `nobar33` с привязанным к низу элементом НИЖЕ направляющей ({names}) записан как `bar33` по образцу платформы (проверено на одной форме): "
                "направляющая уменьшается на 19, правила к низу не прижатых растут на 19, элемент поднимается на 19 со своими правилами. "
                "Под ключом операция поднимает элемент на 19 вместе "
                "с панелью и не меняет его правила, по аналогии с `nobar33` (у `bar33` платформа не проверялась)"]
    if key == BAR8:
        return ["вид `bar8` записан по образцу платформы (проверено на двух формах побайтно): 692/8 → 700/0, 412/8 → 420/0, "
                "верхняя панель 700 → 698 с правилом 0 → −2"]
    if key == NOBAR33_BELOW:
        return ["вид `nobar33` с не прижатым элементом ниже H−36 записан по образцу платформы (одна форма): направляющая 387/33 → 400/20, край остаётся H, правила к низу не "
                "меняются; **платформа перепривязывает нижний элемент, а редактор этого не делает** (самосвязи платформа заменяет привязками к панели и правому краю, 9 мест), "
                "поэтому форма в предприятии разойдётся с родной на 29 строк (11, 11 и 7 на проектном, сжатом и растянутом окне)"]
    low = _nobar_class(doc)
    target, why = _content_edge(doc)
    height = _form_height(doc)
    kind = "`nobar8` (проверено на двух формах)" if key == NOBAR8_HIGH else "`nobar33` (формула подтверждена на всех известных формах)"
    tail = ("; не прижатых элементов нет вовсе: формула берёт старую координату минус 20, не проверялось" if low == "none"
            else "; элемент ниже H−36: край остаётся H, правила не меняются, привязки самого "
                 "элемента платформа заменяет, а редактор их не пишет" if low == "low" else "")
    edge = f"H{target - height:+d}".replace("-", "−") if target is not None else "не определён"
    return [f"вид {kind} записан по образцу платформы: край по содержимому равен {edge} (если справа выступает элемент — H−{NOBAR_EDGE_SHIFT}, "
            "если ничто не выступает — H−20), правила к низу меняются на «H минус край»" + tail
            + "; прижатые к низу формы элементы у видов без панели не проверялись и поднимаются на 19 по аналогии с `bar33`; граница "
              f"класса «не ниже H−36» (`<=`) выбрана между проверенными низами (H−52 и H−53 против H−20 и H−8), ровно H−36 не проверялось"]


def _keyed_wider(doc, kind):
    """Чем форма шире проверенного, когда вид без панели либо `bar8` пишется под `unverified`: DPI, Рамка,
    правила к центру, страницы после первой. Это те же случаи, что называет `tabs_top_bounds` у `bar33`.
    """
    out = []
    block = doc.get(FORM_BLOCK) if isinstance(doc, dict) else None
    dpi = block.get(DPI) if isinstance(block, dict) else None
    if dpi is not None and dpi != 96:
        out.append(f"DPI формы {dpi}, а проверялось при 96: полоса закладок в единицах формы не проверялась")
    border = _form_border_type(doc)
    if border not in (None, FORM_NO_BORDER):
        out.append(f"у формы Рамка ({border}): семь видов Рамки проверены у `bar33`; у вида без панели проверена "
                   "«Одинарная» с краем H−18 (`show_tabs`), у `nobar33` ещё «Двойная» (край H−22) и «Двойное подчеркивание» (край H−3); "
                   "у `bar8` с Рамкой записи платформы нет")
    out += _centre_words(doc)
    later = sorted(_later_guides_of(_form_pages_block(doc)))
    if later:
        pages = ", ".join(map(str, later))
        if kind == BAR8:
            out.append(f"у формы есть страницы после первой ({pages}): у `bar8` это не проверялось, страницы остаются по «Не "
                       "отображать» и не меняются")
        else:
            out.append(f"у формы есть страницы после первой ({pages}): у вида без панели их запись не проверялась, поэтому они пишутся по "
                       "аналогии с `bar33`")
    return out


def _keyed_plan(doc, kind, key, keyless=False):
    """Под `unverified` у трёх видов, которые платформа переписывает иначе: `(переписать, слова,
    пометка)`. Страница 0 пишется только из состояния, которое оставляет «Не отображать» (нижний край H;
    у `bar8` ещё правый W): иначе повторная перепись сдвинула бы правила второй раз.
    """
    block = _form_pages_block(doc)
    height, width = _form_height(doc), (doc.get("form") or {}).get("width")
    guides = [(_form_bottom_guide(block), height)] + ([(_page0_guide(block, 3), width)] if key == BAR8 else [])
    for g, edge in guides:
        if g is None or not all(_is_int(g.get(k)) for k in (GUIDE_COORD, GUIDE_OFFSET)) or g[GUIDE_COORD] + g[GUIDE_OFFSET] != edge:
            return False, [f"край направляющей страницы 0 не равен размеру формы ({edge}): запись платформы проверена из состояния «Не "
                           "отображать», поэтому страница 0 не пересчитывается, иначе правила сдвинулись бы второй раз"],                 TABS_AREA_NOTE_UNMEASURED
    if key not in (BAR8, NOBAR33_PINNED):
        target, why = _content_edge(doc)
        if target is None:
            return False, [why], TABS_AREA_NOTE_UNMEASURED
    if keyless:
        return True, _keyed_wider(doc, kind), TABS_AREA_NOTE_UNMEASURED
    return True, _unverified_edge_words(doc, key) + _keyed_wider(doc, kind), TABS_AREA_NOTE_UNMEASURED


def tabs_top_plan(doc, with_form_bounds=True, unverified=False):
    """Что делать со страницей 0, когда закладки «Сверху» включаются из «Не отображать»: `(переписать,
    слова шире проверенного, пометка отчёта, когда не переписано)`. Одно решение для `set_property
    show_tabs` и `add_form_page`.

    * Рамка (семь видов) у формы `bar33` или `nobar8` с отступом 6: страница 0 не переписывается, ключ
      не нужен.
    * `nobar33`, `bar8` и `nobar8` с элементами не ниже H−36: отказ словами с проверенными числами; под
      `unverified` запись по записанному платформой (`rewrite_page0_for_tabs`, оговорка в словах).
    * `nobar8` с элементом ниже H−36: страница 0 не переписывается (так делает платформа), слов нет.
    * `bar33`: переписывается, если нижний край равен высоте формы; слова — `tabs_top_bounds` (у
      `add_form_page` без DPI и Рамки: их называет `_form_page_bounds`, `with_form_bounds=False`).
    * Иной отступ: не переписывается, слова под `unverified`.
    """
    kind = _edge_kind(doc)
    if with_form_bounds and _form_border_type(doc) in FRAME_NOBAR_KINDS and framed_nobar_state(doc) in (FS_SA, FS_SC) \
            and framed_nobar_top_plan(doc)[0]:
        # У формы без панели с Рамкой «Одинарная» платформа при «Сверху» страницу 0 переписывает (край 384)
        # так же, как у вида без Рамки: без ключа операция отказывает, под ключом пишет. `add_form_page`
        # оставляет ветку «не переписывать» (запись при добавлении страницы у такой формы не проверялась).
        return True, [TABS_FRAMED_NOBAR_WORDS_BY_KIND.get(_form_border_type(doc), TABS_FRAMED_NOBAR_WORDS)], TABS_AREA_NOTE_UNMEASURED
    if _form_border_type(doc) in FRAMED_UNTOUCHED and _dpi_ok(doc) and (kind == BAR33 or framed_nobar8(doc)):
        # Проверены формы с ОДНОЙ страницей; у страниц после первой платформа без Рамки переписывает, поэтому
        # без ключа здесь нельзя.
        later = sorted(_later_guides_of(_form_pages_block(doc)))
        words = ([f"у формы с Рамкой есть страницы после первой ({', '.join(map(str, later))}): проверялась форма с одной страницей, "
                  "как платформа переписывает страницы после первой при Рамке, не проверялось, страницы не меняются"] if later else [])
        if kind == BAR33:
            return False, words, TABS_FRAMED_NOTE
        # Отступ 6, панели нет: запись платформы при включении «Сверху» не проверялась (проверены
        # предприятие и пересохранение). `add_form_page` действует как в проверенном случае (без ключа),
        # `set_property` переносит два результата и работает под ключом.
        if with_form_bounds:
            words.insert(0, "у формы Рамка «Одинарная», панели нет, отступ 6, края страницы 0 (W−2, H−2): запись платформы при включении «Сверху» не "
                            "проверялась; операция переносит два известных результата (`bar33` с Рамкой не переписывает, `nobar8` без Рамки не переписывает). "
                            "У формы без панели с Рамкой, поставленной при «Не отображать» (край H−18, правила от H−2), "
                            "платформа страницу переписывает; для состояния (W−2, H−2) такой записи нет")
            return False, words, TABS_NO_BAR_FRAMED_NOTE
        return False, words or _later_nobar_words(doc, FRAMED_NOBAR_OFFSET), TABS_NO_BAR_FRAMED_NOTE
    key = _edge_key(doc, kind)
    if key == NOBAR20:
        # Формула `nobar33` для отступа 20: 400/20 меняется на 380/4, правила растут на 36, край 384. Без
        # ключа операция работает только в проверенной форме (`_nobar20_measured`); иные случаи —
        # `NOBAR20_WIDER` и `NOBAR33_PINNED` под ключом; иной отступ не пишется.
        return _keyed_plan(doc, kind, key, keyless=True)
    if key in EDGE_REFUSALS:
        if not unverified:
            raise EditError(EDGE_REFUSALS[key])
        return _keyed_plan(doc, kind, key)
    if kind == NOBAR8:
        # Страницы после первой у формы без панели не проверялись: страница 0 не пишется, а страницы после
        # первой остались бы по «Не отображать» молча, поэтому операция называет их в словах, а под
        # `unverified` ничего не правит. DPI и Рамка у `nobar8` не называются: страница 0 не пишется, и от них
        # ничего не зависит.
        return False, _later_nobar_words(doc, 8), TABS_NO_BAR_NOTE
    if not with_form_bounds and framed_nobar8(doc):
        # Рамка «Одинарная» без нижней панели, отступ 6 (8 минус 2): `add_form_page` из «Не отображать» не
        # переписывает страницу 0, и платформа это принимает. Так же, как у `nobar8`.
        return False, _later_nobar_words(doc, FRAMED_NOBAR_OFFSET), TABS_NO_BAR_FRAMED_NOTE
    if not page0_rule_applies(doc):
        wider = []
    elif with_form_bounds:
        wider = tabs_top_bounds(doc)
    else:
        wider = _bottom_guide_bounds(doc) + page0_content_bounds(doc)
    if kind == BAR33:
        return _page0_guide_ok(doc), wider, TABS_AREA_NOTE_UNMEASURED
    return False, _odd_edge_words(doc) + wider, TABS_AREA_NOTE_UNMEASURED


def _dpi_ok(doc):
    """DPI формы равен 96 либо блок без DPI (проверялось при 96)."""
    block = doc.get(FORM_BLOCK) if isinstance(doc, dict) else None
    dpi = block.get(DPI) if isinstance(block, dict) else None
    return dpi is None or dpi == 96


def _plan_page0(doc):
    """Всё, что `rewrite_page0_for_tabs` будет писать, — проверенное и прочитанное, без записи: `(направляющая,
    план, названные центровые, прижатые не панели, прижатые панели, страницы после первой)`. Отказ
    словами выдаётся до любой записи (документ правят и руками: число строкой — не повод для трассировки).
    """
    holder = container(doc)
    block = _form_pages_block(doc)
    guide = _form_bottom_guide(block)
    if guide is None or not _is_int(guide.get(GUIDE_COORD)):
        raise EditError("у страницы 0 нет одной нижней направляющей с целой координатой: правило "
                        "закладок «Сверху» применить не к чему")
    plan, centered, others, bars = [], [], [], []
    pinned = set(_pinned_below(doc)) if _edge_kind(doc) in (NOBAR33, NOBAR20, BAR33) else set()
    for element, coords in _page0_top_level(holder):
        name = (element.get(NAME_BLOCK) or {}).get(NAME)
        if not all(_is_int(coords.get(k)) for k in (X, Y, WIDTH, HEIGHT)):
            raise EditError(f"у элемента {name!r} страницы 0 box не из целых — страницу 0 "
                            "пересчитать нечем")
        rules, flush = [], False
        for key in ANCHORS:
            for rname in RULES:
                rule = (coords.get(key) or {}).get(rname)
                if not isinstance(rule, dict) or rule.get(RULE_OBJECT) != 0:
                    continue
                if rule.get(RULE_SIDE) == 4:
                    centered.append(name)
                elif rule.get(RULE_SIDE) == 1:
                    if not _is_int(rule.get(RULE_OFFSET)):
                        raise EditError(f"у правила «к низу формы» элемента {name!r} смещение не "
                                        "целое — страницу 0 пересчитать нечем")
                    if rule[RULE_OFFSET] != 0:
                        rules.append(rule)
                    else:
                        flush = True
        if str(name) in pinned:
            flush = True  # привязанный к низу элемент ниже направляющей поднят как прижатый
        if flush:
            # Прижатый элемент любого типа: его box и край сдвигаются вместе, собственные ненулевые правила к
            # низу формы не трогаются (иначе box разойдётся с правилами на 19, а панель сожмётся до 5–6 px).
            rules = []
            (bars if element.get("type") == "CommandBar" else others).append(
                (name, element.get("type")))
        plan.append((element, coords, rules, flush))
    return guide, plan, centered, others, bars, _later_pages(doc, strict=True)


def check_page0_rewritable(doc):
    """Если страницу 0 пересчитать нечем (документ испорчен), операция отказывает словами и ничего не
    пишет. Вызывается до любой записи — и поля `show_tabs`, и новой страницы.
    """
    _plan_page0(doc)


def _tabs_mode(doc):
    """Как переписывать страницу 0 при «Сверху»: `bar33` (по умолчанию), `nobar` (`nobar33` и `nobar8` с
    элементами не ниже H−36: край H−36, правила растут на 36) или `bar8` (692/8 меняется на 700/0). Вид
    определяет `page0_edge_kind`, класс — `_nobar_class`.
    """
    kind = _edge_kind(doc)
    if kind in (NOBAR33, NOBAR20) and _pinned_below(doc):
        return "bar33", kind  # платформа записывает такую страницу как `bar33` (элемент ниже направляющей)
    if kind in (NOBAR33, NOBAR20) or (kind == NOBAR8 and _nobar_class(doc) == "high"):
        return "nobar", kind
    if kind == BAR8:
        return "bar8", kind
    return "bar33", kind


def _content_edge(doc):
    """Край страницы 0 по содержимому: `(цель, класс)`; `(None, причина)`, если форма не из проверенных.
    Правило: если справа выступает элемент (правый край x2 больше W−2, например `ДействияФормы`), то
    край равен H−36; если при этом не прижатый элемент лежит ниже H−36, то край остаётся H; если
    ничего не выступает, то край равен H−20. Случай «справа ничего не выступает, но что-то ниже H−20» не
    проверялся.
    """
    reach = _page0_reach(doc)
    height, width = _form_height(doc), (doc.get("form") or {}).get("width")
    if reach is None or not (_is_int(height) and _is_int(width)):
        return None, "размеры элементов или формы не из целых"
    if reach["right"] is not None and reach["right"] > width - 2:
        if reach["low"] is not None and reach["low"] > height - NOBAR_EDGE_SHIFT:
            return height, "ниже"
        return height - NOBAR_EDGE_SHIFT, "выступает"
    if reach["bottom"] is None or reach["bottom"] <= height - 20:
        return height - 20, "помещается"
    return None, (f"справа ничто не выступает, но элемент страницы 0 ниже H−20 ({reach['bottom']} > {height - 20}): такая форма "
                  "не проверялась")


def _nobar_guide(doc, kind, guide):
    """Нижняя направляющая страницы 0 у вида «без панели»: `(координата, отступ, сдвиг правил, слова)`.

    Край определяется по содержимому (`_content_edge`): H−36 при выступе справа (`nobar8` оставляет
    отступ: 412/8 меняется на 376/8; `nobar33` берёт координату `max(низ нижнего, старая − 20)`:
    387/33 меняется на 368/16, 367/17, 400/20 меняется на 380/4), H из-за элемента ниже H−36 (387/33
    меняется на 400/20, правила не меняются), H−20 при отсутствии выступа (467/33 меняется на 448/32,
    правила растут на 20). Сдвиг правил равен H минус край. Запись возможна только из состояния «край
    равен H» (`_page0_guide_ok`): иначе вторая перепись сдвинула бы правила ещё раз.
    """
    height = _form_height(doc)
    coord, offset = guide[GUIDE_COORD], guide[GUIDE_OFFSET]
    reach = _page0_reach(doc)
    low = reach["low"] if reach is not None else None
    target, why = _content_edge(doc)
    if target is None:
        raise EditError(why)
    if coord + offset != height:
        raise EditError(f"край нижней направляющей страницы 0 ({coord} + {offset}) не равен высоте формы ({height}): перепись "
                        "по содержимому проверена из состояния «Не отображать»")
    if why == "ниже":
        new = max(low, coord - NOBAR_SLACK)
        if new > height:
            raise EditError(f"нижний элемент страницы 0 ({low}) ниже края формы {height}: направляющую по формуле поставить "
                            "некуда")
        return new, height - new, 0, [f"элемент страницы 0 ниже H−{NOBAR_EDGE_SHIFT} ({low} > {height - NOBAR_EDGE_SHIFT}): край остаётся "
                                      f"{height}, правила к низу не меняются (проверено на одной форме)"]
    if kind == NOBAR8:
        # `max(низ нижнего не прижатого, край − отступ)`, где край − отступ равен 376. Редактор раньше писал
        # `край − отступ` при любом низе и расходился с платформой у низа 380.
        new = max(low, target - offset) if low is not None else target - offset
    else:
        new = max(low if low is not None else coord - NOBAR_SLACK, coord - NOBAR_SLACK)
    if new > target or new < 0:
        raise EditError(f"по записанному платформой (край {target}) направляющая страницы 0 встала бы на "
                        f"{new}: низ не прижатых элементов {low}, прежняя направляющая {coord}/{offset}; такая форма не "
                        "проверялась, страницу 0 пересчитать нечем")
    where = "справа выступает" if why == "выступает" else "справа ничто не выступает"
    return new, target - new, height - target, [f"{where}: край H{target - height:+d}".replace("+", "+").replace("-", "−")]


def _right_reach(doc, width):
    """Наибольший правый край элемента верхнего уровня страницы 0, не доходящего до W (`ДействияФормы`
    шириной 700 не учитывается), либо `None`. Правая направляющая первой страницы встаёт на этот край,
    если он не меньше W−3 и правее прежней координаты.
    """
    reach = _page0_reach(doc)
    if reach is None:
        return None
    found = [x2 for x2, _y2 in reach["who"].values() if x2 < width]
    return max(found) if found else None


RIGHT_MOVE_WORDS = (
    "правая направляющая первой страницы встаёт на правый край элемента ({m}) вместо прежней координаты: проверено только 698/0 у формы с краем W−2 "
    "и 699/1 при выступе (одна форма); порог W−3 (697 отдельно не проверялся), 699/1 и "
    "сочетание `ДействияФормы` шириной W с элементом на 698 не проверялись, поэтому запись возможна только под ключом")


def _right_move(doc, guides):
    """Новая координата правой направляющей первой страницы (правый край самого правого элемента, не
    доходящего до W: не меньше W−3 и правее прежней) либо `None`.
    """
    width = (doc.get("form") or {}).get("width")
    m = _right_reach(doc, width) if _is_int(width) else None
    if m is None or m < width - 3:
        return None
    return m if any(_is_int(g.get(GUIDE_COORD)) and m > g[GUIDE_COORD] for g in guides) else None


def _first_right_guides(doc, guides, edge, wider=None, tier="помещается"):
    """Правые направляющие первой страницы после того, как ничто не выступает (или выступает не всё): край
    `edge`, координата — правый край самого правого элемента (`_right_reach`), если он не меньше W−3 и
    правее прежней, иначе прежняя; отступ считается до края. Прежний способ (координата прежняя, отступ
    −2, 692/8 меняется на 692/6) расходился с платформой: у форм шириной 700 платформа пишет 698/0, у
    одной — 699/1 (край W), у формы шириной 800 — 792/6.
    """
    width = (doc.get("form") or {}).get("width")
    m = _right_reach(doc, width) if _is_int(width) else None
    for g in guides:
        coord = g[GUIDE_COORD]
        if m is not None and m >= width - 3 and m > coord and m <= edge + 1:
            coord = m
            if wider is not None and (tier == "выступает" or m != width - 2):
                wider.append(RIGHT_MOVE_WORDS.format(m=m))  # без ключа пишется только проверенное (698 при крае W−2)
        g[GUIDE_COORD] = coord
        g[GUIDE_OFFSET] = edge - coord


def reflow_page0_by_content(doc, right=True, wider=None):
    """Что платформа делает со страницей 0 «Сверху» без нижней панели, когда форму правят (панели вписаны
    вручную, «Добавить страницу», сохранение): край по содержимому (`_content_edge`) из состояния,
    которое оставляет включение «Сверху» у `bar33` (край H−19). Координата остаётся, отступ считается
    до нового края, правила «к низу формы» не прижатых меняются на «старый край минус новый», а при
    отсутствии выступа справа (`right`) первая страница сдвигается на +2. Край H−20 встаёт на сам низ,
    если низ не меньше H−21 (399 и 400 дают 400/0). Правая направляющая встаёт на правый край самого
    правого элемента (`_first_right_guides`); при выступе справа (x2 699) она тоже встаёт на него
    (699/1), край остаётся W. Если справа чисто, а снизу выступает (низ 401), направляющие равны 698/0
    и 401/0, правила по содержимому не пересчитываются: +19 и +2 остаются от «Сверху» и добавления
    страницы. Возвращает слова либо `None`, если форма не в проверенном состоянии (тогда ничего не
    пишется).
    """
    kind = page0_edge_kind(doc)
    if kind not in (NOBAR33, NOBAR8) or _form_border_type(doc) not in (None, FORM_NO_BORDER):
        return None
    block = _form_pages_block(doc)
    guide, height = _form_bottom_guide(block), _form_height(doc)
    if guide is None or not all(_is_int(guide.get(k)) for k in (GUIDE_COORD, GUIDE_OFFSET)) or not _is_int(height):
        return None
    was = guide[GUIDE_COORD] + guide[GUIDE_OFFSET]
    width = (doc.get("form") or {}).get("width")
    reach = _page0_reach(doc)
    target, why = _content_edge(doc)
    if was != height - TABS_TOP_SHIFT or reach is None:
        return None
    first_guides, first_rules, _beyond = _first_page_edge(doc, block)
    placed = [(g.get(GUIDE_COORD), g.get(GUIDE_OFFSET)) for g in first_guides
              if _is_int(g.get(GUIDE_COORD)) and _is_int(g.get(GUIDE_OFFSET))]
    first_ready = _is_int(width) and sorted({c + o for c, o in placed}) == [width] \
        and sorted({o for _c, o in placed}) == [FORM_PAGE_TOP_OFFSET]
    if target is None and reach["right"] is not None and reach["right"] <= width - 2 and reach["bottom"] is not None \
            and reach["bottom"] > height - 20:
        # Справа чисто, снизу выступает (низ 401 при H−20 равном 400): пересчёта по содержимому нет,
        # направляющие лежат на самих краях: правая — край W−2 (698/0), нижняя — сам низ (401/0). Что именно
        # задаёт низ 401 — сам элемент или константа, не выяснено: известна одна форма.
        if not first_ready:
            return None
        guide[GUIDE_COORD], guide[GUIDE_OFFSET] = reach["bottom"], 0
        if wider is not None:
            wider.append(f"низ {reach['bottom']} больше H−20 при чистой правой оси: направляющие 698/0 и {reach['bottom']}/0 — известна одна форма, "
                         "что именно задаёт низ 401 (сам элемент или константа), не выяснено; запись возможна только под ключом")
        _first_right_guides(doc, first_guides, width - 2, wider)
        return (f"справа ничто не выступает, но низ {reach['bottom']} больше H−20 = {height - 20}: направляющие страницы 0 — нижняя "
                f"{reach['bottom']}/0, правая по краю W−2 (известна одна форма: правила по содержимому не пересчитываются, +19 и +2 дают «Сверху» и добавление страницы, "
                f"{reach['bottom']} — сам низ либо константа 401, не выяснено)")
    if target is None or target == was or why == "ниже":
        return None
    low = reach["low"]
    if why == "помещается" and low is not None and low >= target - 1:
        guide[GUIDE_COORD] = target  # низ 399 и 400: направляющая 400/0 (на край области), не 368/32
    guide[GUIDE_OFFSET] = target - guide[GUIDE_COORD]
    moved = 0
    for _element, coords in _page0_top_level(container(doc)):
        for rule, _side in _edge_rules(coords, (1,)) or ():
            if rule[RULE_OFFSET] != 0:
                rule[RULE_OFFSET] += was - target
                moved += 1
    _resort_page0(doc, block)
    if first_ready and why == "выступает":
        # При x2 равном 699 сдвига +2 нет, край остаётся W, а направляющая встаёт на правый край элемента:
        # 699/1, не 692/8.
        _first_right_guides(doc, first_guides, width, wider, "выступает")
    if right and why == "помещается" and first_ready:
        _first_right_guides(doc, first_guides, width - FORM_PAGE_TOP_SHIFT, wider)
        for r in first_rules:
            r[RULE_OFFSET] += FORM_PAGE_TOP_SHIFT
    return (f"край страницы 0 H−{TABS_TOP_SHIFT} → H{target - height:+d}".replace("-", "−") + f" по содержимому ("
            + ("справа выступает" if why == "выступает" else "справа ничто не выступает") + f"): отступ нижней направляющей "
            f"{guide[GUIDE_OFFSET]}, смещение правил «к низу формы» {was - target:+d} (изменено правил: {moved})")


def _rewrite_bar8(doc):
    """Вид `bar8` при «Сверху»: правая направляющая 692/8 меняется на 700/0, нижняя 412/8 на 420/0 (края
    те же), верхняя командная панель 700 на 698, её правое правило 0 на −2; правила «к низу формы» и
    нижняя панель не меняются. Слова для отчёта.
    """
    block = _form_pages_block(doc)
    width, height = (doc.get("form") or {}).get("width"), _form_height(doc)
    right, bottom = _page0_guide(block, 3), _form_bottom_guide(block)
    for g, edge in ((right, width), (bottom, height)):
        if g is None or not all(_is_int(g.get(k)) for k in (GUIDE_COORD, GUIDE_OFFSET)) \
                or g[GUIDE_COORD] + g[GUIDE_OFFSET] != edge:
            raise EditError("у страницы 0 нет правой и нижней направляющих с краем по размеру формы: вид `bar8` пересчитать нечем")
    cut = []
    for element, coords in _page0_top_level(container(doc)):
        if element.get("type") != "CommandBar" or _is_flush(coords) or not _is_int(coords.get(WIDTH)) \
                or coords[WIDTH] != width:
            continue
        for key in ANCHORS:
            for rname in RULES:
                rule = (coords.get(key) or {}).get(rname)
                if isinstance(rule, dict) and rule.get(RULE_OBJECT) == 0 and rule.get(RULE_SIDE) == 3 \
                        and rule.get(RULE_OFFSET) == 0:
                    cut.append((element, coords, rule))
    for g, edge in ((right, width), (bottom, height)):
        g[GUIDE_COORD], g[GUIDE_OFFSET] = edge, 0
    for element, coords, rule in cut:
        coords[WIDTH] -= BAR8_RIGHT_CUT
        rule[RULE_OFFSET] = -BAR8_RIGHT_CUT
    _resort_page0(doc, block)
    names = ", ".join(str((e.get(NAME_BLOCK) or {}).get(NAME)) for e, _c, _r in cut) or "—"
    return (f"страница 0 (вид `bar8`): правая направляющая ({width}, 0), нижняя ({height}, 0), верхняя командная панель "
            f"уже на {BAR8_RIGHT_CUT} ({names}: ширина −{BAR8_RIGHT_CUT}, правое правило −{BAR8_RIGHT_CUT}) — так "
            "записывает платформа; в предприятии край остаётся H при области H−20, "
            "элементы окажутся на (−2, −20) от конструктора")


