def _resort_page0(doc, block):
    """Шаги 3–4 переписи: номера создания страницы 0 пересчитываются по (низ box, лево box), с единицы;
    списки зависимых упорядочиваются по возрастанию (элемент, сторона). Возвращает названия списков, у
    которых пары не целые (порядок в них не меняется).

    **Не выяснено:** нижняя панель, опущенная человеком (не прижатая, низ 368 или 448), встала в записи
    платформы перед подписью и полем комментария, чей низ на единицу выше (367 или 447), а ключ (низ,
    лево) ставит её после них (у панели 11 вместо 9, у двух соседей 9 и 10 вместо 10 и 11). Поправка
    «+1 к низу `Label` и `TextBox`» согласуется с этими двумя формами, но ломает форму с прижатым полем
    ввода, поэтому правилом не названа. При пересохранении платформа эти три номера не
    пересортировывает, и на показ они не влияют; самостоятельная пересортировка платформой не
    подтверждена.
    """
    boxes = [(coords[HEIGHT], coords[X], coords) for _element, coords in _page0_top_level(container(doc))]
    for number, (_bottom, _left, coords) in enumerate(sorted(boxes, key=lambda t: (t[0], t[1])), start=1):
        coords[CORPUS_CREATION] = number
    skipped = []
    for key in ed_names.DEPENDENTS:
        rows = block.get(key)
        if not isinstance(rows, list):
            continue
        if all(isinstance(r, dict) and _is_int(r.get(ed_names.DEP_ELEMENT))
               and _is_int(r.get(ed_names.DEP_SIDE)) for r in rows):
            rows.sort(key=lambda r: (r[ed_names.DEP_ELEMENT], r[ed_names.DEP_SIDE]))
        else:
            skipped.append(key)
    return skipped


def resort_page0(doc):
    """Номера создания и списки зависимых страницы 0 — порядок, который платформа записывает при «Сверху»
    и у формы с Рамкой, не переписывая страницу 0.
    """
    return _resort_page0(doc, _form_pages_block(doc))


def _renumber_later(doc, pages):
    """Номера создания элементов страниц после первой, переписанных платформой, пересчитываются заново по
    (низ box, лево box), с единицы на каждой странице (у страницы 2 порядок надписи и поля 1/2
    меняется на 2/1).
    """
    holder = container(doc)
    for page in pages:
        boxes = []
        for element in (holder.get(ELEMENTS) or {}).get(ITEMS) or []:
            coords = element.get(COORDS) if isinstance(element, dict) else None
            if isinstance(coords, dict) and coords.get(PAGE) == page and all(
                    _is_int(coords.get(k)) for k in (X, HEIGHT)):
                boxes.append((coords[HEIGHT], coords[X], coords))
        for number, (_b, _l, coords) in enumerate(sorted(boxes, key=lambda t: (t[0], t[1])), start=1):
            if CORPUS_CREATION in coords:
                coords[CORPUS_CREATION] = number


# ── Рамка «Одинарная» у формы без нижней панели ────────────────────────────────────────────────
#
# Состояния страницы 0 одностраничной формы без нижней панели (`FS_*`): S0 — «Не отображать», край H
# (412/8, 387/33); SA — после Рамки «Одинарная», поставленной при «Не отображать»: край H−18 = 402
# (396/6, 387/15), правила «к низу» отсчитываются от H−2; SB — после «Сверху»: край H−36 = 384 (376/8,
# 368/16, 378/6, 369/15), правила от 384; SC — после обратного пути: край H (без Рамки: 412/8, 404/16)
# либо H−18 (с Рамкой: 396/6, 387/15), правила от края. Правило всегда читается как «координата края
# элемента минус опорный край»: `bottom_anchor` — низ, `top_anchor` — верх (у `ТЧ` с низом 250: −170 при
# опоре 420, −168 при 418, −152 при 402, −134 при 384). Поэтому сдвиг правил при переходе равен разности
# опор, а не фиксированному числу: «Сверху» из SA даёт +34 (418 → 384), из SC +18 (402 → 384) при одной
# и той же нижней направляющей (396/6).
FRAME_AREA_CUT = 2  # Рамка «Одинарная»: правила «к низу» отсчитываются от H−2
FRAME_NOBAR_EDGE_CUT = 18  # Рамка «Одинарная» при «Не отображать» у формы без панели: нижний край H меняется на H−18
FRAME_NOBAR_FLOOR = 6  # наименьший отступ нижней направляющей при Рамке (`nobar8`: 8 меняется на 6; `nobar33`: 33 на 15)
FRAME_NOBAR_TOP_CAP = 16  # «Сверху» у формы без панели: отступ нижней направляющей `min(отступ, 16)`
FS_S0, FS_SA, FS_SB, FS_SC = "S0", "SA", "SB", "SC"
# При `nobar33` край и опора правил после Рамки зависят от вида Рамки: `{вид: (край H−a, опора правил
# H−r)}`. «Одинарная» — (18, 2): 387/33 меняется на 387/15, правила растут на 2; «Двойная» — (22, 6):
# 387/33 меняется на 387/11, +6; «Двойное подчеркивание» — (3, 3): 387/33 меняется на 387/30, +3.
# Проверено `nobar33` (у «Двойной» и подчеркивания только он; `nobar8` — только «Одинарная»), остальные
# виды Рамки у вида без панели не проверялись.
FRAME_NOBAR_KINDS = {"Single": (FRAME_NOBAR_EDGE_CUT, FRAME_AREA_CUT), "Double": (22, 6), "DoubleUnderline": (3, 3)}
FRAME_NOBAR_TOP_FIXED = {("DoubleUnderline", 30): 14}  # «Сверху» у подчеркивания: u7 меняется с 30 на 14 (не `min(u7, 16)` = 16), единственный случай


def _bottom_rule_nodes(doc):
    """Правила «к низу формы» (объект 0, сторона 1), не равные нулю, у элементов страницы 0:
    `[(правило, координата края элемента)]`; у верхней привязки это верх, у нижней низ. Если смещение
    не целое, то `None`.
    """
    out = []
    for _element, coords in _page0_top_level(container(doc)):
        for number, key in enumerate(ANCHORS):
            for rname in RULES:
                rule = (coords.get(key) or {}).get(rname)
                if isinstance(rule, dict) and rule.get(RULE_OBJECT) == 0 and rule.get(RULE_SIDE) == 1:
                    if not _is_int(rule.get(RULE_OFFSET)):
                        return None
                    if rule[RULE_OFFSET] != 0:
                        out.append((rule, coords[Y] if number == 0 else coords[HEIGHT] if number == 1 else None))
    return out


def _rules_ref(doc, candidates):
    """Опорный край, от которого отсчитываются правила «к низу формы» страницы 0: первый из `candidates`, с
    которым согласованы все ненулевые правила верхней и нижней привязки (`смещение = край элемента −
    опора`); `None`, если ни один не подходит либо правил нет.
    """
    nodes = _bottom_rule_nodes(doc)
    if not nodes:
        return None
    for ref in candidates:
        if all(at is None or rule[RULE_OFFSET] == at - ref for rule, at in nodes) and any(at is not None for _rule, at in nodes):
            return ref
    return None


def _nobar_single(doc):
    """`(направляющая нижняя, правая, высота, ширина)` формы без нижней панели с одной страницей и DPI 96
    либо `None` (проверена только такая форма: панели нет, обе направляющие страницы 0 с целыми числами).
    """
    if page0_rule_applies(doc) or not _dpi_ok(doc):
        return None
    block = _form_pages_block(doc)
    pages = (block.get(PAGES) or {}).get(PAGE_ITEMS) if isinstance(block.get(PAGES), dict) else None
    if isinstance(pages, list) and len(pages) > 1:
        return None
    form = doc.get("form") or {}
    height, width = form.get("height"), form.get("width")
    bottom, right = _form_bottom_guide(block), _page0_guide(block, 3)
    if bottom is None or right is None or not (_is_int(height) and _is_int(width)) \
            or not all(_is_int(g.get(k)) for g in (bottom, right) for k in (GUIDE_COORD, GUIDE_OFFSET)):
        return None
    return bottom, right, height, width


def framed_nobar_state(doc):
    """Состояние страницы 0 формы без нижней панели (`FS_*`, таблица выше) либо `None`. Определяется по
    краю нижней направляющей и опоре правил (`_rules_ref`): с Рамкой «Одинарная» — `SA` (край H−18,
    опора H−2) и `SC` (край H−18, опора равна краю); без Рамки — `S0` (край H, опора H); `SB` — край H−36
    и опора равна краю (с Рамкой и без).
    """
    found = _nobar_single(doc)
    if found is None:
        return None
    bottom, _right, height, _width = found
    edge = bottom[GUIDE_COORD] + bottom[GUIDE_OFFSET]
    border = _form_border_type(doc)
    cuts = FRAME_NOBAR_KINDS.get(border)
    framed = cuts is not None
    if border not in (None, FORM_NO_BORDER) and not framed:
        return None
    if framed and edge == height - cuts[0]:
        ref = _rules_ref(doc, (height - cuts[1], edge))  # у подчеркивания опора H−3 совпадает с краем: SA и SC по краю не различить, их разводит отступ (`_frame_top_offset`)
        return FS_SA if ref == height - cuts[1] else FS_SC if ref == edge else None
    if edge == height - NOBAR_EDGE_SHIFT and _rules_ref(doc, (edge,)) == edge:
        return FS_SB
    if not framed and edge == height and _rules_ref(doc, (height,)) == height:
        return FS_S0
    return None


def _frame_top_offset(border, offset):
    """Отступ нижней направляющей после «Сверху» у формы без панели с Рамкой: `min(u7, 16)` либо значение,
    записанное поимённо (`FRAME_NOBAR_TOP_FIXED`: «Двойное подчеркивание» 30 меняется на 14); `None`,
    если для такого вида и отступа запись не проверялась.
    """
    if border == "DoubleUnderline":
        return FRAME_NOBAR_TOP_FIXED.get((border, offset))
    return min(offset, FRAME_NOBAR_TOP_CAP)


def border_nobar_plan(doc, new_border):
    """`set_property border_type` при «Не отображать» у формы без нижней панели: «Одинарная» (`nobar8` и
    `nobar33`) и «Двойная», «Двойное подчеркивание» (`nobar33`). Платформа переписывает нижний край
    страницы 0: край H−a, отступ `u7' = u7 − a` (у «Одинарной» не меньше 6: 412/8 меняется на 396/6,
    387/33 на 387/15; «Двойная» 387/33 на 387/11; подчеркивание 387/33 на 387/30), ненулевые правила «к
    низу формы» растут на r (`FRAME_NOBAR_KINDS`: a / r = 18 / 2, 22 / 6, 3 / 3), правая направляющая не
    меняется. Возвращает `(записи, слова)` либо `(None, причина)`; записи — `[(узел, поле, значение,
    пометка, подпись)]`. У `bar33` платформа ничего не пишет (семь видов Рамки); у `nobar8` — только
    «Одинарная».
    """
    cuts = FRAME_NOBAR_KINDS.get(new_border)
    if cuts is not None and framed_nobar_state(doc) == FS_S0 \
            and (_pinned_below(doc) or any(_is_flush(c) for _e, c in _page0_top_level(container(doc)))):
        return None, ("у формы без панели есть прижатые или привязанные ниже направляющей элементы: запись платформы при Рамке проверена без них "
                      "(у прижатого правило верха получило бы +r, а правило низа 0 осталось бы)")
    if cuts is None or framed_nobar_state(doc) != FS_S0:
        return None, ("Рамка поставлена не из состояния «Не отображать» у формы без нижней панели с краем H и правилами от H (проверено: `nobar8` "
                      "412/8 и `nobar33` 387/33, «Одинарная»; `nobar33` — ещё «Двойная» и «Двойное подчеркивание»), либо вид Рамки иной; запись платформы не проверялась")
    bottom, _right, height, _width = _nobar_single(doc)
    if new_border != FORM_SINGLE_BORDER and bottom[GUIDE_OFFSET] != 33:
        return None, (f"вид Рамки «{new_border}» проверен только у `nobar33` (отступ 33), здесь отступ {bottom[GUIDE_OFFSET]}: запись платформы "
                      "не проверялась")
    # Край H−a: у «Одинарной» a = 18 = (H−2) − 16; число шестнадцать — гипотеза (горизонтальная полоса;
    # по снимкам подтверждена только вертикальная), которую вызывает `ДействияФормы` шириной W, большей
    # области с Рамкой W−2. У «Двойной» и подчеркивания a равно 22 и 3, и разбивка (16 + 6, 0 + 3) не
    # выводится. Без выступа справа платформа сдвигает оба края на −2 (правая и нижняя 8 меняются на 6,
    # правила −8 на −6, −113 на −111) — это другая запись, операция её не пишет (`_content_edge` не
    # «выступает» — запись не проверялась).
    target, why = _content_edge(doc)
    if why != "выступает":
        return None, ("справа ничто не выступает за область формы с Рамкой (W−2) либо элемент ниже H−36: проверено, когда выступает `ДействияФормы` "
                      f"({why}); у формы без выступа платформа пишет оба края с вычетом 2, а не H−a")
    edge_cut, area_cut = cuts
    offset = max(bottom[GUIDE_OFFSET] - edge_cut, FRAME_NOBAR_FLOOR) if new_border == FORM_SINGLE_BORDER else bottom[GUIDE_OFFSET] - edge_cut
    writes = [(bottom, GUIDE_OFFSET, offset, None, "страница 0, нижняя направляющая"),
              (bottom, GUIDE_COORD, height - edge_cut - offset, None, "страница 0, нижняя направляющая")]
    for rule, _at in _bottom_rule_nodes(doc) or ():
        writes.append((rule, RULE_OFFSET, rule[RULE_OFFSET] + area_cut, None, "правило «к низу формы»"))
    if new_border != FORM_SINGLE_BORDER:
        return writes, (f"у формы без нижней панели (`nobar33`) платформа, поставив Рамку «{new_border}» при «Не отображать», переписывает нижний край страницы 0 "
                        f"(387/33 → {height - edge_cut - offset}/{offset}; край H → H−{edge_cut}, отступ `u7 − {edge_cut}`), "
                        f"правила «к низу» не прижатых растут на {area_cut}, правая направляющая не меняется; для каждого вида известна одна форма, поэтому запись возможна под `unverified`; у `nobar8` и у других видов Рамки (Выпуклая, "
                        "Вдавленная, Подчеркивание, Черта сверху) запись не проверялась")
    return writes, (f"у формы без нижней панели платформа, поставив Рамку «Одинарная» при «Не отображать», переписывает нижний край страницы 0 "
                    f"(412/8 → 396/6, 387/33 → 387/15; край H → H−{edge_cut}, отступ "
                    f"`max(отступ − 18, 6)`), правила «к низу» не прижатых растут на {area_cut}, правая направляющая не меняется; проверено на двух формах, запись возможна под `unverified`; "
                    "у `bar33` платформа ничего не пишет; виды Рамки, кроме «Одинарной», «Двойной» и «Двойного подчеркивания» (у `nobar33`), у такой формы не проверялись")


def framed_nobar_top_plan(doc):
    """`show_tabs=Top` у формы без панели с Рамкой («Одинарная», у `nobar33` ещё «Двойная» и «Двойное
    подчеркивание») из состояния `SA` (Рамка поставлена при «Не отображать») либо `SC` (после обратного
    пути, только «Одинарная»): платформа переписывает страницу 0 (край 384, отступ `_frame_top_offset`,
    координата `384 − u7`; правила «к низу» меняются на разность опор: +34 из `SA` «Одинарной», +18 из
    `SC`, +30 «Двойной», +33 подчеркивания). Возвращает `(True, "")` либо `(None, причина)`.
    """
    state = framed_nobar_state(doc)
    border = _form_border_type(doc)
    if state not in (FS_SA, FS_SC):
        return None, "Рамка у формы без панели вне проверенных состояний («Рамка при «Не отображать»», «после обратного пути»)"
    if state == FS_SC and border != FORM_SINGLE_BORDER:
        return None, f"повторное «Сверху» после обратного пути у Рамки «{border}» не проверялось"
    if _pinned_below(doc) or any(_is_flush(c) for _e, c in _page0_top_level(container(doc))):
        return None, "у формы без панели есть прижатые к низу элементы: запись платформы при Рамке проверена без них"
    bottom, _right, _height, _width = _nobar_single(doc)
    if _frame_top_offset(border, bottom[GUIDE_OFFSET]) is None:
        return None, (f"у Рамки «{border}» отступ нижней направляющей {bottom[GUIDE_OFFSET]}: «Сверху» проверено из отступа 30 (30 → 14), "
                      "иной не проверялся")
    target, why = _content_edge(doc)
    if why != "выступает":
        return None, ("край по содержимому у формы с Рамкой проверен, когда справа выступает `ДействияФормы` (H−36): здесь "
                      + (why if target is None else f"{why} ({target})"))
    return True, ""


def rewrite_framed_nobar_top(doc):
    """Запись `framed_nobar_top_plan`: слова для отчёта; страницу 0 пишет по таблице состояний выше."""
    ok, why = framed_nobar_top_plan(doc)
    if ok is None:
        raise EditError(f"«Сверху» у формы без панели с Рамкой пересчитать не могу: {why}")
    block = _form_pages_block(doc)
    bottom, _right, height, _width = _nobar_single(doc)
    state = framed_nobar_state(doc)
    border = _form_border_type(doc)
    edge_now = bottom[GUIDE_COORD] + bottom[GUIDE_OFFSET]
    ref_now = _rules_ref(doc, (height - FRAME_NOBAR_KINDS[border][1], edge_now))
    target = height - NOBAR_EDGE_SHIFT
    reach = _page0_reach(doc)
    offset = _frame_top_offset(border, bottom[GUIDE_OFFSET])
    new = max(reach["low"], target - offset) if reach is not None and reach["low"] is not None else target - offset
    old = (bottom[GUIDE_COORD], bottom[GUIDE_OFFSET])
    bottom[GUIDE_COORD], bottom[GUIDE_OFFSET] = new, target - new
    shift = ref_now - target
    moved = 0
    for rule, _at in _bottom_rule_nodes(doc) or ():
        rule[RULE_OFFSET] += shift
        moved += 1
    later_guides, later_rules, later_words, later_plain = _later_pages(doc, strict=True)
    for node, field, delta in later_guides:
        node[field] += delta
    for rule, delta in later_rules:
        rule[RULE_OFFSET] += delta
    _renumber_later(doc, later_plain)
    _resort_page0(doc, block)
    from_where = "SA — Рамка при «Не отображать»" if state == FS_SA else "SC — после обратного пути"
    said = (f"страница 0 (форма без нижней панели, Рамка «{border}», состояние {from_where}): нижняя направляющая {old[0]}/{old[1]} → "
            f"{new}/{target - new} (край {edge_now} → {target}), правила «к низу формы» {shift:+d} — {moved}, правая не меняется, номера создания по "
            "(низ, лево) — так записывает платформа (край H−36, отступ "
            f"`min(отступ, {FRAME_NOBAR_TOP_CAP})`; для «Двойной» 11, для «Двойного подчеркивания» 30 → 14; запись под `unverified`; "
            "сдвиг правил равен разности опор: из SA «Одинарной» +34, из SC +18, «Двойной» +30, подчеркивания +33)")
    if later_words:
        said += "; страницы после первой, не проверялось: " + "; ".join(later_words)
    return said


