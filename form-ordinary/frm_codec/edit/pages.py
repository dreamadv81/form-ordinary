def _remove_page_of(holder_node, block, name, who, gate=None):
    """Убрать страницу панели (`remove_page`) или самой формы (`remove_form_page`).

    Тело одно на оба случая: запись страницы у них одна и та же, и правило, поправленное в одной копии,
    молча миновало бы другую.

    Страница называется ровно одна (`_page_by_name`): пустое имя и имя нескольких страниц — отказ, у
    панели так же, как у формы.

    `gate(номер, страниц)` — граница «проверено» у вызывающей операции. Вызывается после отказов по
    строению (имя, единственная страница, элементы на ней) и до правки; либо отказывает сама, либо
    отдаёт слова, которые встают в конец отчёта.
    """
    pages = block[PAGES][PAGE_ITEMS]
    at = _page_by_name(pages, name, who)
    # Единственная страница проверяется первой: это отказ по строению, и он верен независимо от того,
    # лежат ли на ней элементы (у формы на единственной странице они лежат почти всегда).
    if len(pages) == 1:
        raise EditError(f"это единственная страница {who}; родителя без страниц платформа "
                        "не писала ни разу — страница есть у каждой формы и у каждой панели")
    living = [(item.get(NAME_BLOCK) or {}).get(NAME)
              for item in elements_of(holder_node)
              if isinstance(item.get(COORDS), dict) and item[COORDS].get(PAGE) == at]
    if living:
        raise EditError(f"на странице {name!r} лежат элементы: {', '.join(map(str, living))}. "
                        "Снесите или перенесите их сами — унести их вместе со страницей "
                        "значило бы удалить их молча")
    checked = gate(at, len(pages)) if gate is not None else ""
    pages.pop(at)
    block[PAGES][PAGES_COUNT] = len(pages)
    for item in elements_of(holder_node):
        coords = item.get(COORDS)
        if isinstance(coords, dict) and isinstance(coords.get(PAGE), int) \
                and coords[PAGE] > at:
            coords[PAGE] -= 1
    # Направляющие убираемой страницы уходят, у остальных номер страницы уменьшается. Перестраивать их
    # целиком нельзя: в корпусе есть направляющие, добавленные человеком сверх четырёх.
    #
    # **Уменьшается только номер страницы, а не любое число на его месте.** У панели `Страницы` одной из
    # форм корпуса две направляющие несут там 2 147 483 647 — то есть «ни к какой странице», — и правило
    # «больше удалённой — минус один» превратило бы их в 2 147 483 646. Поэтому меняются числа в пределах
    # прежнего числа страниц, остальные не трогаются.
    left = []
    for guide in block.get(GUIDES) or []:
        where = guide.get(GUIDE_PAGE) if isinstance(guide, dict) else None
        numbered = isinstance(where, int) and not isinstance(where, bool) \
            and 0 <= where <= len(pages)
        if numbered and where == at:
            continue
        if numbered and where > at:
            guide[GUIDE_PAGE] = where - 1
        left.append(guide)
    block[GUIDES] = left
    control = block.get(DEFAULT_CONTROL)
    if isinstance(control, list) and at < len(control):
        control.pop(at)
    _renumber(holder_node)
    return f"страница {name!r} убрана, страниц {len(pages)}" + (f"; {checked}" if checked else "")
