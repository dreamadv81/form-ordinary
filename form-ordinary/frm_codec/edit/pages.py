        # меняется с ширины (392 + 8) на ширину минус 2 (392 + 6) — так же, как у единственной формы корпуса
        # «Сверху» со страницами. Сдвигается только проверенный случай: край равен ширине и отступ равен 8.
        # Если край уже равен ширине минус 2 (у платформы такой формы нет, страницы сняли), либо край или
        # отступ иные, поведение платформы не проверялось, и сдвига нет.
