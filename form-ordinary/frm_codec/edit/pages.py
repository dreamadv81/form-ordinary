def top_size_plan(doc, axis, old, new):
    """Размер формы «Сверху» со страницами по записи платформы: `(записи, слова)` либо `(None, причина)`,
    если форма не в проверенном состоянии.

    Состояние — то, что оставляет включение «Сверху» у `bar33`: правая направляющая страницы 0 с краем
    W, нижняя — H−19, у страниц после первой направляющие `(W−2, H−20)`. Записи —
    `(узел, поле, значение, пометка, подпись)`.
    """
    block = _form_pages_block(doc)
    if block.get(SHOW_TABS) != "Top" or not (_is_int(old) and _is_int(new)):
        return None, "закладки не «Сверху» либо размер формы не разобран"
    if axis not in ("width", "height"):
        return None, f"ось {axis!r}"
    if not page0_rule_applies(doc):
        return None, ("у формы нет нижней командной панели формы, а формула проверена у `bar33` (форма с панелью): у видов без панели размер "
                      "формы платформа записывает по содержимому, и смесь формулы по одной оси с другим правилом "
                      "по другой не пишется")
    order = 3 if axis == "width" else 4
    guide = _page0_guide(block, order)
    if guide is None or not all(_is_int(guide.get(k)) for k in (GUIDE_COORD, GUIDE_OFFSET)):
        return None, "у страницы 0 нет одной направляющей этого края с целыми числами"
    want = old if axis == "width" else old - TABS_TOP_SHIFT
    if guide[GUIDE_COORD] + guide[GUIDE_OFFSET] != want:
        return None, (f"край страницы 0 {guide[GUIDE_COORD] + guide[GUIDE_OFFSET]}, а проверено {want} "
                      f"({'W' if axis == 'width' else 'H−19'}: так оставляет включение «Сверху» у `bar33`)")
    # Вторая ось либо находится в состоянии «Сверху» (край W / H−19), либо уже записана этой же формулой
    # при прошлой правке размера: правая (W−2, 0), нижняя (H−20, 19). Иное состояние — смесь двух правил
    # на одной форме.
    other = _page0_guide(block, 4 if axis == "width" else 3)
    if other is None or not all(_is_int(other.get(k)) for k in (GUIDE_COORD, GUIDE_OFFSET)):
        return None, "у страницы 0 нет одной направляющей другого края с целыми числами"
    form = doc.get("form") or {}
    o_edge, o_offset = other[GUIDE_COORD] + other[GUIDE_OFFSET], other[GUIDE_OFFSET]
    if axis == "width":
        states = {(form.get("height") - TABS_TOP_SHIFT, None), (form.get("height") - 20, TABS_TOP_SHIFT)}
    else:
        states = {(form.get("width"), None), (form.get("width") - 2, 0)}
    if not any(o_edge == e and (o is None or o_offset == o) for e, o in states):
        return None, (f"другой край страницы 0 ({o_edge}, отступ {o_offset}) не в проверенном состоянии: либо оставленном включением "
                      "«Сверху», либо записанном этой же формулой")
    writes = []
    if axis == "width":
        writes += [(guide, GUIDE_COORD, new - 2, None, "страница 0, правая направляющая"),
                   (guide, GUIDE_OFFSET, 0, None, "страница 0, правая направляющая")]
    else:
        writes += [(guide, GUIDE_COORD, new - 20 - TABS_TOP_SHIFT, None, "страница 0, нижняя направляющая"),
                   (guide, GUIDE_OFFSET, TABS_TOP_SHIFT, None, "страница 0, нижняя направляющая")]
        for element, coords in _page0_top_level(container(doc)):
            found = _edge_rules(coords, (1,))
            if found is None:
                return None, "у правила «к низу формы» страницы 0 смещение не целое"
            for rule, _side in found:
                writes.append((rule, RULE_OFFSET, rule[RULE_OFFSET] - TABS_TOP_SHIFT, None,
                               str((element.get(NAME_BLOCK) or {}).get(NAME))))
    later = _later_guides_of(block)
    for page, nodes in sorted(later.items()):
        mine = [g for g in nodes if g[GUIDE_ORDER] == order]
        if len(mine) != 1 or not all(_is_int(mine[0].get(k)) for k in (GUIDE_COORD, GUIDE_OFFSET)):
            return None, f"у страницы формы {page} нет одной направляющей этого края с целыми числами"
        edge = old - 2 if axis == "width" else old - 20
        if mine[0][GUIDE_COORD] + mine[0][GUIDE_OFFSET] != edge:
            return None, f"край страницы формы {page} не по «Сверху» ({edge})"
        writes.append((mine[0], GUIDE_COORD, new - TOP_SIZE_PAGE_MARGIN - 2 if axis == "width"
                       else new - 20 - TOP_SIZE_PAGE_MARGIN, None, f"страница {page}, направляющая"))
        writes.append((mine[0], GUIDE_OFFSET, TOP_SIZE_PAGE_MARGIN, None, f"страница {page}, направляющая"))
    return writes, TOP_SIZE_MEASURED


