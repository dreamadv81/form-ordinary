def _form_edge_rules(doc, side):
    """Правила привязок элементов верхнего уровня к стороне `side` формы (объект 0): список `(элемент,
    привязка, правило, край элемента)` — все четыре привязки и оба правила.

    Край — координата той границы элемента, к которой относится привязка (верх, низ, лево, право). Он
    нужен словам: «край = размер + смещение» выполняется у всех правил.
    """
    out = []
    for element in _form_top_elements(doc):
        coords = element.get(COORDS)
        if not isinstance(coords, dict):
            continue
        for anchor_key, edge_key in zip(ANCHORS, (Y, HEIGHT, X, WIDTH)):
            anchor = coords.get(anchor_key)
            if not isinstance(anchor, dict):
                continue
            for rule_key in RULES:
                rule = anchor.get(rule_key)
                if isinstance(rule, dict) and rule.get(RULE_OBJECT) == 0 \
                        and rule.get(RULE_SIDE) == side \
                        and isinstance(rule.get(RULE_OFFSET), int) \
                        and not isinstance(rule.get(RULE_OFFSET), bool):
                    out.append((element, anchor_key, rule, coords.get(edge_key)))
    return out


