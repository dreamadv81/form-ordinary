    for order in (1, 2, 3, 4):
        guide = copy.deepcopy(pattern[order])
        guide[GUIDE_COORD] = coords[order - 1]
        guide[GUIDE_PAGE] = count
        if GUIDE_OFFSET in guide:
            guide[GUIDE_OFFSET] = offsets[order - 1]
        guides.append(guide)
    page = copy.deepcopy(source)
    page[PAGE_NAME] = name
    if isinstance(page.get(PAGE_CAPTION), dict):
        set_text(page[PAGE_CAPTION], name if caption is None else caption)
