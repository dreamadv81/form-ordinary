def _form_height(doc):
    """Высота формы (для сверки края нижней направляющей)."""
    return (doc.get("form") or {}).get("height")


def _is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def _page0_guide(block, order):
    """Направляющая страницы 0 формы порядка `order` (3 — правая, 4 — нижняя) либо `None`."""
    found = [g for g in block.get(GUIDES) or () if isinstance(g, dict)
             and g.get(GUIDE_PAGE) == 0 and g.get(GUIDE_ORDER) == order]
    return found[0] if len(found) == 1 else None


def _form_bottom_guide(block):
    """Нижняя направляющая страницы 0 формы (порядок 4) либо `None`."""
    return _page0_guide(block, 4)


def _page0_top_level(holder):
    """Узлы и блоки координат элементов страницы 0 формы."""
    out = []
    for element in (holder.get(ELEMENTS) or {}).get(ITEMS) or []:
        coords = element.get(COORDS) if isinstance(element, dict) else None
        if isinstance(coords, dict) and coords.get(PAGE) == 0:
            out.append((element, coords))
    return out


def page0_rule_applies(doc):
    """Есть ли у формы нижняя командная панель формы: элемент `CommandBar` страницы 0 с правилом «к низу
    формы» со смещением 0 (например `ОсновныеДействияФормы`).

    Это только половина признака вида нижнего края (`page0_edge_kind`), а не условие переписи:
    платформа переписывает страницу 0 и у форм без панели, и у форм с панелью и отступом 8, но иначе,
    чем у формы с панелью и отступом 33.
    """
    holder = container(doc)
    for element, coords in _page0_top_level(holder):
        if element.get("type") != "CommandBar":
            continue
        for key in ANCHORS:
            for rname in RULES:
                rule = (coords.get(key) or {}).get(rname)
                if isinstance(rule, dict) and rule.get(RULE_OBJECT) == 0 \
                        and rule.get(RULE_SIDE) == 1 and rule.get(RULE_OFFSET) == 0:
                    return True
    return False


def page0_edge_kind(doc):
    """Вид нижнего края страницы 0: `bar33`, `nobar8`, `nobar33`, `bar8` либо `None` (иной отступ или нет
    одной нижней направляющей). Признак один на все операции страниц: `show_tabs=Top`, `add_form_page`,
    `show_tabs=DontUse`.
    """
    guide = _form_bottom_guide(_form_pages_block(doc))
    offset = guide.get(GUIDE_OFFSET) if guide is not None else None
    if not _is_int(offset):
        return None
    return {(True, 33): BAR33, (False, 8): NOBAR8, (False, 33): NOBAR33,
            (True, 8): BAR8}.get((page0_rule_applies(doc), offset))


FRAMED_NOBAR_OFFSET = 6  # отступ нижней направляющей при Рамке «Одинарная»: 8 минус 2


def framed_nobar8(doc):
    """Форма с Рамкой «Одинарная», без нижней командной панели формы, у которой правая и нижняя
    направляющие страницы 0 по одной, с отступом 6 и краем `(W−2, H−2)` (`nobar8` с вычетом Рамки;
    `page0_edge_kind` такую форму не узнаёт и возвращает `None`). Только для такой формы проверены
    `add_form_page` из «Не отображать» с одной страницей и запись `add_element` и `set_anchors` у
    страницы 0 при Рамке и «Сверху». Оба края проверяются вместе: при сдвинутой направляющей смещения
    пишутся от края, который не проверялся. Запись страницы 0 при Рамке у иного вида нижнего края и при
    Рамке не «Одинарная» не проверялась (при «Сверху» Рамку вручную выбрать нельзя).
    """
    if _form_border_type(doc) != FORM_SINGLE_BORDER or page0_rule_applies(doc):
        return False
    form = doc.get("form") or {}
    width, height = form.get("width"), form.get("height")
    if not (_is_int(width) and _is_int(height)):
        return False
    block = _form_pages_block(doc)
    for order, edge in ((3, width - 2), (4, height - 2)):
        guide = _page0_guide(block, order)
        if guide is None or guide.get(GUIDE_OFFSET) != FRAMED_NOBAR_OFFSET or not _is_int(guide.get(GUIDE_COORD)) \
                or guide[GUIDE_COORD] + guide[GUIDE_OFFSET] != edge:
            return False
    return True


def _is_flush(coords):
    """Прижат ли элемент к низу формы: правило «к низу формы» (объект 0, сторона 1) со смещением 0 в любой
    привязке.
    """
    for key in ANCHORS:
        for rname in RULES:
            rule = (coords.get(key) or {}).get(rname)
            if isinstance(rule, dict) and rule.get(RULE_OBJECT) == 0 and rule.get(RULE_SIDE) == 1 \
                    and rule.get(RULE_OFFSET) == 0:
                return True
    return False


def _edge_kind(doc):
    """Вид нижнего края для операций страницы 0: `page0_edge_kind` плюс внутренний `NOBAR20` (панели нет,
    отступ 20; в корпусе таких форм нет). Сторонние модули (`layout`) читают `page0_edge_kind`, и для
    них отступ 20 по-прежнему `None`.
    """
    kind = page0_edge_kind(doc)
    if kind is None and not page0_rule_applies(doc):
        guide = _form_bottom_guide(_form_pages_block(doc))
        if guide is not None and guide.get(GUIDE_OFFSET) == 20:
            return NOBAR20
        # Состояние формы после обратного пути, у которой отступ при «Сверху» стал 16 (`min(33, 16)`): 404/16,
        # край H, правила от H. «Сверху» из этого состояния пишется как у `nobar8`: отступ остаётся, 404/16
        # меняется на 368/16.
        if guide is not None and guide.get(GUIDE_OFFSET) == FRAME_NOBAR_TOP_CAP and framed_nobar_state(doc) == FS_S0 \
                and _nobar_class(doc) == "high":
            return NOBAR8
    return kind


def _pinned_below(doc):
    """Имена элементов страницы 0, привязанных к низу формы правилом ЛЮБОГО смещения (кроме нуля — это
    прижатые, см. `_is_flush`), чей низ ниже координаты нижней направляющей. Платформа записывает такую
    страницу как `bar33`: направляющая 368/33, край 401, правила остальных растут на 19, кнопка
    поднимается на 19 с прежними правилами. Элемент, чей низ лежит на координате, не ниже её: страница
    не меняется. Если направляющей нет, список пуст.
    """
    guide = _form_bottom_guide(_form_pages_block(doc))
    if guide is None or not _is_int(guide.get(GUIDE_COORD)):
        return []
    names = []
    for element, coords in _page0_top_level(container(doc)):
        if _is_flush(coords) or not _is_int(coords.get(HEIGHT)) or coords[HEIGHT] <= guide[GUIDE_COORD]:
            continue
        if _edge_rules(coords, (1,)):
            names.append(str((element.get(NAME_BLOCK) or {}).get(NAME)))
    return names


def _only_self_rules(element, coords):
    """Все правила элемента ссылаются только на него самого (объект — его собственный индекс) либо
    отсутствуют (объект −1): ни к форме, ни к другому элементу. Панель, привязанная верхом к элементу
    выше, — иной класс.
    """
    own = element.get("index")
    for key in ANCHORS:
        for rname in RULES:
            rule = (coords.get(key) or {}).get(rname)
            if not isinstance(rule, dict):
                continue
            obj = rule.get(RULE_OBJECT)
            if obj is None or obj == -1:
                continue
            if own is None or obj != own:
                return False
    return True


def _unbound_below_guide(doc):
    """Признак для вида `nobar33` при выступе справа (`_content_edge` возвращает «ниже»): не прижатый
    элемент без правил к низу формы лежит ниже координаты нижней направляющей, и все его правила
    ссылаются только на него самого. Платформа записывает направляющую 400/20 и перепривязывает
    элемент, а редактор самосвязь не пишет. В корпусе таких форм нет: у форм прежнего широкого признака
    ниже направляющей лежит нижняя командная панель, привязанная верхом к элементу выше, — это иной
    класс с общим ключом `nobar33`. Элемент, чей низ лежит на координате направляющей, к этому классу не
    относится: платформа страницу не трогает. Элемент ниже направляющей с правилом к низу формы относится
    к `NOBAR33_PINNED`, который проверяется раньше.
    """
    guide = _form_bottom_guide(_form_pages_block(doc))
    height = _form_height(doc)
    if guide is None or not _is_int(guide.get(GUIDE_COORD)) or _content_edge(doc) != (height, "ниже"):
        return False
    return any(not _is_flush(c) and _is_int(c.get(HEIGHT)) and c[HEIGHT] > guide[GUIDE_COORD] and not _edge_rules(c, (1,)) and _only_self_rules(e, c)
               for e, c in _page0_top_level(container(doc)))


def _page0_reach(doc):
    """До каких краёв дотягивается страница 0. Условие переписи и сдвига определяется содержимым.

    Возвращает `{"right": наибольший правый край (coords.right = x2) любого элемента верхнего уровня,
    "bottom": наибольший низ (coords.bottom = y2) любого, "low": наибольший низ не прижатых к низу формы
    либо `None`, "names": по ключам — какие элементы выступают}`; `None`, если у какого-то элемента box
    не состоит из целых чисел.
    """
    right = bottom = low = None
    who = {}
    for element, coords in _page0_top_level(container(doc)):
        if not all(_is_int(coords.get(k)) for k in (X, Y, WIDTH, HEIGHT)):
            return None
        name = (element.get(NAME_BLOCK) or {}).get(NAME)
        if right is None or coords[WIDTH] > right:
            right = coords[WIDTH]
        if bottom is None or coords[HEIGHT] > bottom:
            bottom = coords[HEIGHT]
        if not _is_flush(coords) and (low is None or coords[HEIGHT] > low):
            low = coords[HEIGHT]
        who[name] = (coords[WIDTH], coords[HEIGHT])
    return {"right": right, "bottom": bottom, "low": low, "who": who}


def _nobar_class(doc):
    """Класс формы без нижней панели по низу самого нижнего не прижатого элемента: `high` — не ниже H−36,
    `low` — ниже, `none` — не прижатых элементов нет (для такой формы вида `nobar8` поведение платформы не
    проверялось), `None` — прочесть нечем.
    """
    reach = _page0_reach(doc)
    height = _form_height(doc)
    if reach is None or not _is_int(height):
        return None
    if reach["low"] is None:
        return "none"
    return "high" if reach["low"] <= height - NOBAR_EDGE_SHIFT else "low"


def _edge_key(doc, kind):
    """Ключ отказа или правила `EDGE_REFUSALS` для вида края; `nobar8` с элементами не ниже H−36 имеет
    отдельный ключ.
    """
    if kind == NOBAR8 and _nobar_class(doc) == "high":
        return NOBAR8_HIGH
    if kind in (NOBAR33, NOBAR20) and _pinned_below(doc):
        return NOBAR33_PINNED  # для вида «иное» привязанный ниже направляющей обрабатывается как у `nobar33`
    if kind == NOBAR33 and _unbound_below_guide(doc):
        return NOBAR33_BELOW  # не прижатый элемент без правил к низу формы лежит ниже направляющей: платформа перепривязывает его, редактор не перепривязывает
    if kind == NOBAR20 and not _nobar20_measured(doc):
        return NOBAR20_WIDER
    return kind


def _nobar20_measured(doc):
    """Отступ 20 без панели в той форме, в которой он проверялся: все не прижатые элементы не ниже H−36,
    прижатых и привязанных ниже направляющей нет. Остальные случаи (класс «ниже», прижатые) шире
    проверенного и пишутся только под ключом.
    """
    return _nobar_class(doc) == "high" and not _pinned_below(doc) \
        and not any(_is_flush(c) for _e, c in _page0_top_level(container(doc)))


