#
# У обычной формы есть встроенный контейнер страниц (правая кнопка по форме, «Добавить страницу»).
# В файле он устроен так же, как панель: контейнер формы носит GUID панели, блок его содержимого
# (`LayoutList`) устроен как блок содержимого панели, а запись страницы — та же
# `Element.PanelPage`. Поэтому операции `add_form_page` и `remove_form_page` устроены так же, как
# `add_page` и `remove_page`, но отличаются границами проверенного.
#
# Правила страницы формы выведены из форм корпуса с несколькими страницами формы. Что у них общего
# и что операция берёт из этого:
#
# * **Запись страницы — копия первой страницы.** У не первых страниц отличаются только имя и
#   заголовок, иногда видимость или доступность, в одном случае картинка заголовка. Код записи
#   (`u0`) у всех страниц одной формы один и тот же.
# * **Направляющие новой страницы берутся по умолчанию, а не копируются с первой.** При закладках
#   «Не отображать» четвёрка лежит в 8 пикселях от каждого края (правая равна ширине минус 8,
#   нижняя равна высоте минус 8), даже если у первой страницы направляющие сдвинуты. При закладках
#   «Сверху» они равны 8, 8, ширина минус 10, высота минус 28. Позиция 7 записи — отступ от дальнего
#   края: у правых направляющих контейнера формы (номер 3) она равна ширине минус координата, у
#   нижних (номер 4) — высоте минус координата. При закладках сверху отступ равен 8, а координата
#   отстоит от края на 10 и 28, потому что считается от области страниц.
# * **АктивизироватьПоУмолчанию у новой страницы — «нет».**
# * **ОтображениеЗакладок операция не меняет.** У большинства таких форм оно равно «Не отображать»,
#   и страницы переключает модуль: встроенный контейнер доступен в модуле как свойство формы
#   `Панель` (`Панель.ТекущаяСтраница=Панель.Страницы.Проценка`). РаспределятьПоСтраницам у них
#   такое же, как у одностраничных форм. Списки раскладки (`list1…list4`) общие на все страницы;
#   операция их не трогает, как и `add_page`.
# * **Текущая страница конструктора в файле не видна:** хвост блока содержимого у форм со
#   страницами такой же, как у одностраничных.
#
# У поколения 10 (формы 8.0 и 8.1) вторая страница устроена иначе: у неё нет направляющих, имена
# обеих страниц пустые, а хвост после АктивизироватьПоУмолчанию несёт одно число на форму, а не на
# страницу. Писать туда по правилу форм 15 и 16 нельзя, поэтому для поколения 10 обе операции
# отказывают, и `unverified` этот отказ не снимает: дело в строении, а не в непроверенности. Отказ
# один на обе операции, он реализован в `_old_form_pages`: `remove_form_page` снимает число
# АктивизироватьПоУмолчанию по номеру страницы, а у такой формы на этом месте лежит сдвинутый хвост.
GUIDE_OFFSET = _maybe("Guide", 7)  # отступ от дальнего края

