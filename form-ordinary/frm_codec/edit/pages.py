def _box_of(node):
    """`(ширина, высота)` узла: в блоке координат лежат края, а не размеры."""
    coords = node[COORDS]
    return coords[WIDTH] - coords[X], coords[HEIGHT] - coords[Y]


def add_page(doc, panel, name, caption=None, donor=None, unverified=False):
    """Страница панели: узел страницы, четыре направляющие, счётчики.

    Платформа принимает такую страницу: обе закладки видны, надписи лежат на своих страницах.
    Штатная команда «Добавить страницу» записывает страницу в том же строении: узел страницы,
    четыре направляющие и ещё одно АктивизироватьПоУмолчанию. Имя страницы лежит в
    `Element.PanelPage/name`; конфигуратор показывает записанное имя в строке «Имя» группы «Текущая
    страница».

    **Направляющие зависят от положения закладок** (`edit.base._guide_cut`): правая и нижняя несут
    край области страницы — размер панели минус вычет, левая и верхняя остаются как у первой
    страницы. «Сверху» — вычет (2, 20), то есть при стандартном отступе 6 правая равна ширине минус 8,
    нижняя — высоте минус 26 (так пишет платформа); с картинкой у закладки — (2, 22); «Не отображать» —
    (0, 0). Эти положения и «Сверху (с прокруткой)» работают без ключа. Остальные положения («Снизу»,
    вертикальные, «Слева/Справа (горизонтально)», «в несколько строк», код 13) выполняются только с
    `unverified=True`: формула от области страницы, корпус её не подтверждает или почти не видел,
    а отчёт называет это словами. Если подпись закладок не измерена, операция отказывает даже с ключом.
    """
    place, block = _panel_pages(doc, panel)
    pages = block[PAGES][PAGE_ITEMS]
    if name in [page.get(PAGE_NAME) for page in pages]:
        raise EditError(f"страница {name!r} у {panel!r} уже есть")
    if donor is None:
        source = pages[0]
    else:
        source = next((p for p in pages if p.get(PAGE_NAME) == donor), None)
        if source is None:
            known = ", ".join(str(p.get(PAGE_NAME)) for p in pages)
            raise EditError(f"страницы-донора {donor!r} у {panel!r} нет; есть: {known}")
    width, height = _box_of(place.element)
    pattern = _guide_pattern(block)
    page = copy.deepcopy(source)
    page[PAGE_NAME] = name
    if caption is not None:
        set_text(page[PAGE_CAPTION], caption)
    # Края считаются по панели вместе с новой страницей: подпись и картинка новой закладки меняют ряды и полосу.
    pages.append(page)
    words = []
    try:
        guides = _make_guides(block, pattern, len(pages) - 1, width, height, node=place.element, doc=doc,
                              unverified=unverified, words=words)
    except EditError:
        pages.pop()
        raise
    block[PAGES][PAGES_COUNT] = len(pages)
    block[GUIDES] = block[GUIDES] + guides
    if isinstance(block.get(DEFAULT_CONTROL), list):
        block[DEFAULT_CONTROL] = block[DEFAULT_CONTROL] + [NO_REFERENCE]
    return f"{panel}: страница {name!r}, страниц {len(pages)}; " + "; ".join(words)


