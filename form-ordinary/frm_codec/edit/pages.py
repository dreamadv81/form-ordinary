def _form_pages_block(doc):
    """Блок раскладки контейнера формы — держатель её страниц. Если блок не разобран, операция
    отказывает словами.
    """
    block = layout_block(container(doc), need=False)
    if block is None:
        raise EditError("у контейнера формы не разобран блок раскладки — ни страниц формы, ни "
                        "направляющих в нём не видно; править нечего")
    return block


def _old_form_pages(doc, act):
    """Проверка поколения 10 общая для `add_form_page` и `remove_form_page`.

    Она выполняется раньше проверки имени: у единственной такой формы имена страниц пустые, и отказ
    по имени назвал бы не ту причину. Параметр `act` — глагол, которым кончается совет («добавляйте»,
    «убирайте»).
    """
    version = _design.form_version(doc)
    if version == FORM_PAGE_OLD:
        raise EditError(
            f"форма поколения {FORM_PAGE_OLD} (8.0/8.1): вторую страницу формы корпус держит у "
            "ОДНОЙ такой формы, и устроена она не так, "
            "как пишут эти операции: у второй страницы нет направляющих, имена страниц пустые, "
            "АктивизироватьПоУмолчанию одно на форму. Как это поколение держит страницы формы, "
            "не проверялось, и ключ unverified этого отказа не снимает. Конфигуратор 8.3 при "
            f"сохранении поднимает форму до своей версии, поэтому {act} страницу в поднятой форме")
    return version


def page_number(holder_node, page, who):
    """Номер страницы родителя с нуля по `page`: число (как есть) или имя страницы. Одно правило для всех операций, где `page` называет
    страницу родителя (`add_element`, `move_element`, `reparent`, `set_tab_order`): раньше имя строкой падало трассировкой.

    Число не проверяется на диапазон — это делает вызывающая операция своим отказом (он называет, какой операцией заводят страницу).
    Имя страницы должно быть ровно одно (`_page_by_name`).
    """
    if isinstance(page, bool) or not isinstance(page, (int, str)):
        raise EditError(f"page — номер страницы с нуля (целое) или её имя (строка), а пришло {page!r}")
    if isinstance(page, int):
        return page
    block = layout_block(holder_node, need=False)
    if block is None:
        raise EditError(f"у {who} страниц не бывает вовсе — страницу по имени {page!r} искать негде (page: 0 — единственное место)")
    return _page_by_name(block[PAGES][PAGE_ITEMS], page, who)


def _page_by_name(pages, name, who, role="страницы"):
    """Индекс страницы панели или формы по имени. Страница должна быть ровно одна, иначе операция
    отказывает словами.

    Пустое имя и имя, которое носят несколько страниц, страницу не определяют: молчаливый выбор
    «первой подходящей» привёл бы к правке не той страницы (у формы поколения 10 обе страницы
    безымянны). `validate` о повторе имени предупреждает, а операция, которой нужна одна страница,
    отказывает.
    """
    names = [page.get(PAGE_NAME) if isinstance(page, dict) else None for page in pages]
    known = ", ".join(repr(n) for n in names)
    if isinstance(name, int) and not isinstance(name, bool):
        # Номер страницы с нуля — та же страница, что и по имени, только однозначнее (имена бывают пустыми и повторными).
        if not 0 <= name < len(pages):
            raise EditError(f"{role} с номером {name} у {who} нет (счёт с нуля); есть: "
                            + ", ".join(f"{i}: {n!r}" for i, n in enumerate(names)))
        return name
    if not isinstance(name, str) or not name:
        raise EditError(f"{role} без имени не назвать: нужна непустая строка (у {who} страницы "
                        f"{known}) — по пустому имени страницу не отличить от другой безымянной")
    found = [i for i, n in enumerate(names) if n == name]
    if not found:
        raise EditError(f"{role} {name!r} у {who} нет; есть: {known}")
    if len(found) > 1:
        raise EditError(f"имя страницы {name!r} у {who} не единственно — его носят страницы "
                        f"{', '.join(str(i) for i in found)} (счёт с нуля); какую из них взять, "
                        "по имени не сказать, а выбирать молча нельзя. Переименуйте одну из них "
                        "правкой JSON (`name` записи страницы)")
    return found[0]


# Что проверено в предприятии для трёх операций со страницами формы.
#
# **Добавление страницы формы.** Проверены три случая (в предприятии нетронутая форма с командой
# «Добавить страницу» сравнивалась с результатом операции):
#
# * Закладки «Не отображать», одна страница. Платформа сама включает закладки «Сверху» (`show_tabs`
#   меняется с DontUse на Top), кладёт направляющие новой страницы по правилам «Сверху» (ширина минус
#   10, высота минус 28, отступы 8) и не трогает первую страницу.
# * Закладки «Сверху», одна страница. Направляющие новой страницы: ширина минус 10, высота минус
#   28. У первой страницы отступ правой направляющей меняется с 8 на 6, а смещения правых привязок её
#   элементов (объект 0, сторона 3) растут на 2; нижние направляющие не меняются.
# * Закладки «Не отображать», страниц уже две. Платформа добавляет «Страница3» после текущей,
#   закладки не меняет, направляющие 8, 8, ширина минус 8, высота минус 8; операция делает то же.
#
