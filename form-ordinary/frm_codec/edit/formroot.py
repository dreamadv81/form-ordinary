def _form_versions(versions):
    """Перечень версий формы в словах отказа: «версии 27», «версий 20, 23 и 25»."""
    listed = [str(version) for version in sorted(versions)]
    text = listed[0] if len(listed) == 1 else ", ".join(listed[:-1]) + " и " + listed[-1]
    return ("версии " if len(listed) == 1 else "версий ") + text


