def _form_property(doc, name, value, unverified):
    """Особые правила для свойств самой формы (`set_property form=True`): Стиль, основной реквизит и обработчики событий. Если
    поле обычное, возвращается `None`, и оно обрабатывается общим путём.

    Для Стиля граница — строение блока, а не значение. Тип основного реквизита и его номер («Данные» формы) операция не пишет и
    отказывает с пояснением: это перестройка формы, а не изменение поля. Обработчики событий формы операция тоже не пишет: у
    формы три списка обработчиков, и во всех трёх поле называется `events`.
    """
    parts = [part for part in str(name).split("/") if part]
    last = parts[-1] if parts else ""
    if last == EVENTS:
        raise EditError(f"{name} у формы: {FORM_EVENTS_WORDS}")
    # Тот же адрес, записанный номером позиции, как его печатает смысловой дифф (`attributes/u0/0`, `main_attribute/0`). Отказ
    # для него формулируется теми же словами.
    last = FORM_POSITIONS.get(tuple(parts[-3:]) if len(parts) >= 3 else (), None) \
        or FORM_POSITIONS.get(tuple(parts[-2:]), last)
    if last == MAIN_ATTRIBUTE_ID:
        raise EditError(
            f"{name} у формы: «Данные» формы — это номер основного реквизита, и его смена — не "
            "правка поля, а перестройка формы. Вместе с номером платформа меняет тип значения формы "
            "(`main_attribute/main_attribute_type` повторяет тип основного реквизита), перестраивает "
            "блок основного реквизита (`main_attribute/u2`) и палитру формы (пропадают «Сохранять "
            "значения», «Сохраняемые значения», «ВосстанавливатьЗначенияПриОткрытии», появляются "
            "«ИспользованиеДляГруппИЭлементов» и «Автонумерация»), а проверка модуля, который "
            "обращается к реквизитам прежнего основного реквизита без имени, находит ошибки "
            "(«Переменная не определена»). Платформа допускает не любой выбор: реквизит типа "
            "«ТаблицаЗначений» диалог «Данные» не предлагает, реквизит объектного типа "
            "(`СправочникОбъект.Товары`) предлагает, а элемент-таблицу выбрать не позволяет. "
            "У редактора такой операции нет: основной реквизит назначают в конфигураторе.")
    if last == MAIN_ATTRIBUTE_TYPE:
        raise EditError(
            f"{name} у формы: тип основного реквизита — не поле, а перестройка формы. Вместе с ним "
            "платформа меняет тип реквизита формы в описателе, "
            f"снимает {X18_TYPE_REBUILT['привязок']} привязок данных и "
            f"{X18_TYPE_REBUILT['связей']} связи по типу у элементов, которые шли от "
            "ОбработкаОбъект, перестраивает блок основного реквизита (`main_attribute/u2`) и палитру "
            "формы (пропадают «Сохранять значения», «Сохраняемые значения», «Восстанавливать"
            "ЗначенияПриОткрытии», появляются «ИспользованиеДляГруппИЭлементов» и «Автонумерация»), "
            "а модуль перестаёт видеть реквизиты обработки («Переменная не определена»). "
            "У редактора такой операции нет: тип значения формы меняют в конфигураторе.")
    if last != STYLE:
        return None
    block = doc.get(STYLE_BLOCK) if isinstance(doc, dict) else None
    if not isinstance(block, dict) or STYLE_LEAD not in block:
        raise EditError(f"{name} у формы: блока стиля ({STYLE_BLOCK}) у формы нет или он другого "
                        f"строения ({block!r}); у форм этот блок всегда есть")
    if value is None:
        new = None
    elif isinstance(value, dict) and set(value) == {"guid"} and _guid_like(value["guid"]):
        new = {"guid": value["guid"]}
    elif _guid_like(value):
        new = {"guid": value}
    else:
        raise EditError(f"{name} у формы: значение должно быть GUID объекта стиля ({{\"guid\": …}} или "
                        f"строкой), а для «Авто» — null; получено {value!r}")
    lead, old = block.get(STYLE_LEAD), block.get(STYLE)
    shape = "{" + str(lead) + (",GUID" if new is not None else "") + "}"
    seen = CORPUS_FORM_STYLES.get(shape)
    if seen is None and not unverified:
        known = ", ".join(key for key in CORPUS_FORM_STYLES if key != "GUID")
        raise EditError(f"{name} у формы: блок стиля строением {shape} в образцах форм не встречается; "
                        f"встречаются {known}. Чтобы всё же выполнить операцию, "
                        "передайте unverified=True")
    if seen is None:
        tail = f"; строение {shape}: {UNSEEN_NOTE}"
    elif new is None:
        tail = f"; строение {shape} — «Авто», встречается в образцах форм"
    else:
        # Пометка «проверено в предприятии» ставится только для строения `{0, GUID}`. Для `{-1, GUID}` без `unverified` операция
        # отказывает, а с ним пишет «в образцах не встречалось».
        tail = (f"; строение {shape}: {ROUND12_STYLE}; {EXP_STYLE}. Сам GUID — это объект "
                "стиля данной конфигурации, у каждой конфигурации свой, и операция не может сверить его "
                "с конфигурацией: стиль с таким GUID в конфигурации должен существовать, а что сделает "
                f"платформа с чужим GUID, не проверялось; {_style_page_note()}")
    items = [(key, item) for key, item in block.items() if key != STYLE]
    if new is not None:
        items.append((STYLE, new))
    block.clear()
    block.update(items)
    return (f"формы: {STYLE} {_short(old) if old is not None else '— (Авто)'} → "
            f"{_short(new) if new is not None else '— (Авто)'}"
            + (" (то же значение, что стояло)" if old == new else "") + tail)


