def _library_picture(value):
    """Картинка из библиотеки: источник 1 и GUID в ссылке."""
    ref = value.get(PIC_REF) if isinstance(value, dict) else None
    return isinstance(value, dict) and value.get(PIC_SOURCE) == 1 and isinstance(ref, dict) \
        and isinstance(ref.get(PICREF_GUID), dict)


def _rgb(value):
    return isinstance(value, dict) and value.get("color_kind") == 0


def _is(expected):
    return lambda value: value == expected and type(value) is type(expected)


