def _form_trail(found):
    """Путь поля от корня формы, записанный именами из карты. Если у позиции имя снято демоцией, используется оно."""
    return "/".join(found.trail[:-1] + (getattr(found.slot, "name", None) or found.key,))


def _form_written(trail):
    """Строка палитры формы, к которой относится поле (у подполя — строка его блока): `(путь, строка)`. Путь, охватывающий поле, в
    перечне один. Если появятся вложенные пути, берётся строка с самым длинным путём.
    """
    hits = [written for written in FORM_WRITES
            if trail == written or trail.startswith(written + "/")]
    if not hits:
        return None, None
    written = max(hits, key=len)
    return written, FORM_WRITES[written]


def _form_settings_words(doc, name):
    """Отказ для строк сохранения значений у формы, у которой блок основного реквизита не является блоком настроек. Для блока
    настроек возвращается `None`.
    """
    kind = props.form_settings(doc)
    if kind == "настройки":
        return None
    guid = ((doc.get(MAIN_ATTRIBUTE) or {}).get(MAIN_ATTRIBUTE_TYPE) or {}).get("guid", "—")
    shape = {"без блока": "нет вовсе",
             "события объекта": f"несёт события объекта (тип основного реквизита `{guid}`)",
             "иное": f"другого строения (тип основного реквизита `{guid}`)"}[kind]
    return (f"{name} у формы: строки «Сохранять значения» и «ВосстанавливатьЗначенияПриОткрытии» "
            f"живут в блоке НАСТРОЕК основного реквизита (`{FORM_SETTINGS}`), а у этой формы этот "
            f"блок {shape} — это не блок настроек. Блок настроек — со «Сохраняемыми значениями» и "
            "их счётчиком — стоит только у форм отчёта и обработки; у формы объекта на тех же "
            "позициях события объекта, у части форм блок иной или его нет, и палитра такой формы "
            "этих строк не показывает (они пропадают при смене "
            "типа значения формы). Писать сюда значило бы править другое свойство")


def _form_has(doc, found_all, parts):
    """Проверяет, есть ли у формы позиция по пути ключей, который отсчитывается от корня или от блока, чей путь заканчивается
    остальными шагами (так же, как имя пути у `set_property`).
    """
    node = doc
    for part in parts:
        if not isinstance(node, dict) or part not in node:
            break
        node = node[part]
    else:
        return True
    head, last = parts[:-1], parts[-1]
    for found in found_all:
        value = found.holder.get(found.key)
        if isinstance(value, dict) and last in value \
                and _form_trail(found).split("/")[-len(head):] == head:
            return True
    return False


def _form_missing(doc, found_all, name):
    """Отказ «поля нет» для корня формы с указанием, где поле находится и почему. Если особого случая нет, возвращается `None`, и
    действует общий отказ.
    """
    parts = [part for part in str(name).split("/") if part]
    last = parts[-1] if parts else ""
    # СоединяемоеОкно — позиция 8 корня. Позиция `u8` набора картинок или другого блока — не она.
    if len(parts) == 1 and last in ("u8", "connectable_window"):
        return f"{name!r} у формы: {FORM_CONNECTABLE}"
    if last in ("save_values", "restore_values_on_open"):
        words = _form_settings_words(doc, name)
        if words is not None:
            return words
    if last in FORM_MISSING and (len(parts) == 1 or parts[0] in ("form", "main_attribute")):
        version = (f" (версия формы {doc.get('version')})"
                   if any(trail.rsplit("/", 1)[-1] == last for trail in CORPUS_FORM_MISSING)
                   else "")
        return f"поля {name!r} у этой формы нет{version}: {FORM_MISSING[last]}"
    if len(parts) > 1 and last[:1] == "u" and last[1:].isdigit() \
            and _form_has(doc, found_all, parts):
        # Позиция существует, но у неё нет имени. Поиск по имени её не находит, поэтому ответ «поля нет» был бы неверным (например,
        # набор картинок формы: u3…u8).
        return (f"{name!r} у формы — безымянная позиция: смысла её карта не знает, и по имени её "
                "не правят (как и блок, в котором она лежит, целиком) — правьте JSON по адресу, "
                "validate сверит строение")
    if parts and parts[0] == "attributes" or last in ("next_id", "bindings", "list"):
        return f"{name!r} у формы: {FORM_REFUSALS['attributes']}"
    if last in ("menu", "kind", "owner", "count") and "context_menu_links" in parts:
        return f"{name!r} у формы: {FORM_REFUSALS['context_menu_links']}"
    if last in ("menu", "kind"):
        return f"{name!r} у формы: {FORM_REFUSALS['context_menu_links']}"
    if last in FORM_PAGE_NAMES or "pages" in parts:
        return f"{name!r} у формы: {FORM_REFUSALS[_FORM_LL + '/pages']}"
    return None


