def _standard_code(value):
    """Стандартное действие: ИМЯ значения перечисления либо неназванный код числом.

    Названный код числом кодек отвергает («у кода есть имя — его и пишут»), поэтому отказ здесь
    называет имя сам.
    """
    enum = schema.ENUMS[schema.MAP["EventAction.v6"].fields[3].enum]
    if isinstance(value, str):
        if value not in enum.codes:
            known = ", ".join(f"{name} = {code}"
                              for name, code in sorted(enum.codes.items(), key=lambda kv: kv[1]))
            raise EditError(f"стандартного действия {value!r} карта не знает; известны {known}. "
                            "Неназванный код пишут числом — их 59, и палитрой их никто не "
                            "открывал")
        return value
    if not isinstance(value, int) or isinstance(value, bool):
        raise EditError(f"стандартное действие — имя значения перечисления либо код числом, "
                        f"а не {value!r}")
    for name, code in enum.codes.items():
        if code == value:
            raise EditError(f"у кода {value} есть имя — {name!r}, его и пишут: число кодек "
                            "отвергнет при сборке")
    return value


