def _shortcut_twins(doc, action, pair, skip=None):
    """Кнопки формы с тем же непустым сочетанием, кроме `action`: `["панель/кнопка"]`.

    Ищется по записям действий ВСЕХ блоков формы и по кнопкам ФОРМЫ (`кнопки формы Имя`); запись без
    кнопки называется своим GUID. Повтор — та же ПАРА (клавиша, модификаторы); `skip` — узел кнопки
    формы, которой ставят. Сочетания поля ввода и поля картинки повтор НЕ видит.
    """
    out = []
    for name, element in _design.elements(doc):
        if element.get("type") != "Button" or element is skip:
            continue
        if _form_button_pair(element) == pair:
            out.append(f"{_FORM_SIDE}{name}")
    for name, block in _bars(doc):
        names = {(node.get(BUTTON_ID) or {}).get("guid"): node.get(BTN_NAME)
                 for _s, node in _buttons(block)}
        for other in block.get(ACTIONS) or []:
            if other is action or not isinstance(other, dict):
                continue
            shortcut = (other.get(EXTRAS) or {}).get(SHORTCUT)
            if isinstance(shortcut, dict) and \
                    (shortcut.get(SHORTCUT_KEY), shortcut.get(SHORTCUT_MODIFIERS)) == pair:
                guid = (other.get(ACTION_ID) or {}).get("guid")
                out.append(f"{name}/{names.get(guid) or guid}")
    return out


