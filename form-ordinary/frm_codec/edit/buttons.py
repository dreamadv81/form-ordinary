def _table_bar_hint(doc, bar):
    """Выход для панели без автозаполнения, источник действий которой — табличное поле: включить автозаполнение (слова) либо пусто."""
    node = _bar_element(doc, bar)
    if node is None:
        return ""
    source = (node.get(NAME_BLOCK) or {}).get(ACTION_SOURCE)
    u1 = (node.get("content") or {}).get("u1") or {}
    if u1.get("auto_fill") is True or not isinstance(source, int) or source in (0, 4294967295):
        return ""
    return (f" Выход проще: включите автозаполнение панели (set_property element={bar!r} name=auto_fill value=true) — платформа поставит стандартные "
            "кнопки таблицы сама (Добавить, Изменить, Удалить, Вверх, Вниз…); своими кнопками ставят только свои команды с обработчиком.")


def _refuse_on_auto_fill(doc, bar, standard):
    """Стандартная кнопка на панели с автозаполнением задвоила бы действие, которое платформа ставит сама."""
    node = _bar_element(doc, bar)
    if node is not None and ((node.get("content") or {}).get("u1") or {}).get("auto_fill") is True:
        raise EditError(f"панель {bar!r} с автозаполнением ставит действие «{standard}» сама; своя кнопка задвоит его. Своими кнопками ставят "
                        "только свои команды формы (procedure=… с обработчиком в модуле); убрать стандартные кнопки платформы с панели можно, только "
                        f"выключив автозаполнение (set_property element={bar!r} name=auto_fill value=false) — тогда кнопки придётся ставить все")


def _standard_donor(block, bar, donor, hint=""):
    have = [(button.get(BTN_NAME), _action_of(block, button, bar, button.get(BTN_NAME)))
            for _set, button in _buttons(block)]
    standard = [(name, action) for name, action in have if _spec_mark(action) == STANDARD_MARK]
    if donor is None:
        known = ", ".join(name for name, _a in standard) or "—"
        raise EditError(
            "у этой кнопки сейчас не стандартное действие, а завести стандартное с нуля "
            "нечем: в описании лежит ссылка на ИСТОЧНИК действия (у действий формы — основной "
            "набор кнопок панели, у табличных — «никуда»), и какой источник у нужного действия, "
            f"узнать не из чего. Назовите донора — кнопку этой же панели со стандартным "
            f"действием того же источника. Со стандартным действием здесь: {known}." + hint)
    for name, action in standard:
        if name == donor:
            return action
    known = ", ".join(name for name, _a in standard) or "—"
    raise EditError(f"донор {donor!r} панели {bar!r} стандартного действия не несёт; "
                    f"несут: {known}")


def _set_procedure_action(action, node, bar, button, procedure, text):
    from .. import templates  # ленивo: шаблоны читают файлы
    sample = templates.action("procedure")
    action[ACT_KIND] = copy.deepcopy(sample[ACT_KIND])
    spec = copy.deepcopy(sample[ACT_SPEC])
    spec[HANDLER] = procedure
    spec[DESCRIPTION][DESC_NAME] = procedure
    shown = text if text is not None else _button_text(node)
    for key, value in spec[DESCRIPTION].items():
        # Три локализованные строки описания одинаковы, поэтому порядок строк различить нельзя.
        if isinstance(value, dict) and LS_ITEMS in value and shown is not None:
            set_text(value, shown)
    action[ACT_SPEC] = spec
    extras = dict(action.get(EXTRAS) or {})
    old = extras.get(SHORTCUT)
    extras[SHORTCUT] = copy.deepcopy(sample[EXTRAS][SHORTCUT])
    action[EXTRAS] = _order_extras(extras)
    said = f"{bar}/{button}: действие → процедура {procedure!r}"
    if isinstance(old, dict) and old != extras[SHORTCUT] \
            and (old.get(SHORTCUT_KEY), old.get(SHORTCUT_MODIFIERS)) != (0, 0):
        # Образец процедуры несёт нулевой блок, и прежнее сочетание уходит; сохранит ли его платформа при
        # смене действия в палитре, не проверялось. Нулевой прежний блок — не сочетание: повторная смена на
        # процедуру (нулевой → нулевой) молчит.
        was = _shortcut_words(old.get(SHORTCUT_KEY), old.get(SHORTCUT_MODIFIERS))
        said += (f"; прежнее сочетание {was} заменено нулевым блоком образца процедуры — "
                 "вернуть его: set_button_shortcut после этой операции")
    return said


