def add_button(doc, bar, name, text=None, donor=None, guid=None, standard=None, procedure=None,
               action_donor=None, button_set=-1, unverified=False, kind=None, parent=None, before=None, after=None, index=None):
    """Кнопка в командную панель: узел, запись действия, номер и счётчик головы.

    **`kind`** — вид кнопки: `action` (умолчание: кнопка-действие, как описано ниже), `submenu` (кнопка-подменю вместе с её
    набором кнопок: набор получает код «номер кнопки + 1», хвост набора, где лежит кнопка, называет её) и `separator`
    (разделитель). **`parent`** — имя кнопки-подменю этой панели: кнопка встаёт в её набор, то есть становится пунктом подменю
    (`kind="submenu"` с `parent` — подменю внутри подменю). Устройство — `edit.submenu`.

    **Номер сквозной.** Последний выданный лежит в голове блока действий (`last_number`), хвост набора
    адресует подменю номерами. Новый номер — на единицу больше И головы, И наибольшего у кнопок.
    **GUID** связывает кнопку с её записью действия (по умолчанию случайный).

    **Донор** — кнопка этой же панели, чей узел и запись берутся образцом. Без донора — встроенный
    шаблон (кнопка БЕЗ действия), набор — `button_set` (умолчание — последний; в панели бывает несколько
    наборов, и что в них лежит, решает конфигурация). С донором кнопка ложится туда же, где донор.

    **Владельца** (`owner`) ставит операция: голова ЭТОГО блока, и с донором, и без.

    **Место кнопки в наборе.** Без ключа места кнопка встаёт в конец набора. `before` / `after` — имя соседней кнопки этой панели
    (кнопка ложится в её набор — в подменю тоже; разделитель — такая же кнопка, и считается соседом); `index` — позиция в наборе
    (с нуля, 0 — в начало, число кнопок набора — в конец). Ключ один из трёх; с `button_set` и `parent` вместе `before` / `after`
    не бывают (набор называет сосед), `index` — бывает. Порядок кнопок в файле — порядок на экране. На панели с автозаполнением
    порядок задаёт платформа — отказ; кнопку-подменю и ключи места вместе не ставят (порядок троек хвоста набора не проверялся).
    Уже стоящую кнопку переставляет `move_button`.

    **В МЕНЮ кнопки формы** пункт ложится под границу меню: процедура проверена в предприятии;
    разделитель — пометка с числом (`CORPUS_MENU_ITEMS`); вид, которого в меню корпуса нет (кнопка без
    действия, стандартное действие), — ОТКАЗ, `unverified=True` снимает. Граница спрашивается ДО правки.
    """
    from . import submenu
    block = find_bar(doc, bar)
    if name in [button.get(BTN_NAME) for _s, button in _buttons(block)]:
        raise EditError(f"кнопка {name!r} в панели {bar!r} уже есть")
    if standard is not None:
        _refuse_on_auto_fill(doc, bar, standard)
    head = _head_of(block, bar)
    kind = submenu.button_kind(kind)
    submenu.check_arguments(kind, parent, donor, button_set, standard, procedure, action_donor, text)
    _check_place(doc, bar, kind, parent, button_set, before, after, index)
    if standard is not None:
        code = _standard_code(standard)
        if _spec_mark_is_document(code) and action_donor is None:     # отказ до первой правки: узел кнопки ещё не поставлен
            from . import formactions
            formactions.refuse_wrong_kind(doc, code)
    if kind == "submenu" and id(block) in _menu_blocks(doc):
        raise EditError(f"подменю в меню кнопки формы ({bar!r}) корпус не держит и платформа не проверяла: "
                        "подменю заводят в командной панели")
    if donor is not None:
        _b, target, source, source_action = find_button(doc, bar, donor)
        node, record = copy.deepcopy(source), copy.deepcopy(source_action)
    else:
        from .. import templates
        node, record = templates.button()
        sets = block.get(BUTTON_SETS) or []
        if not sets:
            raise EditError(f"в панели {bar!r} нет ни одного набора кнопок — класть кнопку "
                            "некуда, а заводить набор редактор не умеет "
                            "(не проверялось)")
        if not -len(sets) <= button_set < len(sets):
            raise EditError(f"в панели {bar!r} наборов кнопок {len(sets)} (счёт с нуля, "
                            f"−1 — последний), а назван {button_set}")
        target = sets[button_set]
        if button_set == -1:
            # Последний набор панели без наборов подменю: после подменю «последний» был бы набором подменю.
            target = submenu.last_panel_set(block, sets)
    if parent is not None:
        target, _popup = submenu.parent_set(block, bar, parent)
    position = None
    if before is not None or after is not None:
        _b, target, neighbour, _a = find_button(doc, bar, before if before is not None else after)
        position = (target.get(BUTTONS) or []).index(neighbour) + (1 if after is not None else 0)
    elif index is not None:
        have = len(target.get(BUTTONS) or [])
        if not 0 <= index <= have:
            raise EditError(f"index={index!r}: в наборе кнопок {have}, место называют числом от 0 (в начало) до {have} (в конец); "
                            "кнопки считаются вместе с разделителями")
        position = index
    if kind == "separator":
        submenu.shape_separator(node, record)
    elif kind == "submenu":
        submenu.shape_submenu(node)
    # Вид, который кнопка получит В ИТОГЕ: действие, названное вызовом, побеждает вид образца.
    action_kind = PROCEDURE_KIND if procedure is not None else STANDARD_KIND if standard is not None \
        else submenu.SUBMENU_KIND if kind == "submenu" else _action_kind(block, record)
    tail = _menu_item_bounds(doc, block, action_kind, f"кнопка в МЕНЮ {bar!r}", unverified)
    new_id = {"guid": guid or str(uuid.uuid4())}
    node[BTN_NAME], node[BUTTON_ID] = name, new_id
    node[BTN_OWNER] = {"guid": head}
    record[ACTION_ID] = dict(new_id)
    if text is not None:
        node[BTN_TEXT] = localized(text)
    numbers = [button.get(NUMBER) for _s, button in _buttons(block)
               if isinstance(button.get(NUMBER), int) and not isinstance(button.get(NUMBER), bool)]
    last = block.get(LAST_NUMBER)
    number = max(numbers + [last if isinstance(last, int) and not isinstance(last, bool) else 0]) + 1
    note = ""
    if kind == "submenu":
        # Номер кнопки и код её набора идут подряд, счётчик головы занят обоими.
        number = submenu.next_number(block, head, numbers, last)
        code = submenu.register_submenu(block, head, target, node, record, number)
        block[LAST_NUMBER] = code
        note = submenu.submenu_note(bar, name, number, code)
        if parent is not None:
            note += submenu.nested_note()
    else:
        block[LAST_NUMBER] = number
    node[NUMBER] = number
    if position is None:
        target.setdefault(BUTTONS, []).append(node)
    else:
        target.setdefault(BUTTONS, []).insert(position, node)
    block.setdefault(ACTIONS, []).append(record)
    if standard is not None or procedure is not None:
        _set_action(doc, bar, name, standard=standard, procedure=procedure,
                    donor=action_donor, text=text, unverified=unverified)
        if standard is not None and _spec_mark_is_document(_standard_code(standard)):
            from . import formactions
            tail += _document_view_words(node, _standard_code(standard)) + formactions.bottom_bar_note(doc, _bar_element(doc, bar), _standard_code(standard))
    where = f", пункт подменю {parent!r}" if parent is not None else ""
    if position is not None:
        where += f", место {position + 1} из {len(target[BUTTONS])} в наборе: {_order_words(target)}"
    return f"{bar}: кнопка {name!r}, номер {number}, id {new_id['guid']}{where}" + note + tail


def _order_words(button_set):
    """Порядок кнопок набора одной строкой: подпись (а без неё имя), разделитель — «|»."""
    out = []
    for button in button_set.get(BUTTONS) or []:
        if button.get(BTN_TYPE) == SEPARATOR:
            out.append("|")
        else:
            out.append(_button_text(button) or str(button.get(BTN_NAME)))
    return " ".join(out)


def _check_place(doc, bar, kind, parent, button_set, before, after, index):
    """Ключи места кнопки (`before`, `after`, `index`) — до правки: не больше одного, не вместе с набором, не на панели с автозаполнением."""
    named = [name for name, value in (("before", before), ("after", after), ("index", index)) if value is not None]
    if not named:
        return
    if len(named) > 1:
        raise EditError(f"место кнопки называет один ключ из before / after / index, а названо {', '.join(named)}")
    node = _bar_element(doc, bar)
    if node is not None and ((node.get("content") or {}).get("u1") or {}).get("auto_fill") is True:
        raise EditError(f"панель {bar!r} с автозаполнением: порядок её стандартных кнопок задаёт платформа, а свою кнопку она ставит в конец — "
                        f"ключ {named[0]} здесь не действует; чтобы расставить кнопки самому, выключите автозаполнение "
                        f"(set_property element={bar!r} name=auto_fill value=false) и поставьте все кнопки")
    if kind == "submenu":
        raise EditError(f"подменю с ключом места ({named[0]}) не ставится: хвост набора перечисляет подменю тройками по номеру, и порядок троек "
                        "относительно порядка кнопок не проверялся; поставьте подменю в конец (без ключа места) и пункты в него")
    if named[0] != "index" and (parent is not None or button_set != -1):
        raise EditError(f"{named[0]}: набор называет соседняя кнопка, поэтому parent и button_set вместе с ним не бывают; "
                        "назовите соседа из нужного набора либо используйте index")
    if named[0] != "index":
        who = before if before is not None else after
        if not isinstance(who, str) or not who:
            raise EditError(f"{named[0]} — имя соседней кнопки панели {bar!r}, а пришло {who!r}")
    elif not isinstance(index, int) or isinstance(index, bool):
        raise EditError(f"index — номер места числом, а пришло {index!r}")


def move_button(doc, bar, name, before=None, after=None, index=None):
    """Кнопка на другое место в её же наборе: порядок кнопок в файле — порядок на экране.

    Место называет один ключ: `before` / `after` — имя соседней кнопки (в том же наборе: между наборами и подменю кнопки не переносят —
    `remove_button` и `add_button` с `parent`), `index` — позиция в наборе после переноса (с нуля; кнопки считаются вместе с разделителями).
    Номер, имя, запись действия, текст и номер кнопки по умолчанию панели не меняются. На панели с автозаполнением порядок задаёт
    платформа — отказ; кнопку-подменю не переставляют (порядок троек хвоста набора не проверялся).
    """
    block, button_set, node, _action = find_button(doc, bar, name)
    named = [key for key, value in (("before", before), ("after", after), ("index", index)) if value is not None]
    if len(named) != 1:
        raise EditError(f"move_button: место называет ровно один ключ из before / after / index, а названо {', '.join(named) or 'ничего'}")
    _check_place(doc, bar, "action", None, -1, before, after, index)
    if node.get(BTN_TYPE) == POPUP:
        raise EditError(f"кнопка {name!r} — подменю: порядок троек хвоста набора относительно порядка кнопок не проверялся, подменю не переставляют")
    buttons = button_set[BUTTONS]
    was = buttons.index(node)
    if index is not None:
        if not 0 <= index < len(buttons):
            raise EditError(f"index={index!r}: в наборе кнопок {len(buttons)}, место называют числом от 0 до {len(buttons) - 1}; "
                            "кнопки считаются вместе с разделителями")
        want = index
    else:
        who = before if before is not None else after
        if who == name:
            raise EditError(f"{'before' if before is not None else 'after'}={who!r}: кнопка не может стоять рядом сама с собой")
        _b, other_set, other, _o = find_button(doc, bar, who)
        if other_set is not button_set:
            raise EditError(f"кнопка {name!r} лежит в наборе (код {button_set.get(SET_CODE)}), а {who!r} — в другом (код {other_set.get(SET_CODE)}): "
                            "между наборами и подменю кнопки не переносят — remove_button и add_button с parent")
        rest = [b for b in buttons if b is not node]
        want = rest.index(other) + (1 if after is not None else 0)
    buttons.remove(node)
    buttons.insert(want, node)
    if want == was:
        return f"{bar}: кнопка {name!r} уже на месте {want + 1}; порядок: {_order_words(button_set)}"
    return f"{bar}: кнопка {name!r} перенесена с места {was + 1} на место {want + 1} из {len(buttons)}; порядок: {_order_words(button_set)}"


def _head_of(block, bar):
    """GUID головы блока действий — тот, что кнопка блока несёт владельцем. Отказ, если его нет.

    Без головы владельца поставить нечем, а оставить нуль шаблона значило бы собрать кнопку, каких
    корпус не держит.
    """
    head = block.get(ACTIONS_GUID)
    guid = head.get("guid") if isinstance(head, dict) else None
    if not isinstance(guid, str):
        raise EditError(f"у блока действий {bar!r} нет GUID головы — а его кнопка несёт "
                        "владельцем у любой кнопки. Форму надо "
                        "чинить, а не править")
    return guid


def remove_button(doc, bar, name):
    """Кнопка из панели: её узел и её запись действия. Счётчик головы НЕ опускается.

    Счётчик — «последний ВЫДАННЫЙ номер»: платформа его назад не двигает, а опустить значило бы выдать
    следующей кнопке номер, уже записанный у подменю. Номер удалённой кнопки не возвращается; ИМЯ
    переиспользуется — это разные счётчики.

    Приём проверен на кнопке со СТАНДАРТНЫМ действием; прочие виды есть в корпусе
    (`ON_CORPUS["remove_button/action"]`), отчёт называет вид словом. **Кнопка-ПОДМЕНЮ уходит вместе с набором,
    который она открывала, и пунктами набора** (подменю внутри — так же); тройка кнопки убирается из хвоста набора, где она
    лежала, а связи контекстных меню формы, называвшие этот набор, снимаются (`edit.ctxmenu.forget_sets`) с отчётом.
    Набор, на который ссылается ещё одна запись действия, остаётся. Набор с владельцем не головой блока остаётся без
    владельца, и отчёт это называет.
    """
    from . import submenu, ctxmenu
    block, button_set, node, action = find_button(doc, bar, name)
    kind, seen = _action_kind_words(block, action)
    plan, kept = ([], [])
    if _action_kind(block, action) == submenu.SUBMENU_KIND:
        plan, kept = submenu.plan_remove(block, _head_of(block, bar), action)
    button_set[BUTTONS].remove(node)
    block[ACTIONS].remove(action)
    said = (f"{bar}: кнопка {name!r} убрана, {LAST_NUMBER} оставлен "
            f"{block.get(LAST_NUMBER)}")
    if plan or kept:
        said += "; " + "; ".join(submenu.apply_remove(block, button_set, node, plan, kept))
        said += "".join("; " + words for words in ctxmenu.forget_sets(doc, block, [pair for pair, _t, _e in plan]))
    orphan = _orphan_set(block, action)
    if orphan is not None:
        said += f"; набор кнопок {orphan} больше ничей — его открывала эта кнопка"
    if _spec_mark(action) != ROUND5_REMOVED_ACTION:
        said += _on_corpus("remove_button/action", f"у кнопки {kind}", seen)
    if id(block) in _menu_blocks(doc):
        said += _on_corpus("button/menu-remove",
                           f"кнопка убрана из МЕНЮ {bar!r}, а не из командной панели",
                           CORPUS_MENUS[0], counted="меню кнопок")
    return said


def _button_sets_by_pair(block):
    """`{(GUID владельца, код): набор}` — наборы кнопок панели, как их адресуют ссылки."""
    out = {}
    for item in block.get(BUTTON_SETS) or []:
        ref = item.get(SET_REF) if isinstance(item, dict) else None
        if isinstance(ref, dict):
            out[(ref.get("guid"), item.get(SET_CODE))] = item
    return out


def _action_kind_words(block, action):
    """`(вид действия кнопки СЛОВАМИ, сколько таких в корпусе)` — для отчёта об удалении.

    Вид определяется по метке описания: по ней же карта выбирает, как читать запись. Служебные пары
    названы словом (`validate.SERVICE_REFS`); число — у `CORPUS_ACTION_KINDS`. `None` — метка, которой
    карта не знает.
    """
    kind = _action_kind(block, action)
    if kind == PROCEDURE_KIND:
        return f"{kind} {action[ACT_SPEC].get(HANDLER)!r}", CORPUS_ACTION_KINDS[kind]
    if kind is None:
        spec = action.get(ACT_SPEC)
        return f"действие вида {spec.get(SPEC_MARK) if isinstance(spec, dict) else None}", None
    return kind, CORPUS_ACTION_KINDS.get(kind)


def _action_kind(block, action):
    """Вид действия записи КЛЮЧОМ `CORPUS_ACTION_KINDS`; `None` — метки карта не знает.

    Одно место на два вопроса: как назвать вид в отчёте об удалении (`_action_kind_words`) и какой
    пункт кладётся в меню кнопки (`_menu_item_bounds`).
    """
    spec = action.get(ACT_SPEC)
    mark = spec.get(SPEC_MARK) if isinstance(spec, dict) else None
    if mark == STANDARD_MARK:
        return STANDARD_KIND
    if mark == PROCEDURE_MARK:
        return PROCEDURE_KIND
    pair = ((spec.get(REF_ID) or {}).get("guid"), spec.get(REF_CODE)) \
        if isinstance(spec, dict) else (None, None)
    if pair in _button_sets_by_pair(block):
        return "кнопка-подменю"
    if pair in validate.SERVICE_REFS:
        return validate.SERVICE_REFS[pair]
    if mark == REF4_MARK:
        return "ссылка вида 4"
    if mark == schema.MAP["ActionSpec.v1"].fields[0].const:
        return "ссылка, набора которой в панели нет"
    return None


def _orphan_set(block, action):
    """Набор кнопок, который после удаления этой записи не открывает никто; иначе `None`.

    Считается ПОСЛЕ удаления и по остаткам, а не по виду записи: тот же набор бывает назван второй
    записью (у панели с двумя ходами в одно подменю).
    """
    spec = action.get(ACT_SPEC)
    sets = _button_sets_by_pair(block)
    gone = [pair for pair in validate._refs_in(spec, REF_ID, REF_CODE) if pair in sets]
    left = {pair for item in block.get(ACTIONS) or []
            for pair in validate._refs_in(item.get(ACT_SPEC), REF_ID, REF_CODE)}
    for pair in gone:
        if pair not in left:
            held = len(sets[pair].get(BUTTONS) or [])
            return f"{pair[1]} (кнопок в нём {held})"
    return None


def _times(count):
    """«1 раз», «3 раза», «5 раз», «12 раз», «22 раза» — число с формой слова «раз»."""
    tail = count % 100
    if 11 <= tail <= 14:
        return f"{count} раз"
    return f"{count} раза" if 2 <= count % 10 <= 4 else f"{count} раз"


