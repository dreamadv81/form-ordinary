def _menu_item_bounds(doc, block, kind, what, unverified):
    """Граница пункта МЕНЮ кнопки формы: хвост отчёта либо отказ.

    Вне меню — пустая строка. В меню: процедура проверена в предприятии (пометки нет); вид, который в
    меню корпуса есть (`CORPUS_MENU_ITEMS`: разделитель), — пометка с числом; вида, которого нет
    (кнопка без действия, стандартное действие, подменю), — ОТКАЗ, `unverified=True` снимает.
    """
    if id(block) not in _menu_blocks(doc) or kind == ROUND8_MENU_ITEM:
        return ""
    seen = CORPUS_MENU_ITEMS.get(kind)
    if seen is None and not unverified:
        known = ", ".join(CORPUS_MENU_ITEMS)
        raise EditError(
            f"{what}: пункт вида «{kind}» в меню кнопок образцов форм не встречается "
            f"(там есть: {known}), а в меню проверены только пункты-процедуры. "
            "Форму-результат не подтверждает ни платформа, ни образцы форм. Дайте пункту процедуру "
            "(procedure=…) — либо unverified=True: отказ снимается, исход не проверялся")
    return _on_corpus("button/menu", f"{what} — {kind}", seen)
