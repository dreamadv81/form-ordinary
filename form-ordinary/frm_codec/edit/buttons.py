def _extras_bounds(bit, where, kind, what, unverified, way=None):
    """Граница вида действия у блока по биту: хвост отчёта либо ОТКАЗ.

    Корпус держит вид — пометка с числом; не держит, а платформа писала сама — пометка с формой; ни
    того ни другого — отказ, снимаемый `unverified=True`. Исключение — стандартное действие (`way` —
    способ вызова, ключ `ROUND16_BUTTON`): картинка из библиотеки и сочетание проверены в предприятии.
    Код и файл у стандартного действия остаются отказом.
    """
    table = CORPUS_BUTTON_PICTURES if bit == PICTURE_BIT else CORPUS_BUTTON_SHORTCUTS
    variant = f"{'set_button_picture' if bit == PICTURE_BIT else 'set_button_shortcut'}/kind"
    seen = table.get((where, kind))
    if seen is not None:
        return _on_corpus(variant, what, seen)
    platform = PLATFORM_BUTTON_EXTRAS.get((bit, kind)) if where == "панель" else None
    if platform is not None:
        return (f"; {what}: в образцах форм такого нет, а платформа это писала сама "
                f"({platform}); {ON_CORPUS[variant]}")
    if (bit, where, kind, way) in ROUND16_BUTTON:
        return ""
    if not unverified:
        known = ", ".join(f"{k} ({w})" for (w, k), n in sorted(table.items(),
                                                               key=lambda kv: -kv[1]))
        why = _STANDARD_OWN[bit] if kind == STANDARD_KIND else (
            "в меню кнопок непустого сочетания у пунктов нет"
            if where == "меню" and bit == SHORTCUT else
            f"у записи вида «{kind}» ({where}) такого блока нет")
        raise EditError(
            f"{what}: {why}; где блок есть — {known}. Форму-результат не "
            "подтверждает ни платформа, ни корпус. Позвать всё же можно — unverified=True: отказ "
            "снимается, исход не проверялся")
    return _on_corpus(variant, what, None)


def _picture_words(picture):
    """Картинка словами: откуда она — для отчёта о прежней и новой."""
    if not isinstance(picture, dict):
        return "—"
    source, ref = picture.get(PIC_SOURCE), picture.get(PIC_REF)
    ref = ref if isinstance(ref, dict) else {}
    guid = ref.get(PICREF_GUID)
    guid = guid.get("guid") if isinstance(guid, dict) else None
    if source == 0:
        return "пустая (источник 0)"
    if source == 3:
        return "встроенная из файла" + (f", GUID {guid}" if guid else "")
    if source == 1 and guid:
        return f"из библиотеки {guid}"
    if source == 1:
        name = PICTURE_CODE_NAMES.get(ref.get(PICREF_CODE))
        return f"стандартная, код {ref.get(PICREF_CODE)}" + (f" («{name}»)" if name else "")
    return f"источник {source}"


def _picture_block(version, source, ref, body=None, mark=None):
    """Блок картинки записи действия — метка по версии формы, хвост по метке, тело по источнику.
    Позиции 3–6 — как пишет платформа у картинки из библиотеки (`"", -1, -1, 1`); у встроенной на 6
    ноль. Смысл 4–6 карта не знает; операция пишет только строение «без них».
    """
    mark = mark if mark is not None else PICTURE_MARKS.get(version)
    if mark is None:
        raise EditError(
            f"версия формы {version!r}: метка блока картинки ходит за ней (3 у версии 10, 4 у "
            "13, 15 и 16), а для этой версии пары нет — какую метку писать, не проверялось")
    block = {PIC_MARK: mark, PIC_SOURCE: source, PIC_REF: ref, _maybe("Picture", 3): "",
             _maybe("Picture", 4): -1, _maybe("Picture", 5): -1,
             _maybe("Picture", 6): 0 if body is not None else 1}
    if body is None:
        block[_maybe("Picture", 7)] = 0
        tail = 8
    else:
        block[_maybe("Picture", 7)] = [[{"base64": body}]]
        block[_maybe("Picture", 8)] = 0
        tail = 9
    if mark == 4:
        block[_maybe("Picture", tail)] = ""
    return block


_GUID_RE = _re.compile(r"^[0-9a-fA-F]{8}(-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}$")


def _library_ref(library):
    guid = library.get("guid") if isinstance(library, dict) and set(library) == {"guid"} \
        else library
    if not isinstance(guid, str) or not _GUID_RE.match(guid):
        raise EditError(f"library — GUID картинки (строкой или {{\"guid\": …}}), а пришло "
                        f"{library!r}")
    guid = guid.lower()
    if set(guid) <= set("0-"):
        raise EditError("library: нулевой GUID — это «картинки нет», а не картинка; снимают её "
                        "remove=true")
    return {PICREF_CODE: 0, PICREF_GUID: {"guid": guid}}, guid


def _library_by_name(library, code):
    """`library=<имя картинки платформы>` → GUID (у картинки есть GUID) либо `code` (у картинки код без GUID) по каталогу `platform_pictures`; GUID и не строка проходят как есть.
    Имя вне каталога и не GUID — отказ словами."""
    if not isinstance(library, str) or _GUID_RE.match(library):
        return library, code
    record = _platform_pictures.record(library)
    if record is None:
        raise EditError(f"library — GUID картинки либо имя картинки платформы из каталога (299 имён: Печать, Записать, Закрыть, Календарь…), а пришло {library!r}: "
                        "такого имени в каталоге нет")
    if code is not None:
        return library, code            # два способа сразу: отказ поставит общая проверка ниже
    if record["guid"]:
        return record["guid"], None
    return None, record["code"]


# Подпись вида и длина заголовка, без которой размер и признак «целого» не прочесть.
_IMAGE_SIGNATURES = (("BMP", b"BM", 30), ("PNG", b"\x89PNG\r\n\x1a\n", 24),
                     ("ICO", b"\x00\x00\x01\x00", 22), ("GIF", b"GIF8", 10))
_IMAGE_HEADER = {kind: header for kind, _signature, header in _IMAGE_SIGNATURES}


def _image_kind(data):
    """`(вид, размер «Ш×В» или None, файл целый)` — по подписи файла; вид `None` — не узнан.

    «Целый»: длина из заголовка у BMP и ICO, завершитель у PNG (`IEND`) и GIF (`;`); у ICO каталог
    обязан помещаться в файл, а картинки — лежать ЗА каталогом. Файл короче заголовка своего вида —
    того же вида и НЕ целый: под `unverified` неполный файл не снимается никогда.
    """
    for kind, signature, header in _IMAGE_SIGNATURES:
        if data[:len(signature)] == signature and len(data) >= header:
            break
        if data and len(data) < header and (data.startswith(signature)
                                            or signature.startswith(data)):
            return kind, None, False
    else:
        return None, None, False
    if kind == "BMP":
        width, height = _struct.unpack_from("<ii", data, 18)
        return kind, f"{width}×{abs(height)}", _struct.unpack_from("<I", data, 2)[0] == len(data)
    if kind == "PNG":
        width, height = _struct.unpack_from(">II", data, 16)
        return kind, f"{width}×{height}", data.endswith(b"IEND\xaeB`\x82")
    if kind == "GIF":
        width, height = _struct.unpack_from("<HH", data, 6)
        return kind, f"{width}×{height}", data.endswith(b";")
    count = _struct.unpack_from("<H", data, 4)[0]
    table = 6 + 16 * count
    if count == 0 or table > len(data):
        return kind, None, False
    end, sizes, inside = 0, [], True
    for i in range(count):
        width, height = data[6 + 16 * i], data[7 + 16 * i]
        size, offset = _struct.unpack_from("<II", data, 14 + 16 * i)
        inside = inside and size > 0 and offset >= table
        end = max(end, size + offset)
        sizes.append(f"{width or 256}×{height or 256}")
    return kind, "+".join(sizes), inside and end == len(data)


def _file_picture(version, file, data, unverified, mark=None, corpus_words=True):
    """`(блок картинки, слова)` встроенной картинки из файла.

    Пустой и неполный файл — отказ ВСЕГДА. BMP, PNG, ICO и GIF пишутся одним строением «файл»: платформа
    записала его всем четырём (`FILE_KINDS_TRIED`; образцы форм держат BMP и PNG). Неузнанный вид —
    отказ, снимаемый `unverified`. `mark` — метка блока из узла-владельца (у кнопки панели её даёт
    версия формы).
    """
    inside = "BMP, PNG, ICO и GIF"
    if not data:
        raise EditError(f"file: файл {file!r} пуст — вкладывать нечего")
    kind_of, size, whole = _image_kind(data)
    if kind_of is None and not unverified:
        raise EditError(
            f"file: вид файла {file!r} не узнан (подпись {data[:4].hex()}); в строении, которое "
            f"пишет операция, бывают {inside}, и тело — файл целиком. unverified=True снимает отказ")
    if kind_of is not None and not whole:
        raise EditError(
            f"file: {kind_of} в {file!r} неполный — "
            + ("файл короче заголовка своего вида" if len(data) < _IMAGE_HEADER[kind_of] else
               "длина из заголовка, каталог или завершитель не сходятся с файлом")
            + "; тело записи — файл целый, и этот отказ unverified не снимает")
    words = []
    if kind_of is None:
        words.append(f"вид файла: {UNSEEN_NOTE}")
    else:
        seen = CORPUS_PICTURE_SIZES.get((kind_of, size))
        tested = (kind_of, size) in FILE_KINDS_TRIED
        if corpus_words and kind_of in CORPUS_PICTURE_FILES:
            words.append(f"{kind_of} {size} в этом строении встречается в образцах форм" if seen else
                         f"размера {size} у {kind_of} в этом строении в образцах форм нет (там "
                         + ", ".join(f"{k} {s}" for (k, s) in CORPUS_PICTURE_SIZES)
                         + "): что покажет платформа, не проверялось")
        elif tested:
            words.append(FILE_NOTE)
        else:
            words.append(f"{kind_of} {size}: в конфигураторе были "
                         + ", ".join(f"{k} {s}" for (k, s) in FILE_KINDS_TRIED)
                         + "; что покажет платформа, не проверялось")
    picture = _picture_block(version, 3, {PICREF_CODE: 0},
                             _base64.b64encode(data).decode("ascii"), mark)
    shape = (f"из файла: {kind_of or 'вид не узнан'}" + (f" {size}" if size else "")
             + f", {len(data)} байт; строение — встроенная без GUID (виды файла: {inside}); "
             + "; ".join(words))
    return picture, shape


def read_picture_file(file):
    """Байты файла картинки — отказ словами, если файл не прочитан."""
    try:
        with open(file, "rb") as handle:
            return handle.read()
    except (OSError, TypeError, ValueError) as e:
        raise EditError(f"file: файл картинки не прочитан — {e}") from None


