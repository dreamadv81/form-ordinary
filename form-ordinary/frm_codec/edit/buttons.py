def _form_button_pair(element):
    """`(клавиша, модификаторы)` непустого сочетания кнопки формы, иначе `None`."""
    body = (element.get(CONTENT) or {}).get(FORM_BUTTON_BODY)
    shortcut = body.get(SHORTCUT_FIELD) if isinstance(body, dict) else None
    if not isinstance(shortcut, dict):
        return None
    pair = (shortcut.get(SHORTCUT_KEY), shortcut.get(SHORTCUT_MODIFIERS))
    return None if pair == (0, 0) else pair


def _order_of(doc):
    """`{имя элемента: индекс в списке элементов формы}` — положение, по которому называют победителя в
    повторе «форма ↔ панель»; первое вхождение имени.
    """
    out = {}
    for index, (name, _element) in enumerate(_design.elements(doc)):
        out.setdefault(name, index)
    return out


def _table_bound_panels(doc):
    """Имена панелей, привязанных к табличному полю (`name_block/action_source` панели — `index`
    элемента-таблицы; у панелей формы источника нет: `0xFFFFFFFF` и `0`). Победитель пары «кнопка
    формы ↔ панель ТАБЛИЦЫ» — по фокусу.
    """
    elements = list(_design.elements(doc))
    tables = {e.get("index") for _n, e in elements if e.get("type") == "TableBox"}
    out = set()
    for name, element in elements:
        block = element.get("name_block")
        if element.get("type") == "CommandBar" and isinstance(block, dict) and block.get("action_source") in tables:
            out.add(name)
    return out


def _side_index(order, place):
    """Индекс элемента стороны: кнопка формы («кнопки формы Имя» или просто имя) — сам элемент,
    кнопка панели («блок/кнопка») — элемент-панель или кнопка-меню; не нашёлся — `None`.
    """
    if place.startswith(_FORM_SIDE):
        return order.get(place[len(_FORM_SIDE):])
    return order.get(place.split("/", 1)[0]) if "/" in place else order.get(place)


def _form_panel_here(doc, pair, forms, panel):
    """Кто победит в ЭТОЙ паре «форма ↔ панель»: срабатывает кнопка, чей элемент находится в списке элементов
    РАНЬШЕ. Берётся НАИМЕНЬШИЙ индекс каждой стороны (`_order_of`); индекс — сквозной обход дерева
    (`design.elements`). Не нашёлся индекс или индексы равны — победителя слова не называют. Панель
    таблицы — другая ветка: по фокусу (`REPEAT_OTHER_PANELS`). `pair` оставлен в подписи: вызывающие его
    передают.
    """
    order = _order_of(doc)
    tables = _table_bound_panels(doc)
    if any(place.split("/", 1)[0] in tables for place in panel):
        return ("для этой пары: панель привязана к табличному полю — победителя называет ФОКУС, не "
                "положение: фокус в таблице — кнопка панели, фокус в поле ввода — кнопка формы "
                "(«фокус против положения» не разведены: панель таблицы находится в списке первой)")
    form_ats = [i for i in (_side_index(order, f) for f in forms) if i is not None]
    panel_ats = [i for i in (_side_index(order, p) for p in panel) if i is not None]
    form_at, panel_at = (min(form_ats) if form_ats else None), (min(panel_ats) if panel_ats else None)
    if form_at is None or panel_at is None or form_at == panel_at:
        return "для этой пары: положение в списке элементов здесь не установить — победителя слова не называют"
    winner = "формы" if form_at < panel_at else "панели"
    return (f"для этой пары: по положению в списке элементов (кнопка формы {form_at}, панель {panel_at}) — "
            f"кнопка {winner}")


class _Entry(NamedTuple):
    pair: tuple
    side: str  # «форма» или «панель»
    place: str  # имя кнопки формы либо `блок/кнопка`
    block: object  # `id` блока действий (у панели), у кнопки формы — `None`
    target: object  # к чему ведёт запись: обработчик либо вся спецификация действия


def _target(action):
    spec = action.get(ACT_SPEC)
    handler = spec.get(HANDLER) if isinstance(spec, dict) and spec.get(SPEC_MARK) == PROCEDURE_MARK \
        else None
    return ("proc", handler) if handler is not None else ("spec", repr(spec))


def _shortcut_entries(doc):
    """Непустые сочетания формы: `[_Entry]`; сторона «форма» — кнопка формы (место — имя), «панель» —
    запись действия панели или меню (место — `блок/кнопка`, блок и цель записи — для разбора повторов).
    """
    out = []
    for name, element in _design.elements(doc):
        if element.get("type") == "Button":
            pair = _form_button_pair(element)
            if pair is not None:
                out.append(_Entry(pair, "форма", name, None, None))
    for name, block in _bars(doc):
        names = {(node.get(BUTTON_ID) or {}).get("guid"): node.get(BTN_NAME)
                 for _s, node in _buttons(block)}
        for action in block.get(ACTIONS) or []:
            shortcut = (action.get(EXTRAS) or {}).get(SHORTCUT) if isinstance(action, dict) \
                else None
            if isinstance(shortcut, dict):
                pair = (shortcut.get(SHORTCUT_KEY), shortcut.get(SHORTCUT_MODIFIERS))
                if pair != (0, 0):
                    guid = (action.get(ACTION_ID) or {}).get("guid")
                    out.append(_Entry(pair, "панель", f"{name}/{names.get(guid) or guid}",
                                      id(block), _target(action)))
    return out


def same_class_repeats(doc):
    """Повторы ВНУТРИ одного класса: `[(пара, класс, [места], вывод)]`.

    Форма ↔ форма — две и более кнопки: `"one"` (срабатывает одна). Панель ↔ панель режется по блоку:
    несколько записей ОДНОЙ панели с РАЗНЫМИ обработчиками — `"one"`; РАЗНЫХ панелей с разными
    обработчиками — `"panels"` (побеждает расположенная раньше); один обработчик — молчание. Одно место для
    `validate` и отчёта (`_panel_twin_words`).
    """
    found = {}
    for entry in _shortcut_entries(doc):
        found.setdefault((entry.pair, entry.side), []).append(entry)
    out = []
    for (pair, side), entries in found.items():
        if len(entries) < 2:
            continue
        if side == "форма":
            out.append((pair, side, [e.place for e in entries], "one"))
            continue
        if len({e.target for e in entries}) < 2:
            continue  # один обработчик: молчание
        by_block = {}
        for e in entries:
            by_block.setdefault(e.block, []).append(e)
        for group in by_block.values():
            if len(group) > 1 and len({e.target for e in group}) > 1:
                out.append((pair, side, [e.place for e in group], "one"))
        if len(by_block) > 1:
            out.append((pair, side, [e.place for e in entries], "panels"))
    return out


def form_panel_repeats(doc):
    """Пары «кнопка формы ↔ кнопка панели» с одной комбинацией: `[(пара, [кнопки формы],
    [кнопки панели])]`, по порядку первой кнопки формы. Кнопка панели — запись действия (панель
    или меню кнопки формы), называется `блок/кнопка`. Одно место для отчёта операций и `validate`.
    """
    found = {}
    for name, element in _design.elements(doc):
        if element.get("type") != "Button":
            continue
        pair = _form_button_pair(element)
        if pair is None:
            continue
        panel = [twin for twin in _shortcut_twins(doc, None, pair)
                 if not twin.startswith(_FORM_SIDE)]
        if panel:
            found.setdefault(pair, ([], panel))[0].append(name)
    return [(pair, forms, panel) for pair, (forms, panel) in found.items()]


def _panel_twin_words(doc, pair, place):
    """Слова о повторе у кнопки ПАНЕЛИ `place` с другими записями панелей той же пары — тем же
    разрезом, что у `same_class_repeats` (одна панель — «одна из них», разные панели — расположенная раньше,
    один обработчик — не важно). Пусто, если других записей панелей нет.
    """
    entries = [e for e in _shortcut_entries(doc) if e.pair == pair and e.side == "панель"]
    mine = next((e for e in entries if e.place == place), None)
    others = [e for e in entries if e is not mine]
    if mine is None or not others:
        return []
    words = []
    if any(o.block == mine.block and o.target != mine.target for o in others):
        words.append("между кнопками панели " + REPEAT_SAME_CLASS)
    if any(o.block != mine.block and o.target != mine.target for o in others):
        words.append(REPEAT_OTHER_PANELS)
    if not words and all(o.target == mine.target for o in others):
        words.append(REPEAT_SAME_HANDLER)
    return words


def _twin_words(twins, mine, doc=None, pair=None, place=None):
    """Слова о повторе — по тому, КАКИЕ стороны повторились. `mine` — чью кнопку ставят, `place` —
    её место (форма: имя, панель: `блок/кнопка`); `doc` и `pair` — форма и сочетание: по ним слова
    называют победителя ЭТОЙ пары «форма ↔ панель» по положению в списке (`_form_panel_here`).
    """
    form = [twin for twin in twins if twin.startswith(_FORM_SIDE)]
    panel = [twin for twin in twins if not twin.startswith(_FORM_SIDE)]
    words = []
    if mine == "панель" and form:
        words.append("ПРЕДУПРЕЖДЕНИЕ: по сочетанию сработает одна из двух кнопок, не обязательно "
                     "эта — " + REPEAT_FORM_PANEL)
    if mine == "форма" and panel:
        words.append("по сочетанию сработает одна из двух кнопок, не обязательно эта — "
                     + REPEAT_FORM_PANEL)
    if (mine == "панель" and form or mine == "форма" and panel) and doc is not None:
        forms, panels = (form, [place] + panel) if mine == "панель" else ([place] + form, panel)
        words.append(_form_panel_here(doc, pair, forms, panels))
    if mine == "форма" and form:
        words.append("между кнопками формы " + REPEAT_SAME_CLASS)
    if mine == "панель" and panel and doc is not None:
        words += _panel_twin_words(doc, pair, place)
    return "; " + "; ".join(words) if words else ""


