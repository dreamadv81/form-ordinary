#
# `set_property` ставит поле карты ПО ИМЕНИ (как в `FORMAT.md`) у элемента, у колонки или у вложенного
# элемента колонки: проверка значения картой, граница «что видела платформа», отказ там, где у поля
# своя операция или оно — флаг строения, согласованные поля. Обход полей и таблица границы — `props`.
def _named(type_name, name):
    """Имя поля узла карты. При импорте имя проверяется, как у `_at`: если правило устарело вместе с
    картой, об этом сообщается сразу.
    """
    names = {getattr(slot, "name", None) for _addr, slot in schema.node_slots(schema.MAP[type_name])}
    if name not in names:
        raise schema.SchemaError(f"редактор ждёт у {type_name} поле {name!r}, а карта его не держит; "
                                 "правило устарело вместе с картой — поправьте его вместе с ней")
    return type_name, name

