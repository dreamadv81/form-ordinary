def _modifier_words(modifiers):
    """Модификаторы словами в порядке палитры («Ctrl+Alt+Shift»); лишний бит — числом."""
    if not isinstance(modifiers, int) or isinstance(modifiers, bool):
        return f"модификаторы {modifiers!r}"
    names = sorted((name for name, bit in SHORTCUT_MODIFIER_BITS.items() if modifiers & bit),
                   key=["Ctrl", "Alt", "Shift"].index)
    rest = modifiers & ~sum(SHORTCUT_MODIFIER_BITS.values())
    return "+".join(names + ([f"бит {rest}"] if rest else []))


def _shortcut_words(key, modifiers):
    """Сочетание словами: «Ctrl+Shift+C»; код без имени в таблице — числом."""
    key_name = next((name for name, code in SHORTCUT_KEY_CODES.items() if code == key),
                    f"код {key}")
    if key_name.startswith("_") and key_name[1:].isdigit():
        key_name = key_name[1:]  # `_2` — внутреннее имя клавиши; человек читает «Alt+2»
    mods = _modifier_words(modifiers)
    return f"{mods}+{key_name}" if mods else key_name


def _shortcut_codes(key, modifiers, unverified):
    """`(код клавиши, код модификаторов, [слова])` — по именам; невиданное корпусом — отказ."""
    if not isinstance(key, str) or key not in SHORTCUT_KEY_CODES:
        hint = (" — Break не пишется: клавише у Windows отвечают два кода, в образцах форм нет ни "
                "одного, и выбрать нечем" if key == "Break" else "")
        raise EditError(
            f"клавиши {key!r} в таблице нет{hint}. Клавиши называются как значения перечисления "
            "Клавиша: A…Z, _0…_9, F1…F12, Num0…Num9, NumAdd, NumSubtract, NumMultiply, "
            "NumDivide, NumDecimal, BackSpace, Space")
    if modifiers is None:
        names = []
    elif isinstance(modifiers, str):
        names = modifiers.split("+")
    elif isinstance(modifiers, (list, tuple)):
        names = list(modifiers)
    else:
        raise EditError(f"modifiers — список имён (\"Ctrl\", \"Shift\", \"Alt\") или строка "
                        f"«Ctrl+Shift», а пришло {modifiers!r}")
    unknown = [name for name in names if name not in SHORTCUT_MODIFIER_BITS]
    if unknown or len(set(names)) != len(names):
        raise EditError(f"modifiers: {names!r} — имена модификаторов Ctrl, Shift, Alt (свойства "
                        "объекта СочетаниеКлавиш), каждое не больше раза")
    code, mods = SHORTCUT_KEY_CODES[key], sum(SHORTCUT_MODIFIER_BITS[name] for name in names)
    words = []
    seen_key = CORPUS_SHORTCUT_KEYS.get(code)
    if seen_key is None and code not in PLATFORM_SHORTCUT_KEYS:
        if not unverified:
            raise EditError(
                f"клавиши {key} (код {code}) в сочетаниях образцов форм нет, и платформа её не писала. Код взят по "
                "таблице виртуальных кодов Windows, как и прочие, но этот — не видел никто. "
                "unverified=True снимает отказ")
        words.append(f"клавиша {key} (код {code}): {UNSEEN_NOTE}")
    elif seen_key is None:
        words.append(f"клавиши {key} в образцах форм нет, а платформа её писала сама")
    seen_mods = CORPUS_SHORTCUT_MODIFIERS.get(mods)
    if seen_mods is None:
        if not unverified:
            known = ", ".join(_modifier_words(m) or "без модификаторов"
                              for m in CORPUS_SHORTCUT_MODIFIERS)
            raise EditError(
                f"модификаторов {'+'.join(names)} (код {mods}) в сочетаниях образцов форм нет; "
                f"есть {known}. unverified=True снимает отказ")
        words.append(f"модификаторы {'+'.join(names)} (код {mods}): {UNSEEN_NOTE}")
    if "Alt" in names:
        words.append(ALT_WORDS)
    return code, mods, words


def set_button_shortcut(doc, bar=None, button=None, key=None, modifiers=None, remove=False,
                        unverified=False, element=None):
    """Сочетание клавиш кнопки панели: блок по биту 8 записи ДЕЙСТВИЯ; у кнопки ФОРМЫ — `element` вместо
    `bar` и `button` (`_form_button_shortcut`).

    `key` — имя значения перечисления `Клавиша` (`F5`, `C`, `_1`, `Num0`…), `modifiers` — список из
    `Ctrl`, `Shift`, `Alt` (или строка `Ctrl+Shift`). Коды — `SHORTCUT_KEY_CODES`, модификаторы — биты
    8, 4, 16. Блок — `{0, клавиша, модификаторы}`.

    **Граница.** Клавиша, которой корпус не держит, и модификаторы, каких корпус не держит (Ctrl+Alt,
    Shift+Alt, Ctrl+Shift+Alt), — отказ, снимаемый `unverified`. ПАРА не даёт отказа (отчёт называет
    число). У стандартного действия и в меню кнопок — как у картинки. `remove=true` снимает блок
    вместе с битом 8; нулевой блок `{0,0,0}` операция не пишет.

    **Повтор** сочетания — ПРЕДУПРЕЖДЕНИЕ, не отказ. Форма ↔ панель: срабатывает кнопка, чей элемент
    находится в списке раньше (`REPEAT_FORM_PANEL`, `_form_panel_here`); внутри класса срабатывает одна
    (`REPEAT_SAME_CLASS`). `validate` говорит о том же (`form_panel_repeats`, `same_class_repeats`).
    Проверено в предприятии: сочетания у действий-процедур и у кнопки ФОРМЫ, снятие, сочетание у
    стандартного действия.
    """
    if remove == (key is not None) or (remove and modifiers is not None):
        raise EditError("сочетание называют key=<клавиша> (и modifiers=[…]) — либо remove=true, "
                        "одно из двух")
    if element is not None:
        if bar is not None or button is not None:
            raise EditError("element — кнопка ФОРМЫ, bar и button — кнопка командной панели или "
                            "меню кнопки: это разные адреса, назовите один")
        return _form_button_shortcut(doc, element, key, modifiers, remove, unverified)
    if bar is None or button is None:
        raise EditError("кнопку называют bar=<панель или кнопка-меню> и button=<имя кнопки> — "
                        "либо element=<кнопка формы>")
    action, _node, where, kind = _extras_place(doc, bar, button)
    extras = dict(action.get(EXTRAS) or {})
    old = extras.get(SHORTCUT)
    old_words = _shortcut_words(old.get(SHORTCUT_KEY), old.get(SHORTCUT_MODIFIERS)) \
        if isinstance(old, dict) and (old.get(SHORTCUT_KEY), old.get(SHORTCUT_MODIFIERS)) \
        != (0, 0) else "нулевое" if isinstance(old, dict) else None
    if remove:
        if old is None:
            return f"{bar}/{button}: блока сочетания у кнопки нет — снимать нечего"
        extras.pop(SHORTCUT)
        action[EXTRAS] = _order_extras(extras)
        said = (f"{bar}/{button}: сочетание клавиш снято — блок по биту 8 записи действия "
                f"убран (было {old_words})")
        if kind == STANDARD_KIND:
            return said + "; " + ROUND5_SHORTCUT_NOTE
        seen = CORPUS_BUTTON_WITHOUT[SHORTCUT].get((where, kind))
        return said + (_round_button(SHORTCUT, where, kind, "remove",
                                       f"кнопка вида «{kind}» без сочетания", seen,
                                       "записей этого вида без блока сочетания")
                       or _on_corpus("set_button_shortcut/remove",
                                     f"кнопка вида «{kind}» без сочетания", seen,
                                     counted="записей этого вида без блока сочетания"))
    code, mods, words = _shortcut_codes(key, modifiers, unverified)
    what = f"сочетание у кнопки вида «{kind}»" + (f" в МЕНЮ {bar!r}" if where == "меню" else "")
    bounds = _extras_bounds(SHORTCUT, where, kind, what, unverified, "key")
    extras[SHORTCUT] = {SHORTCUT_MARK: 0, SHORTCUT_KEY: code, SHORTCUT_MODIFIERS: mods}
    action[EXTRAS] = _order_extras(extras)
    shown = _shortcut_words(code, mods)
    said = (f"{bar}/{button}: сочетание клавиш → {shown} (клавиша {code}, модификаторы {mods})"
            + (f"; прежнее — {old_words}" if old_words else ""))
    pair = CORPUS_BUTTON_SHORTCUT_PAIRS.get((code, mods))
    said += (f"; {shown} встречается в записях действий образцов форм" if pair else
             f"; пары {shown} в записях действий образцов форм нет — клавиша и модификаторы "
             "порознь есть: редкость пары — выборка, а не правило")
    said += "".join(f"; {word}" for word in words)
    twins = _shortcut_twins(doc, action, (code, mods))
    if twins:
        said += f"; то же сочетание в форме уже у {', '.join(twins)}"
        if any(not twin.startswith(_FORM_SIDE) for twin in twins):  # счёт — про панель ↔ панель
            said += " — повтор двух кнопок панели в образцах форм бывает"
        said += _twin_words(twins, "панель", doc, (code, mods), f"{bar}/{button}")
    given = ROUND18_BUTTON.get((SHORTCUT, where, kind, ("key", (code, mods))))
    if given is not None and twins:  # слова — об исходе ПОВТОРА: без двойника им нечего сказать
        said += f"; {ROUND18_BUTTON_NOTE}: {given}"
    return said + (_round_button(SHORTCUT, where, kind, "key", what,
                                   CORPUS_BUTTON_SHORTCUTS.get((where, kind))) or bounds)


def _form_button_shortcut(doc, element, key, modifiers, remove, unverified):
    """Сочетание клавиш КНОПКИ ФОРМЫ: блок `Shortcut` в узле самой кнопки (`content/u1/shortcut`), теми
    же именами, что у панели (`_shortcut_codes`). Блок есть у КАЖДОЙ кнопки формы, «сочетания нет» —
    нули: `remove=true` ставит нули. Границы по виду действия нет. Пара клавиши с модификаторами — не
    отказ, а слова.
    """
    place = find_element(doc, element)
    kind = place.element.get("type")
    if kind != "Button":
        road = (" — сочетание поля ввода и поля картинки пишет set_property (name=shortcut)"
                if kind in ("TextBox", "PictureBox") else "")
        raise EditError(f"{element!r} — {kind}, а element у set_button_shortcut — КНОПКА формы "
                        f"(кнопку командной панели называют bar и button){road}")
    body = (place.element.get(CONTENT) or {}).get(FORM_BUTTON_BODY)
    old = body.get(SHORTCUT_FIELD) if isinstance(body, dict) else None
    if not isinstance(old, dict):
        raise EditError(f"у кнопки формы {element!r} блока сочетания нет, а у кнопки формы он "
                        "есть всегда — узел разобран не так, как карта ждёт; правьте JSON по адресу")
    old_pair = (old.get(SHORTCUT_KEY), old.get(SHORTCUT_MODIFIERS))
    old_words = _shortcut_words(*old_pair) if old_pair != (0, 0) else None
    variant = "set_button_shortcut/form-button"
    if remove:
        if old_words is None:
            return f"кнопка формы {element!r}: сочетания у кнопки нет (нули) — снимать нечего"
        body[SHORTCUT_FIELD] = {SHORTCUT_MARK: 0, SHORTCUT_KEY: 0, SHORTCUT_MODIFIERS: 0}
        return (f"кнопка формы {element!r}: сочетание клавиш снято — блок в узле кнопки обнулён, "
                f"как у кнопок, которым его не ставили (было {old_words}); кнопка формы без "
                f"сочетания: {ROUND16_BUTTON_NOTE}: {ROUND16_FORM_BUTTON[('remove',)]}")
    code, mods, words = _shortcut_codes(key, modifiers, unverified)
    body[SHORTCUT_FIELD] = {SHORTCUT_MARK: 0, SHORTCUT_KEY: code, SHORTCUT_MODIFIERS: mods}
    shown = _shortcut_words(code, mods)
    said = (f"кнопка формы {element!r}: сочетание клавиш → {shown} (клавиша {code}, модификаторы "
            f"{mods})" + (f"; прежнее — {old_words}" if old_words else ""))
    pair = CORPUS_FORM_BUTTON_SHORTCUT_PAIRS.get((code, mods))
    said += (f"; {shown} встречается у кнопок формы в образцах форм" if pair else
             f"; пары {shown} у кнопок формы в образцах форм нет — клавиша и модификаторы "
             "порознь есть: редкость пары — выборка, а не правило")
    said += "".join(f"; {word}" for word in words)
    twins = _shortcut_twins(doc, None, (code, mods), skip=place.element)
    if twins:
        said += (f"; то же сочетание в форме уже у {', '.join(twins)}"
                 + _twin_words(twins, "форма", doc, (code, mods), element))
    for table, note in ((ROUND16_FORM_BUTTON, ROUND16_BUTTON_NOTE),
                        (ROUND18_FORM_BUTTON, ROUND18_BUTTON_NOTE)):
        given = table.get(("key", (code, mods)))
        if given is not None and (table is ROUND16_FORM_BUTTON or twins):  # слова — об исходе повтора
            return said + f"; сочетание кнопки формы: {note}: {given}"
    return said + _on_corpus(variant, "сочетание кнопки формы",
                             CORPUS_FORM_BUTTON_SHORTCUTS["непустых"],
                             counted="кнопок формы с сочетанием")


