def _draft(op, unverified):
    """Отказ для черновика по умолчанию. Сейчас его никто не вызывает, потому что `DRAFTS` пуст. Механизм оставлен для следующего
    приёма, правило которого получено не с платформы: такой приём подключается одной строкой в `DRAFTS` и вызовом этой функции.
    """
    if unverified:
        return
    raise EditError(
        f"{op}: платформа этот приём не проверяла — {DRAFTS[op]}. Что ответит конфигуратор, неизвестно. "
        "Чтобы всё же выполнить операцию, передайте unverified=True; результат придётся проверить самостоятельно.")


