def remove_page(doc, panel, name, unverified=False):
    """Удаляет страницу панели. Страницу с элементами и единственную страницу операция не удаляет даже с `unverified`, потому что
    вместе со страницей молча пропали бы её элементы.

    Проверено в предприятии. Из трёх страниц панели с закладками «Сверху» на форме поколения 16 удалена средняя; после
    пересохранения страницы, направляющие по страницам, АктивизироватьПоУмолчанию и элементы остались как были собраны. Из трёх
    страниц панели «Не отображать» удалены первая и последняя (`REMOVE_PAGE_MEASURED`). Остальные случаи не проверялись:
    другое число страниц, средняя страница у «Не отображать», первая и последняя у «Сверху», формы поколений 13 и 15. В них
    операция отказывает, и отказ снимается ключом `unverified`.
    """
    place, block = _panel_pages(doc, panel)
    version = _design.form_version(doc)
    tabs = block.get(SHOW_TABS)

    def gate(at, count):
        wider = []
        key = (tabs, count, at)
        if key not in REMOVE_PAGE_MEASURED:
            if tabs not in ("Top", "DontUse"):
                wider.append(f"закладки панели {tabs!r}, а проверялись только панели с закладками "
                             "«Сверху» и «Не отображать»")
            else:
                wider.append(f"страница {at} из {count} (счёт с нуля) при закладках панели "
                             f"{tabs!r}, а проверялось удаление только из трёх страниц панели: у «Сверху» "
                             "средней, у «Не отображать» первой и последней страницы")
        if version != FORM_PAGE_VERSION:
            wider.append(f"форма поколения {version}, а удаление страницы панели проверялось только на "
                         f"форме поколения {FORM_PAGE_VERSION}")
        return _page_gate("remove_page", wider, unverified, REMOVE_PAGE_MEASURED.get(key))
    return f"{panel}: {_remove_page_of(place.element, block, name, repr(panel), gate)}"


def _menu_host(place, button):
    """Тело записи кнопки — узел, в котором лежит флаг режима меню. Он ищется по строению: флаг назван в карте, и в содержимом
    кнопки узел с таким ключом один (так же ищется блок действий в `_bars`).
    """
    found = []

    def walk(value, trail):
        if not isinstance(value, dict):
            return
        if MENU_MODE in value:
            found.append((trail, value))
        for key, item in value.items():
            walk(item, trail + (key,))

    walk(place.element.get(CONTENT) or {}, ())
    if not found:
        raise EditError(
            f"У элемента {button!r} ({place.element.get('type')}) режима меню нет. Режим меню бывает только у "
            "кнопки формы. У кнопки командной панели подменю устроено иначе: запись действия указывает на "
            "набор кнопок.")
    if len(found) > 1:
        where = ", ".join("/".join(trail) for trail, _node in found)
        raise EditError(f"У {button!r} несколько флагов режима меню ({where}), и карта не позволяет определить, "
                        "какой из них нужен.")
    return found[0][1]


def set_menu_mode(doc, button, mode, guid=None, set_guid=None, drop_items=False,
                  unverified=False):
    """Режим меню кнопки формы: добавляет блок меню или убирает его.

    Режим меню — это флаг строения, а не обычное значение. При значениях «Use» и «UseExtra» в теле записи кнопки лежит блок
    меню (такой же `CommandBarActions`, как у командной панели), а хвост записи сдвигается на одну позицию. Флаг без блока
    обрывает поток.

    Проверено в предприятии. Меню «Use» и «UseExtra» с пунктами-процедурами раскрывается в конструкторе и в предприятии, пункты
    срабатывают. Пустое меню конфигуратор показывает на стрелке строкой «<Новая>», а кнопка с таким меню при нажатии ничего не
    делает. Снятие режима не проверялось, отчёт сообщает об этом. Ключ `unverified` принимается, но ничего не меняет.

    Операция выполняет следующее. Она вставляет блок целиком, как копию платформы (`templates.menu()`), и выставляет два GUID
    разной природы. Голова блока у каждого меню своя: операция выдаёт её заново, либо её задаёт параметр `guid`. GUID набора
    постоянный (`schema.MENU_BUTTON_SET`), потому что со случайным GUID меню не раскрывается. Поэтому параметр `set_guid`
    допускается только с постоянным значением, иначе операция отказывает.

    На существующем меню режим «Use» или «UseExtra» дополнительно исправляет блок: набору ставится постоянный GUID, если там
    другой, а владельцы пунктов приводятся к голове меню. Отчёт называет, что было исправлено (`_mend_menu`). Проверка
    `validate` на первом уровне отвергает такие формы и направляет сюда. Параметр `guid` (голова) на существующем меню должен
    совпадать с прежним, иначе операция отказывает: новую голову операция выдаёт только новому меню.

    Хвост кнопки операция не меняет. В документе он называется по именам (`L1+0`, `L1+1`, `L1+2`, `layout_state`) в обоих
    строениях, а сдвиг позиций выполняется при сборке. У кнопок-меню хвост такой же, как у обычных. Утверждение «производное
    2/1/15 при меню равно нулю» верно только для сырого дерева, где нулём становится `L1+2`.

    Кнопки в меню добавляют и изменяют обычные операции: `add_button`, `remove_button`, `set_button_text`, `set_button_action`,
    `set_tool_tip`, `set_description`. Меню они находят по строению и по имени самой кнопки-меню.

    Параметр `drop_items=True` нужен, чтобы снять режим у меню с кнопками. Без него операция отказывает, потому что иначе кнопки
    были бы удалены молча.
    """
    if set_guid is not None and set_guid != MENU_SET_GUID:
        raise EditError(
            f"set_guid: GUID набора кнопок меню выбирать нельзя, он постоянный: {MENU_SET_GUID}. С другим "
            "GUID платформа открывает и сохраняет форму, но меню в предприятии не раскрывается. Уберите "
            "параметр: операция сама поставит постоянный GUID.")
    if mode not in MENU_MODES:
        raise EditError(f"режима меню {mode!r} карта не знает; есть {', '.join(MENU_MODES)} "
                        f"(с блоком меню — {', '.join(MENU_WITH)}, без него — "
                        f"{', '.join(MENU_WITHOUT)})")
    place = find_element(doc, button)
    body = _menu_host(place, button)
    was, block = body.get(MENU_MODE), body.get(MENU)
    if mode in MENU_WITH:
        if isinstance(block, dict):
            head = (block.get(ACTIONS_GUID) or {}).get("guid") \
                if isinstance(block.get(ACTIONS_GUID), dict) else None
            if guid is not None and guid != head:
                raise EditError(
                    f"guid: у кнопки {button!r} меню уже есть, и голова у него {head}. Голову "
                    "операция выдаёт только НОВОМУ меню, а у существующего её не меняет: на неё "
                    "ссылаются владельцы пунктов. Уберите параметр")
            body[MENU_MODE] = mode
            said = (f"{button}: режим меню {was} → {mode}, меню на месте "
                    f"(кнопок {len(_buttons(block))})")
            return said + "".join(f"; {fix}" for fix in _mend_menu(block, head))
        from .. import templates
        block = templates.menu()
        block[ACTIONS_GUID] = {"guid": guid or str(uuid.uuid4())}
        for item in block[BUTTON_SETS]:
            item[SET_REF] = {"guid": MENU_SET_GUID}
        body[MENU_MODE] = mode
        _put_after(body, MENU, block, MENU_MODE)
        return (f"{button}: режим меню {was} → {mode}, заведено пустое меню (голова "
                f"{block[ACTIONS_GUID]['guid']}, набор — постоянный {MENU_SET_GUID}); хвост "
                "записи не тронут. " + EMPTY_MENU_NOTE)
    if not isinstance(block, dict):
        body[MENU_MODE] = mode
        return f"{button}: режим меню {was} → {mode}, меню и не было"
    held = [node.get(BTN_NAME) for _set, node in _buttons(block)]
    if held and not drop_items:
        raise EditError(
            f"в меню кнопки {button!r} лежат кнопки: {', '.join(map(str, held))}. Снять режим "
            "значит унести блок вместе с ними, а вместе с ними уйдут и их записи действий — то "
            "есть удалить их молча. Уберите их сами (remove_button) либо скажите "
            "drop_items=True")
    body.pop(MENU)
    body[MENU_MODE] = mode
    said = f"{button}: режим меню {was} → {mode}, меню убрано"
    said += f" вместе с кнопками: {', '.join(map(str, held))}" if held else " (пустое)"
    return said + _on_corpus("set_menu_mode/off", "меню снято",
                             CORPUS_BUTTONS - CORPUS_MENUS[0], counted="кнопок формы без меню")


def _mend_menu(block, head):
    """Исправляет набор существующего меню (постоянный GUID) и владельцев пунктов (голова меню). Возвращает список фраз отчёта.

    Проверка `validate` на первом уровне отвергает меню со случайным GUID набора. `set_menu_mode` с режимом меню на такой
    кнопке ставит постоянный GUID и сообщает, какой GUID был.

    Ссылки действий этого блока на прежнюю пару набора («GUID и код») переписываются вместе с набором, потому что набор
    адресуется именно парой. Отчёт называет эти ссылки, только если они были.

    Исправление владельца — это выравнивание, а не починка: у кнопок владельцем служит голова их блока, но на раскрытие меню
    это не влияет.

    Если набор уже постоянный и владельцы правильные, список пуст, и отчёт остаётся прежним.

    Меню с несколькими наборами в образцах не встречается и может появиться только после ручной правки. Операция исправляет
    каждый набор, но в итоге прямо сообщает, что наборов больше одного и что при двух наборах одного кода оба получили одну пару,
    поэтому ссылки на них неразличимы (`validate` предупреждает об этом же). Объединять наборы операция не берётся.
    """
    said = []
    for item in block.get(BUTTON_SETS) or []:
        if not isinstance(item, dict):
            continue
        ref = item.get(SET_REF)
        old = ref.get("guid") if isinstance(ref, dict) else None
        if old == MENU_SET_GUID:
            continue
        item[SET_REF] = {"guid": MENU_SET_GUID}
        moved = _move_set_refs(block, (old, item.get(SET_CODE)), MENU_SET_GUID)
        said.append(
            f"GUID набора кнопок меню был {old or 'пуст'}, поставлен постоянный "
            f"{MENU_SET_GUID} (ButtonSet.MenuButtons, он одинаков у всех меню образцов форм). Со случайным GUID набора платформа открывает и "
            "сохраняет форму, но меню в 1С:Предприятии не раскрывается, а с постоянным раскрывается"
            + (f"; ссылок действий на прежний набор переписано {moved}" if moved else ""))
    sets = [item for item in block.get(BUTTON_SETS) or [] if isinstance(item, dict)]
    if said and len(sets) != 1:
        codes = collections.Counter(item.get(SET_CODE) for item in sets)
        twins = sorted(code for code, n in codes.items() if n > 1)
        said.append(
            f"У меню наборов кнопок {len(sets)}, а у меню образцов форм набор один. Как работает "
            "меню после исправления при нескольких наборах, не проверялось"
            + (f"; наборам одного кода ({', '.join(map(str, twins))}) досталась одна пара "
               f"«{MENU_SET_GUID}, код» — ссылки на них неразличимы; лишний набор уберите руками"
               if twins else ""))
    if not isinstance(head, str):
        return said
    foreign = {}
    for _set, node in _buttons(block):
        owner = node.get(BTN_OWNER)
        owner = owner.get("guid") if isinstance(owner, dict) else None
        if owner != head:
            foreign.setdefault(owner, []).append(str(node.get(BTN_NAME)))
            node[BTN_OWNER] = {"guid": head}
    for owner, names in foreign.items():
        said.append(
            f"Владелец у {', '.join(names)} был {owner or 'пуст'}, поставлена голова меню "
            f"{head}. Это выравнивание по образцам форм, а не исправление: владельцем кнопки служит "
            "голова её блока, но на раскрытие меню владелец не влияет")
    return said


def _move_set_refs(block, pair, guid):
    """Переписывает ссылки действий блока с набора `pair` на тот же код с GUID `guid` и возвращает число переписанных ссылок. Обход
    описаний идёт на любой глубине, как в проверке (`validate._refs_in`): у трёх видов описания ссылка лежит на разных уровнях.
    """
    moved = 0

    def walk(value):
        nonlocal moved
        if isinstance(value, dict):
            ref = value.get(REF_ID)
            if isinstance(ref, dict) and (ref.get("guid"), value.get(REF_CODE)) == pair:
                value[REF_ID] = {"guid": guid}
                moved += 1
            for item in value.values():
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)

    for action in block.get(ACTIONS) or []:
        if isinstance(action, dict):
            walk(action.get(ACT_SPEC))
    return moved


