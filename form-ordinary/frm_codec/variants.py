"""Элементы на одном месте, из которых код показывает один: варианты, названные в разборе кода (`exclusive_group`, `brief.codenotes`).

Так делают две командные панели списка, видимые по роли пользователя, или два поля на одном месте. В файле все они видимы и стоят друг на друге, а на экране остаётся один.
Рисунок формы и досье называют такие элементы вариантами: рисуется один — у которого запись разбора назвала `default: true`, иначе первый по списку элементов из видимых
в файле; остальные названы пометкой.

Группу называет разбор кода, а не совпадение мест: код читает модель, и что варианты взаимоисключающие, решает она. Здесь группа проверяется только тем, что её члены —
элементы одного родителя и одной страницы."""

VISIBILITY = "видимость"


def groups(entries, marks):
    """Группы вариантов: `[[элемент, …]]` в порядке списка, у каждой группы не меньше двух элементов одного родителя и одной страницы.

    `entries` — `[(элемент, место)]` одного родителя в порядке списка элементов; `marks` — пометки кода (`render.CodeMarks`) с `groups`: `{группа: [индексы элементов]}`."""
    out = []
    for indexes in getattr(marks, "groups", {}).values():
        mine = [it for it, _box in entries if it.index in indexes]
        by_page = {}
        for it in mine:
            by_page.setdefault(it.page or 0, []).append(it)
        out += [members for members in by_page.values() if len(members) > 1]
    return out


def drawn(members, hidden=lambda item: False, defaults=()):
    """Элемент группы, который рисуется: из видимых в файле и не скрытых другим способом (`hidden(элемент)`) — названный по умолчанию (`defaults` — индексы),
    иначе первый по списку; `None`, если рисовать нечего."""
    shown = [m for m in members if m.visible and not hidden(m)]
    return next((m for m in shown if m.index in defaults), shown[0] if shown else None)
