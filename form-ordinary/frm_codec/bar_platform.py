@contextlib.contextmanager
def context(kind=None, posting=None, groups=None, tables=None, role=None):
    """На время блока: вид формы (`census`: `document.item`, `document.list`, …) и проведение документа (`True`/`False`/`None` — неизвестно), есть ли у справочника группы (`groups`, так же),
    роль формы регистра (`role`: `record` — запись, `list` — список), вид данных табличных полей формы (`tables`: номер элемента → «табличная часть», «список», «таблица значений», «список значений»; `None` — не известен)."""
    before = _context[0]
    _context[0] = {"kind": kind, "posting": posting, "groups": groups, "tables": tables, "role": role}
    try:
        yield
    finally:
        _context[0] = before


def set_context(**kwargs):
    """Дополняет действующий контекст (`context`): вид формы и проведение становятся известны не сразу. Вне блока `context` — ничего не делает."""
    if _context[0] is not None:
        _context[0].update(kwargs)


def current():
    return _context[0] or {}


def action_text(code):
    """Текст стандартного действия, который показывает платформа, либо `None` (у кода текста в снимках нет)."""
    return ACTION_TEXT.get(code)


def menu_text(pair):
    """Название стандартного меню по паре «GUID набора, код» либо `None`."""
    return STANDARD_MENUS.get(tuple(pair)) if pair else None


def menu_items(kind, groups=None, source_is_table=False, table_kind=None, saved=False, main=True, bottom=False):
    """Пункты меню «Действия» панели с автозаполнением (слова, для досье) либо `None`. У панели таблицы — по виду данных таблицы (`table_kind`): известен у списка."""
    if source_is_table:
        return MENU_ITEMS["table.list"] if table_kind == TABLE_LIST_KIND else None
    if kind in (None, "processing") and not main:
        return None                       # у формы без основного реквизита вида обработки меню «Действия» нет
    if bottom and kind != "document.item":
        return None
    if kind == "processing" and saved:
        return "Восстановить значения…; Сохранить значения…; разделитель; Закрыть"
    if kind in ("processing", "document.item", "document.list", "catalog.item"):
        return MENU_ITEMS[kind]
    if kind == JOURNAL_KIND:
        return MENU_ITEMS["journal"]
    if kind == INFOREG_KIND and current().get("role") in ("record", "list"):
        return MENU_ITEMS["register." + current()["role"]]
    if kind == "catalog.list":
        return MENU_ITEMS["catalog.flat" if groups is False else "catalog.groups"]
    return None


def is_goto(pair):
    return tuple(pair or ()) == (GUID_GOTO, 6)


def fill(source_is_table, kind=None, posting=None, groups=None, table_kind=None, saved=False, bottom=False, main=True):
    """Состав панели с автозаполнением: `(голова, хвост, слова, источник)`. Голова ставится до кнопок файла, хвост — после «Перейти» (если оно есть в файле) либо
    сразу за головой; `слова` — что в составе неизвестно: `None` — состав наблюдался целиком; `источник` — по какому наблюдению в предприятии состав (слова, без кодов).
    Состав, которого наблюдение не дало, — `([], [], слова, None)`. У панели таблицы состав зависит от вида данных таблицы (`table_kind`): табличная часть, список;
    вид не известен или иной — набор табличной части со словами.

    Порядок «кнопки файла ↔ значки платформы» известен не полностью: у списка «Номенклатура» «обновить» стоит до «Перейти», у списка перемещений — после;
    рендер ставит голову, затем кнопки файла, затем хвост."""
    if not source_is_table and kind in (None, "processing") and not main:
        return [], [("sep", ""), HELP], NO_MAIN_WORDS, "форма обработки без основного реквизита"
    if bottom and not source_is_table and kind != "document.item":
        return [], [], BOTTOM_WORDS, None
    if source_is_table:
        if table_kind == TABLE_LIST_KIND:
            return list(TABLE_LIST), [], TABLE_LIST_WORDS, "список подчинённого справочника в форме элемента"
        if table_kind == TABLE_PART:
            return list(TABLE), [], TABLE_PART_WORDS, "табличная часть документа и элемента справочника"
        if table_kind == TABLE_VALUES:
            return list(TABLE), [], TABLE_PART_WORDS, "таблица значений формы обработки"
        return list(TABLE), [], TABLE_OTHER_WORDS, "табличная часть документа и дерево обработки"
    if kind in ("document.item", "catalog.item"):
        head = list(DOC_HEAD) + (list(DOC_POSTING) if kind == "document.item" and posting is True else [])
        if kind == "catalog.item":
            return head, [("sep", ""), HELP], "наблюдалась одна форма элемента иерархического справочника; у справочника с иным составом панели набор мог отличаться", \
                "форма элемента справочника"
        words = None if posting is not None else "проведение документа неизвестно (нужна выгрузка конфигурации): «Провести» и «Отмена проведения» в состав не включены"
        return head, [("sep", ""), HELP], words, "форма документа"
    if kind == "document.list":
        return list(DOC_LIST_HEAD), list(DOC_LIST_TAIL), None, "список документов"
    if kind == JOURNAL_KIND:
        return list(JOURNAL_HEAD), list(DOC_LIST_TAIL), "наблюдался один журнал; «Перейти» стоит в файле", "журнал документов"
    if kind == INFOREG_KIND and current().get("role") == "record":
        return list(DOC_HEAD), [("sep", ""), HELP], "наблюдалась одна форма записи регистра сведений", "форма записи регистра сведений"
    if kind == INFOREG_KIND and current().get("role") == "list":
        return list(REGISTER_LIST_HEAD), list(DOC_LIST_TAIL[1:]), "наблюдался один список регистра сведений", "список регистра сведений"
    if kind == "catalog.list":
        if groups is False:
            return (list(CATALOG_FLAT_HEAD), list(CATALOG_TAIL), "наблюдался один неиерархический справочник без формы элемента (правка в строке списка); "
                    "у списка с формой элемента состав мог отличаться", "список неиерархического справочника")
        words = ("иерархичность справочника неизвестна (нужна выгрузка конфигурации): состав — по списку с группами; у неиерархического он короче" if groups is None else None)
        words = (words + "; " if words else "") + ("«Выбрать» платформа не ставит: она есть на панели, только если записана в файле формы (стандартное действие «Выбрать»), и рисуется как кнопка файла, "
                                                  "серая, когда список открыт не для выбора; у формы выбора она активна — по назначению, наблюдения нет")
        return list(CATALOG_GROUPS_HEAD), list(CATALOG_TAIL), words, "список справочника с группами"
    if kind == "processing" and saved:
        return (list(PROCESSING_VALUES_HEAD), list(PROCESSING_VALUES_TAIL), "наблюдалась одна обработка с сохраняемыми значениями", "форма обработки с сохраняемыми значениями")
    if kind == "processing":
        return (list(PROCESSING_HEAD), [], "наблюдались две обработки с основным реквизитом — объектом обработки («Дерево составляющих», заготовка без кнопок): «Действия ▾» и «?»; кнопки «Восстановить/Сохранить настройку…» у первой — кнопки файла формы", "форма обработки")
    return [], [], "состав ставит платформа: у этого вида формы автозаполнение в предприятии не наблюдалось", None
